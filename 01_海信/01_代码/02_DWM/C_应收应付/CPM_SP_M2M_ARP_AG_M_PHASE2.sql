     WHERE A.COD_SCENARIO = V_SCENARIO
       AND A.COD_PERIODO = V_PERIODO
       AND A.COD_AZIENDA IN (
             SELECT ELEM
               FROM SESSION_AZIENDA_LIST
              WHERE SESSION_ID = V_SESSION_ID
       )
  ),
  -- 取当前期间每个业务键的维度基准行，ORG来源优先，其他来源作为兜底。
  CURRENT_DIM_RN AS (
    SELECT S.*
         , ROW_NUMBER() OVER (
               PARTITION BY S.COD_AZIENDA
                          , S.COD_CONTO
                          , S.CUST_CODE
                          , S.COD_DEST2
               ORDER BY CASE WHEN S.SRC_DETAIL LIKE 'ORG%' THEN 1 ELSE 2 END
                      , S.OID
           ) AS RN
      FROM CURRENT_SOURCE S
  ),
  CURRENT_DIM AS (
    SELECT COD_AZIENDA
         , COD_CONTO
         , COD_CATEGORIA
         , CUST_CODE
         , CUST_NAME
         , CUST_HEAD_CODE
         , CUST_HEAD_NAME
         , CUST_BRANCH_CODE
         , CUST_BRANCH_NAME
         , COD_AZI_CTP
         , COUNTRY_CODE
         , COUNTRY_NAME
         , ACCT_SRC_CODE
         , LE_AGE_FLAG
         , IS_REC_LG
         , ME_AGE_FLAG
         , IS_REC_ME
         , MB_AGE_FLAG
         , IS_REC_MB
         , GRP_SCOPE
         , NATURE_L1_NAME
         , NATURE_L2_NAME
         , NATURE_L3_NAME
         , D_CHANNEL
         , D_ONOFFLINE
         , COD_DEST2
         , COD_DEST3
         , D_SALE_DEPT
         , TAX_RATE
         , COD_VALUTA
         , COD_VALUTA_ORIGINARIA
         , PAY_TERM_CODE
         , PAY_TERM_DESC
         , EXCHANGE_RATE_EVAL_FLAG
      FROM CURRENT_DIM_RN
     WHERE RN = 1
  ),
  -- 当前期间按来源类别汇总，用于生成结果表的横向金额字段。
