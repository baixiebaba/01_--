    6. 非2023公司取DATI_CAMBIO.CAMBIO_FINALE；公司2023取SAP TCURR汇率。

  版本信息：最新修改记录放最上面
    20260922 SHIQINGFENG.EX 新增ARPM02账龄结果表过程

  手工执行：CALL CPM_SP_M2M_ARP_AG_M_PHASE2('2025ACT','06','6700','USER');
  **************************************************************************/
