         , NVL(A.QCY_5_AMT, 0) AS QCY_5_AMT
         , NVL(A.QCY_6_AMT, 0) AS QCY_6_AMT
         , NVL(A.QCY_7_AMT, 0) AS QCY_7_AMT
         , NVL(A.QCY_8_AMT, 0) AS QCY_8_AMT
         , NVL(A.QCY_9_AMT, 0) AS QCY_9_AMT
