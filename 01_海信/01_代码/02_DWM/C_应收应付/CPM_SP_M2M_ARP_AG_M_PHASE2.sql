    , BCY_ADJ_INCL_8_AMT
    , BCY_ADJ_INCL_9_AMT
    , BCY_ADJ_INCL_10_AMT
    , BCY_ADJ_INCL_11_AMT
    , BCY_ADJ_INCL_12_AMT
    , BCY_ADJ_INCL_13_AMT
    , BCY_ADJ_INCL_14_AMT
    , BCY_ADJ_INCL_15_AMT
    , BCY_ADJ_EXCL_0_AMT
    , overdue_0_amt
    , overdue_1_amt
