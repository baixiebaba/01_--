    END IF;

    -- 10个固定筛选槽位；全部规则均通过APPEND_FILTER绑定。
    APPEND_FILTER(R.COLUMN_NAME_1, R.COLUMN_FILTER_1, R.COLUMN_VALUE_1, 1);
    APPEND_FILTER(R.COLUMN_NAME_2, R.COLUMN_FILTER_2, R.COLUMN_VALUE_2, 2);
    APPEND_FILTER(R.COLUMN_NAME_3, R.COLUMN_FILTER_3, R.COLUMN_VALUE_3, 3);
    APPEND_FILTER(R.COLUMN_NAME_4, R.COLUMN_FILTER_4, R.COLUMN_VALUE_4, 4);
    APPEND_FILTER(R.COLUMN_NAME_5, R.COLUMN_FILTER_5, R.COLUMN_VALUE_5, 5);
    APPEND_FILTER(R.COLUMN_NAME_6, R.COLUMN_FILTER_6, R.COLUMN_VALUE_6, 6);
    APPEND_FILTER(R.COLUMN_NAME_7, R.COLUMN_FILTER_7, R.COLUMN_VALUE_7, 7);
    APPEND_FILTER(R.COLUMN_NAME_8, R.COLUMN_FILTER_8, R.COLUMN_VALUE_8, 8);
    APPEND_FILTER(R.COLUMN_NAME_9, R.COLUMN_FILTER_9, R.COLUMN_VALUE_9, 9);
    APPEND_FILTER(R.COLUMN_NAME_10, R.COLUMN_FILTER_10, R.COLUMN_VALUE_10, 10);
    V_SQL := V_SQL || CHR(10) || 'GROUP BY S.COD_CATEGORIA, S.COD_VALUTA';

    V_CURSOR := DBMS_SQL.OPEN_CURSOR;
    DBMS_SQL.PARSE(V_CURSOR, V_SQL, DBMS_SQL.NATIVE);
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_SESSION_ID', V_SESSION_ID);
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_RUN_ID', V_RUN_ID);
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_TARGET_OWNER', V_TARGET_OWNER);
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_TARGET_TABLE', V_TARGET_NAME);
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_SCENARIO', V_SCENARIO);
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_PERIODO', V_PERIODO);
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_D_BG', DIM_VALUE(R.D_BG, 'D_BG'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_COD_CONTO', DIM_VALUE(R.COD_CONTO, 'COD_CONTO'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_COD_AZIENDA', DIM_VALUE(R.COD_AZIENDA, 'COD_AZIENDA'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_D_GRAN_CAL', DIM_VALUE(R.D_GRAN_CAL, 'D_GRAN_CAL'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_D_CHANNEL', DIM_VALUE(R.D_CHANNEL, 'D_CHANNEL'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_D_ONOFFLINE', DIM_VALUE(R.D_ONOFFLINE, 'D_ONOFFLINE'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_COD_DEST2', DIM_VALUE(R.COD_DEST2, 'COD_DEST2'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_COD_DEST3', DIM_VALUE(R.COD_DEST3, 'COD_DEST3'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_D_SALE_DEPT', DIM_VALUE(R.D_SALE_DEPT, 'D_SALE_DEPT'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_D_TOV_CHAN', DIM_VALUE(R.D_TOV_CHAN, 'D_TOV_CHAN'));
    DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':B_D_CC_CUSTGRP', DIM_VALUE(R.D_CC_CUSTGRP, 'D_CC_CUSTGRP'));
    FOR I IN 1 .. V_BIND_COUNT LOOP
      DBMS_SQL.BIND_VARIABLE(V_CURSOR, ':' || V_BINDS(I).NAME, V_BINDS(I).VALUE);
    END LOOP;
    V_EXEC_RESULT := DBMS_SQL.EXECUTE(V_CURSOR);
    CLOSE_CURSOR;
  END LOOP;
  WRITE_LOG('来源暂存完成', 'RUN_ID=' || V_RUN_ID || ';SCOPE_COUNT=' || V_SCOPE_COUNT);

  IF V_SCOPE_COUNT = 0 THEN
    -- 无适用配置不删除目标；只清理本次运行的会话数据。
    DELETE FROM SESSION_TOVCAL_RESULT WHERE SESSION_ID = V_SESSION_ID AND RUN_ID = V_RUN_ID;
    DELETE FROM SESSION_TOVCAL_SCOPE WHERE SESSION_ID = V_SESSION_ID AND RUN_ID = V_RUN_ID;
    DELETE FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID;
    DELETE FROM SESSION_V_REF_AZIENDA WHERE SESSION_ID = V_SESSION_ID;
    WRITE_LOG('END 无适用配置', 'RUN_ID=' || V_RUN_ID);
    COMMIT;
    RELEASE_LOCK(V_TARGET_HANDLE);
    RELEASE_LOCK(V_SESSION_HANDLE);
    RETURN;
  END IF;

  -- 所有来源已暂存后才删除目标；SOURCE_TABLE=TARGET_TABLE不会自读自插重复。
  V_STAGE := '目标范围删除';
  V_SQL := TO_CLOB('DELETE FROM ' || V_TARGET_OBJECT || ' D WHERE D.COD_SCENARIO = :B_SCENARIO'
    || ' AND D.COD_PERIODO = :B_PERIODO AND EXISTS ('
    || 'SELECT 1 FROM SESSION_TOVCAL_SCOPE X WHERE X.SESSION_ID = :B_SESSION_ID AND X.RUN_ID = :B_RUN_ID'
    || ' AND X.TARGET_OWNER = :B_TARGET_OWNER AND X.TARGET_TABLE = :B_TARGET_TABLE'
    || ' AND X.COD_SCENARIO = D.COD_SCENARIO AND X.COD_PERIODO = D.COD_PERIODO'
    || ' AND NVL(NULLIF(TRIM(D.D_BG), ''''), ''ZZZZ'') = X.D_BG'
    || ' AND NVL(NULLIF(TRIM(D.COD_CONTO), ''''), ''ZZZZ'') = X.COD_CONTO'
    || ' AND NVL(NULLIF(TRIM(D.COD_AZIENDA), ''''), ''ZZZZ'') = X.COD_AZIENDA'
    || ' AND NVL(NULLIF(TRIM(D.D_GRAN_CAL), ''''), ''ZZZZ'') = X.D_GRAN_CAL'
    || ' AND NVL(NULLIF(TRIM(D.D_CHANNEL), ''''), ''ZZZZ'') = X.D_CHANNEL'
    || ' AND NVL(NULLIF(TRIM(D.D_ONOFFLINE), ''''), ''ZZZZ'') = X.D_ONOFFLINE'
    || ' AND NVL(NULLIF(TRIM(D.COD_DEST2), ''''), ''ZZZZ'') = X.COD_DEST2'
    || ' AND NVL(NULLIF(TRIM(D.COD_DEST3), ''''), ''ZZZZ'') = X.COD_DEST3'
    || ' AND NVL(NULLIF(TRIM(D.D_SALE_DEPT), ''''), ''ZZZZ'') = X.D_SALE_DEPT'
    || ' AND NVL(NULLIF(TRIM(D.D_TOV_CHAN), ''''), ''ZZZZ'') = X.D_TOV_CHAN'
    || ' AND NVL(NULLIF(TRIM(D.D_CC_CUSTGRP), ''''), ''ZZZZ'') = X.D_CC_CUSTGRP)');
  EXECUTE IMMEDIATE V_SQL USING V_SCENARIO, V_PERIODO, V_SESSION_ID, V_RUN_ID, V_TARGET_OWNER, V_TARGET_NAME;
  WRITE_LOG('目标范围删除完成', 'RUN_ID=' || V_RUN_ID);

  -- 最终按目标维度、类别、币种聚合18个金额，再计算6个周转天数。
  -- 最终金额聚合CTE：按目标维度、类别和币种汇总18个金额后再计算周转天数。
  V_SQL := TO_CLOB('INSERT INTO ' || V_TARGET_OBJECT || '('
    || 'COD_SCENARIO, COD_PERIODO, D_BG, COD_CONTO, COD_AZIENDA, D_GRAN_CAL, COD_CATEGORIA'
    || ', D_CHANNEL, D_ONOFFLINE, COD_DEST2, COD_DEST3, D_SALE_DEPT, D_TOV_CHAN, D_CC_CUSTGRP, COD_VALUTA'
    || ', PLN_BEG_OCP_AMT, PLN_LM_OCP_AMT, PLN_END_OCP_AMT, PLN_YTD_OCP_AMT, PLN_MTD_CSM_AMT, PLN_YTD_CSM_AMT'
    || ', ACT_BEG_OCP_AMT, ACT_LM_OCP_AMT, ACT_END_OCP_AMT, ACT_YTD_OCP_AMT, ACT_MTD_CSM_AMT, ACT_YTD_CSM_AMT'
    || ', LY_BEG_OCP_AMT, LY_LM_OCP_AMT, LY_END_OCP_AMT, LY_YTD_OCP_AMT, LY_MTD_CSM_AMT, LY_YTD_CSM_AMT'
    || ', PLN_MTD_TDAYS, PLN_YTD_TDAYS, ACT_MTD_TDAYS, ACT_YTD_TDAYS, LY_MTD_TDAYS, LY_YTD_TDAYS)'
    || CHR(10) || 'WITH AGG AS ('
    || CHR(10) || 'SELECT COD_SCENARIO, COD_PERIODO, D_BG, COD_CONTO, COD_AZIENDA, D_GRAN_CAL, COD_CATEGORIA'
    || ', D_CHANNEL, D_ONOFFLINE, COD_DEST2, COD_DEST3, D_SALE_DEPT, D_TOV_CHAN, D_CC_CUSTGRP, COD_VALUTA'
    || ', SUM(NVL(PLN_BEG_OCP_AMT, 0)) AS PLN_BEG_OCP_AMT, SUM(NVL(PLN_LM_OCP_AMT, 0)) AS PLN_LM_OCP_AMT'
    || ', SUM(NVL(PLN_END_OCP_AMT, 0)) AS PLN_END_OCP_AMT, SUM(NVL(PLN_YTD_OCP_AMT, 0)) AS PLN_YTD_OCP_AMT'
    || ', SUM(NVL(PLN_MTD_CSM_AMT, 0)) AS PLN_MTD_CSM_AMT, SUM(NVL(PLN_YTD_CSM_AMT, 0)) AS PLN_YTD_CSM_AMT'
    || ', SUM(NVL(ACT_BEG_OCP_AMT, 0)) AS ACT_BEG_OCP_AMT, SUM(NVL(ACT_LM_OCP_AMT, 0)) AS ACT_LM_OCP_AMT'
    || ', SUM(NVL(ACT_END_OCP_AMT, 0)) AS ACT_END_OCP_AMT, SUM(NVL(ACT_YTD_OCP_AMT, 0)) AS ACT_YTD_OCP_AMT'
    || ', SUM(NVL(ACT_MTD_CSM_AMT, 0)) AS ACT_MTD_CSM_AMT, SUM(NVL(ACT_YTD_CSM_AMT, 0)) AS ACT_YTD_CSM_AMT'
    || ', SUM(NVL(LY_BEG_OCP_AMT, 0)) AS LY_BEG_OCP_AMT, SUM(NVL(LY_LM_OCP_AMT, 0)) AS LY_LM_OCP_AMT'
    || ', SUM(NVL(LY_END_OCP_AMT, 0)) AS LY_END_OCP_AMT, SUM(NVL(LY_YTD_OCP_AMT, 0)) AS LY_YTD_OCP_AMT'
    || ', SUM(NVL(LY_MTD_CSM_AMT, 0)) AS LY_MTD_CSM_AMT, SUM(NVL(LY_YTD_CSM_AMT, 0)) AS LY_YTD_CSM_AMT'
    || CHR(10) || 'FROM SESSION_TOVCAL_RESULT'
    || CHR(10) || 'WHERE SESSION_ID = :B_SESSION_ID AND RUN_ID = :B_RUN_ID'
    || ' AND TARGET_OWNER = :B_TARGET_OWNER AND TARGET_TABLE = :B_TARGET_TABLE'
    || CHR(10) || 'GROUP BY COD_SCENARIO, COD_PERIODO, D_BG, COD_CONTO, COD_AZIENDA, D_GRAN_CAL, COD_CATEGORIA'
    || ', D_CHANNEL, D_ONOFFLINE, COD_DEST2, COD_DEST3, D_SALE_DEPT, D_TOV_CHAN, D_CC_CUSTGRP, COD_VALUTA)'
    || CHR(10) || 'SELECT COD_SCENARIO, COD_PERIODO, D_BG, COD_CONTO, COD_AZIENDA, D_GRAN_CAL, COD_CATEGORIA'
    || ', D_CHANNEL, D_ONOFFLINE, COD_DEST2, COD_DEST3, D_SALE_DEPT, D_TOV_CHAN, D_CC_CUSTGRP, COD_VALUTA'
    || ', PLN_BEG_OCP_AMT, PLN_LM_OCP_AMT, PLN_END_OCP_AMT, PLN_YTD_OCP_AMT, PLN_MTD_CSM_AMT, PLN_YTD_CSM_AMT'
    || ', ACT_BEG_OCP_AMT, ACT_LM_OCP_AMT, ACT_END_OCP_AMT, ACT_YTD_OCP_AMT, ACT_MTD_CSM_AMT, ACT_YTD_CSM_AMT'
    || ', LY_BEG_OCP_AMT, LY_LM_OCP_AMT, LY_END_OCP_AMT, LY_YTD_OCP_AMT, LY_MTD_CSM_AMT, LY_YTD_CSM_AMT'
    || ', CASE WHEN PLN_MTD_CSM_AMT = 0 THEN NULL ELSE ((PLN_LM_OCP_AMT + PLN_END_OCP_AMT) / 2 * 30) / PLN_MTD_CSM_AMT END AS PLN_MTD_TDAYS'
    || ', CASE WHEN PLN_YTD_CSM_AMT = 0 THEN NULL ELSE ((PLN_BEG_OCP_AMT / 2 + PLN_YTD_OCP_AMT - PLN_END_OCP_AMT / 2) * 30) / PLN_YTD_CSM_AMT END AS PLN_YTD_TDAYS'
    || ', CASE WHEN ACT_MTD_CSM_AMT = 0 THEN NULL ELSE ((ACT_LM_OCP_AMT + ACT_END_OCP_AMT) / 2 * 30) / ACT_MTD_CSM_AMT END AS ACT_MTD_TDAYS'
    || ', CASE WHEN ACT_YTD_CSM_AMT = 0 THEN NULL ELSE ((ACT_BEG_OCP_AMT / 2 + ACT_YTD_OCP_AMT - ACT_END_OCP_AMT / 2) * 30) / ACT_YTD_CSM_AMT END AS ACT_YTD_TDAYS'
    || ', CASE WHEN LY_MTD_CSM_AMT = 0 THEN NULL ELSE ((LY_LM_OCP_AMT + LY_END_OCP_AMT) / 2 * 30) / LY_MTD_CSM_AMT END AS LY_MTD_TDAYS'
    || ', CASE WHEN LY_YTD_CSM_AMT = 0 THEN NULL ELSE ((LY_BEG_OCP_AMT / 2 + LY_YTD_OCP_AMT - LY_END_OCP_AMT / 2) * 30) / LY_YTD_CSM_AMT END AS LY_YTD_TDAYS'
    || CHR(10) || 'FROM AGG');
  EXECUTE IMMEDIATE V_SQL USING V_SESSION_ID, V_RUN_ID, V_TARGET_OWNER, V_TARGET_NAME;
  WRITE_LOG('目标表装载完成', 'RUN_ID=' || V_RUN_ID);

  DELETE FROM SESSION_TOVCAL_RESULT WHERE SESSION_ID = V_SESSION_ID AND RUN_ID = V_RUN_ID;
  DELETE FROM SESSION_TOVCAL_SCOPE WHERE SESSION_ID = V_SESSION_ID AND RUN_ID = V_RUN_ID;
  DELETE FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID;
  DELETE FROM SESSION_V_REF_AZIENDA WHERE SESSION_ID = V_SESSION_ID;
  WRITE_LOG('END 执行完成', 'RUN_ID=' || V_RUN_ID);
  COMMIT;
  RELEASE_LOCK(V_TARGET_HANDLE);
  RELEASE_LOCK(V_SESSION_HANDLE);

EXCEPTION
  WHEN OTHERS THEN
    V_ERROR_COD := SQLCODE;
    V_ERROR_MSG := SUBSTR(SQLERRM, 1, 3500);
    V_ERROR_STAGE := V_STAGE;
    CLOSE_CURSOR;
    ROLLBACK;
    BEGIN
      DELETE FROM SESSION_TOVCAL_RESULT WHERE SESSION_ID = V_SESSION_ID AND RUN_ID = V_RUN_ID;
      DELETE FROM SESSION_TOVCAL_SCOPE WHERE SESSION_ID = V_SESSION_ID AND RUN_ID = V_RUN_ID;
      DELETE FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID;
      DELETE FROM SESSION_V_REF_AZIENDA WHERE SESSION_ID = V_SESSION_ID;
      COMMIT;
    EXCEPTION
      WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('CPM清理失败：' || SUBSTR(SQLERRM, 1, 1000));
    END;
    WRITE_LOG('ERROR 执行报错', 'RUN_ID=' || V_RUN_ID || ';阶段=' || V_ERROR_STAGE
      || ';规则=' || V_ERROR_RULE || ';SOURCE=' || V_ERROR_SOURCE || ';TARGET=' || V_ERROR_TARGET
      || ';错误=' || V_ERROR_COD || ':' || V_ERROR_MSG, FALSE);
    RELEASE_LOCK(V_TARGET_HANDLE);
    RELEASE_LOCK(V_SESSION_HANDLE);
    RAISE;
END CPM_SP_S2S_TDAYS_M;
