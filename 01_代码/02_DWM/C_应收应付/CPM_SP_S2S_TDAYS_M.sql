  FUNCTION VALIDATE_OBJECT(
      P_OBJECT_NAME IN VARCHAR2
    , P_TARGET      IN BOOLEAN
    , P_OWNER       OUT VARCHAR2
    , P_OBJECT      OUT VARCHAR2
  ) RETURN VARCHAR2 IS
    V_NAME       VARCHAR2(261) := UPPER(TRIM(P_OBJECT_NAME));
    V_DOT        PLS_INTEGER;
    V_OWNER      VARCHAR2(128);
    V_OBJECT     VARCHAR2(128);
    V_COUNT      NUMBER;
    V_OBJECT_TYPE VARCHAR2(19);
  BEGIN
    IF V_NAME IS NULL OR NOT REGEXP_LIKE(V_NAME, '^[A-Z][A-Z0-9_$#]*(\.[A-Z][A-Z0-9_$#]*)?$') THEN
      RAISE_APPLICATION_ERROR(-20002, '非法动态对象名：' || SUBSTR(P_OBJECT_NAME, 1, 200));
    END IF;
    V_DOT := INSTR(V_NAME, '.');
    IF V_DOT = 0 THEN
      V_OWNER := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
      V_OBJECT := V_NAME;
    ELSE
      V_OWNER := SUBSTR(V_NAME, 1, V_DOT - 1);
      V_OBJECT := SUBSTR(V_NAME, V_DOT + 1);
    END IF;
    -- DBMS_ASSERT仅负责语法校验，下面仍执行字典和目标白名单校验。
    V_NAME := DBMS_ASSERT.SQL_OBJECT_NAME(V_OWNER || '.' || V_OBJECT);
    V_OWNER := DBMS_ASSERT.SIMPLE_SQL_NAME(V_OWNER);
    V_OBJECT := DBMS_ASSERT.SIMPLE_SQL_NAME(V_OBJECT);

    SELECT COUNT(*), MAX(OBJECT_TYPE)
      INTO V_COUNT, V_OBJECT_TYPE
      FROM ALL_OBJECTS
     WHERE OWNER = V_OWNER
       AND OBJECT_NAME = V_OBJECT
       AND OBJECT_TYPE IN ('TABLE', 'VIEW', 'MATERIALIZED VIEW');
    IF V_COUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20003, '动态对象不存在或不可访问：' || V_OWNER || '.' || V_OBJECT);
    END IF;
    IF P_TARGET AND (V_OBJECT <> 'AW_MR7_ARPA01_000001' OR V_OBJECT_TYPE <> 'TABLE') THEN
      RAISE_APPLICATION_ERROR(-20004, 'TARGET_TABLE不在ARPA01白名单内：' || V_OWNER || '.' || V_OBJECT);
    END IF;
    P_OWNER := V_OWNER;
    P_OBJECT := V_OBJECT;
    RETURN V_OWNER || '.' || V_OBJECT;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE BETWEEN -20999 AND -20000 THEN
        RAISE;
      END IF;
      RAISE_APPLICATION_ERROR(-20005, '动态对象校验失败：' || SUBSTR(SQLERRM, 1, 3500));
  END;

  PROCEDURE CHECK_COLUMN(
      P_OWNER       IN VARCHAR2
