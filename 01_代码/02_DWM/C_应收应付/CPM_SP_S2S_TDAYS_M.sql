  最后更新时间：20261021
  本次修改：新增周转天数S2S配置驱动装载过程，支持动态SOURCE_TABLE、10组筛选和
            AW_MR7_ARPA01_000001目标装载；所有配置值使用绑定变量。
  名称：CPM_SP_S2S_TDAYS_M
  用途：按AW_RUL_TOVCAL_000001配置汇总18个金额并计算6个周转天数。
  源表：配置表指定的SOURCE_TABLE。
  目标表：配置表指定的TARGET_TABLE，当前仅允许AW_MR7_ARPA01_000001。
  版本信息：最新修改记录放在最上面。

  待确认项（不以知识库中的AW_MR7_ARPS02_000001替换用户指定的ARPA01）：
  1. 配置表、目标表、来源表、两个SESSION_TOVCAL_*暂存表和日志表的OWNER、DDL及直接授权；
  2. V_REF_DEST2、V_REF_ED_D_GRAN_CAL的批准OWNER、列类型和直接授权；
  3. 目标表独占性；当前删除范围按本过程目标维度处理，部署前必须取得独占证明；
  4. 目标字段没有*_MTD_OCP_AMT，本过程按对应*_END_OCP_AMT作为“本月占用金额”；
  5. 六个周转天数分母为0时按用户要求返回NULL；类别、币种保持来源直接对应（包括NULL）。

  运行前置条件：SESSION_TOVCAL_RESULT、SESSION_TOVCAL_SCOPE必须由DBA预创建并使用
