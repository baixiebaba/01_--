  PROCEDURE ADD_BIND(P_NAME IN VARCHAR2, P_VALUE IN VARCHAR2) IS
  BEGIN
    IF LENGTH(P_NAME) > 30 OR NOT REGEXP_LIKE(P_NAME, '^B_[A-Z0-9_]+$') THEN
      RAISE_APPLICATION_ERROR(-20025, '动态绑定名非法：' || P_NAME);
    END IF;
    FOR I IN 1 .. V_BIND_COUNT LOOP
      IF V_BINDS(I).NAME = P_NAME THEN
        RAISE_APPLICATION_ERROR(-20026, '同一动态SQL中绑定名重复：' || P_NAME);
      END IF;
    END LOOP;
    V_BIND_COUNT := V_BIND_COUNT + 1;
    V_BINDS(V_BIND_COUNT).NAME := P_NAME;
    V_BINDS(V_BIND_COUNT).VALUE := P_VALUE;
  END;

  PROCEDURE APPEND_FILTER(
      P_COLUMN IN VARCHAR2
    , P_OPERATOR IN VARCHAR2
    , P_VALUE IN VARCHAR2
    , P_GROUP_NO IN PLS_INTEGER
  ) IS
    V_COLUMN   VARCHAR2(128) := UPPER(TRIM(P_COLUMN));
    V_OPERATOR VARCHAR2(30) := UPPER(TRIM(P_OPERATOR));
    V_VALUE    VARCHAR2(4000) := P_VALUE;
    V_TOKEN    VARCHAR2(4000);
    V_TOTAL    PLS_INTEGER;
    V_NAME     VARCHAR2(30);
    V_HIE      VARCHAR2(4000);
    V_NODE     VARCHAR2(4000);
    V_POS      PLS_INTEGER;
  BEGIN
    IF V_COLUMN IS NULL AND V_OPERATOR IS NULL AND V_VALUE IS NULL THEN
      RETURN;
    END IF;
    IF V_COLUMN IS NULL OR V_OPERATOR IS NULL THEN
      RAISE_APPLICATION_ERROR(-20027, '第' || P_GROUP_NO || '组筛选必须同时填写字段和规则');
    END IF;
    CHECK_COLUMN(V_SOURCE_OWNER, V_SOURCE_NAME, V_COLUMN, TRUE, FALSE);
    V_SQL := V_SQL || CHR(10) || '   AND (';

    IF V_OPERATOR IN ('=', '<>') THEN
      IF TRIM(V_VALUE) IS NULL OR INSTR(V_VALUE, ',') > 0 THEN
        RAISE_APPLICATION_ERROR(-20028, '第' || P_GROUP_NO || '组' || V_OPERATOR || '规则值非法');
      END IF;
      V_NAME := 'B_G' || LPAD(P_GROUP_NO, 2, '0');
      ADD_BIND(V_NAME, TRIM(V_VALUE));
      V_SQL := V_SQL || 'S.' || V_COLUMN || ' ' || V_OPERATOR || ' :' || V_NAME || ')';
    ELSIF V_OPERATOR IN ('LIKE', 'NOT LIKE') THEN
      IF V_VALUE IS NULL THEN
        RAISE_APPLICATION_ERROR(-20029, '第' || P_GROUP_NO || '组' || V_OPERATOR || '规则必须填写值');
      END IF;
      V_NAME := 'B_G' || LPAD(P_GROUP_NO, 2, '0');
      ADD_BIND(V_NAME, V_VALUE);
      V_SQL := V_SQL || 'S.' || V_COLUMN || ' ' || V_OPERATOR || ' :' || V_NAME || ')';
    ELSIF V_OPERATOR IN ('IS NULL', 'IS NOT NULL') THEN
      IF V_VALUE IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20030, '第' || P_GROUP_NO || '组' || V_OPERATOR || '规则值必须为空');
      END IF;
      V_SQL := V_SQL || 'S.' || V_COLUMN || ' ' || V_OPERATOR || ')';
    ELSIF V_OPERATOR = 'HIE' THEN
      V_POS := INSTR(V_VALUE, '|');
      IF V_POS <= 1 OR V_POS = LENGTH(V_VALUE) OR INSTR(V_VALUE, '|', V_POS + 1) > 0 THEN
        RAISE_APPLICATION_ERROR(-20031, '第' || P_GROUP_NO || '组HIE值必须为单个|分隔的HIE|NODE');
      END IF;
      V_HIE := TRIM(SUBSTR(V_VALUE, 1, V_POS - 1));
      V_NODE := TRIM(SUBSTR(V_VALUE, V_POS + 1));
      IF V_HIE IS NULL OR V_NODE IS NULL THEN
        RAISE_APPLICATION_ERROR(-20032, '第' || P_GROUP_NO || '组HIE值的HIE或NODE为空');
      END IF;
      IF SUBSTR(V_COLUMN, 1, 4) = 'COD_' THEN
        V_HIE_OBJECT := C_HIE_OWNER || '.V_REF_' || SUBSTR(V_COLUMN, 5);
      ELSIF SUBSTR(V_COLUMN, 1, 2) = 'D_' THEN
        V_HIE_OBJECT := C_HIE_OWNER || '.V_REF_ED_' || V_COLUMN;
      ELSE
        RAISE_APPLICATION_ERROR(-20033, 'HIE字段必须以COD_或D_开头：' || V_COLUMN);
      END IF;
      V_HIE_OBJECT := VALIDATE_OBJECT(V_HIE_OBJECT, FALSE, TRUE, V_HIE_OWNER, V_HIE_NAME);
      CHECK_COLUMN(V_HIE_OWNER, V_HIE_NAME, 'ELEM', TRUE, FALSE);
      CHECK_COLUMN(V_HIE_OWNER, V_HIE_NAME, 'HIE', TRUE, FALSE);
      CHECK_COLUMN(V_HIE_OWNER, V_HIE_NAME, 'NODE', TRUE, FALSE);
      V_NAME := 'B_H' || LPAD(P_GROUP_NO, 2, '0');
      ADD_BIND(V_NAME, V_HIE);
      ADD_BIND('B_N' || LPAD(P_GROUP_NO, 2, '0'), V_NODE);
      V_SQL := V_SQL || 'S.' || V_COLUMN || ' IN (SELECT ELEM FROM '
            || V_HIE_OBJECT || ' WHERE HIE = :' || V_NAME
            || ' AND NODE = :B_N' || LPAD(P_GROUP_NO, 2, '0') || '))';
    ELSIF V_OPERATOR IN ('IN', 'NOT IN') THEN
      IF V_VALUE IS NULL OR REGEXP_LIKE(V_VALUE, '(^|,)[[:space:]]*(,|$)') THEN
        RAISE_APPLICATION_ERROR(-20034, '第' || P_GROUP_NO || '组' || V_OPERATOR || '规则含空token');
      END IF;
      V_TOTAL := REGEXP_COUNT(V_VALUE, ',') + 1;
      V_SQL := V_SQL || CHR(10) || '       ';
      FOR I IN 1 .. V_TOTAL LOOP
        V_TOKEN := TRIM(REGEXP_SUBSTR(V_VALUE, '[^,]+', 1, I));
        IF V_TOKEN IS NULL THEN
          RAISE_APPLICATION_ERROR(-20035, '第' || P_GROUP_NO || '组' || V_OPERATOR || '存在空token');
        END IF;
        IF MOD(I - 1, 1000) = 0 THEN
          IF I > 1 THEN
            V_SQL := V_SQL || CASE WHEN V_OPERATOR = 'IN' THEN ' OR ' ELSE ' AND ' END;
          END IF;
          V_SQL := V_SQL || 'S.' || V_COLUMN || ' ' || V_OPERATOR || ' (';
        ELSIF I > 1 THEN
          V_SQL := V_SQL || ', ';
        END IF;
        V_NAME := 'B_G' || LPAD(P_GROUP_NO, 2, '0') || '_I' || LPAD(I, 4, '0');
        ADD_BIND(V_NAME, V_TOKEN);
        V_SQL := V_SQL || ':' || V_NAME;
        IF MOD(I, 1000) = 0 OR I = V_TOTAL THEN
          V_SQL := V_SQL || ')';
        END IF;
      END LOOP;
      V_SQL := V_SQL || ')';
    ELSE
      RAISE_APPLICATION_ERROR(-20036, '第' || P_GROUP_NO || '组不支持筛选规则：' || V_OPERATOR);
    END IF;
  END;

