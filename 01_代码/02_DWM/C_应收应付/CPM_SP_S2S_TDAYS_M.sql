  PROCEDURE APPEND_FILTER(
      P_COLUMN IN VARCHAR2
    , P_OPERATOR IN VARCHAR2
    , P_VALUE IN VARCHAR2
    , P_GROUP_NO IN PLS_INTEGER
  ) IS
    V_COLUMN   VARCHAR2(128) := UPPER(TRIM(P_COLUMN));
    V_OPERATOR VARCHAR2(30) := UPPER(TRIM(P_OPERATOR));
    V_VALUE    VARCHAR2(4000) := P_VALUE;
    V_TOKEN    VARCHAR2(4000);
    V_INDEX    PLS_INTEGER := 0;
    V_FIRST    BOOLEAN := TRUE;
    V_NAME     VARCHAR2(30);
    V_HIE      VARCHAR2(4000);
    V_NODE     VARCHAR2(4000);
    V_POS      PLS_INTEGER;
  BEGIN
    IF V_COLUMN IS NULL AND V_OPERATOR IS NULL AND V_VALUE IS NULL THEN
      RETURN;
    END IF;
    IF V_COLUMN IS NULL OR V_OPERATOR IS NULL THEN
      RAISE_APPLICATION_ERROR(-20010, '第' || P_GROUP_NO || '组筛选配置必须同时填写字段和规则');
    END IF;
    CHECK_COLUMN(V_SOURCE_OWNER, V_SOURCE_NAME, V_COLUMN, TRUE);
    V_SQL := V_SQL || CHR(10) || '   AND (';

    IF V_OPERATOR = '=' OR V_OPERATOR = '<>' THEN
      IF TRIM(V_VALUE) IS NULL OR INSTR(V_VALUE, ',') > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, '第' || P_GROUP_NO || '组' || V_OPERATOR || '规则值非法');
      END IF;
      V_NAME := 'B_G' || LPAD(P_GROUP_NO, 2, '0');
      V_SQL := V_SQL || 'S.' || V_COLUMN || ' ' || V_OPERATOR || ' :' || V_NAME || ')';
      ADD_BIND(V_NAME, V_VALUE);
    ELSIF V_OPERATOR = 'LIKE' OR V_OPERATOR = 'NOT LIKE' THEN
      IF V_VALUE IS NULL THEN
        RAISE_APPLICATION_ERROR(-20012, '第' || P_GROUP_NO || '组' || V_OPERATOR || '规则必须填写值');
      END IF;
      V_NAME := 'B_G' || LPAD(P_GROUP_NO, 2, '0');
      V_SQL := V_SQL || 'S.' || V_COLUMN || ' ' || V_OPERATOR || ' :' || V_NAME || ')';
      ADD_BIND(V_NAME, V_VALUE);
    ELSIF V_OPERATOR = 'IS NULL' OR V_OPERATOR = 'IS NOT NULL' THEN
      IF V_VALUE IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20013, '第' || P_GROUP_NO || '组' || V_OPERATOR || '规则值必须为空');
      END IF;
      V_SQL := V_SQL || 'S.' || V_COLUMN || ' ' || V_OPERATOR || ')';
    ELSIF V_OPERATOR = 'HIE' THEN
      V_POS := INSTR(V_VALUE, '|');
      IF V_POS <= 1 OR V_POS = LENGTH(V_VALUE) OR INSTR(V_VALUE, '|', V_POS + 1) > 0 THEN
        RAISE_APPLICATION_ERROR(-20014, '第' || P_GROUP_NO || '组HIE值必须为单个|分隔的HIE|NODE');
      END IF;
      V_HIE := SUBSTR(V_VALUE, 1, V_POS - 1);
      V_NODE := SUBSTR(V_VALUE, V_POS + 1);
      IF SUBSTR(V_COLUMN, 1, 4) = 'COD_' THEN
        V_HIE_OBJECT := 'TGK_FIMA_HISENSE.V_REF_' || SUBSTR(V_COLUMN, 5);
      ELSIF SUBSTR(V_COLUMN, 1, 2) = 'D_' THEN
        V_HIE_OBJECT := 'TGK_FIMA_HISENSE.V_REF_ED_' || V_COLUMN;
      ELSE
        RAISE_APPLICATION_ERROR(-20015, 'HIE字段必须以COD_或D_开头：' || V_COLUMN);
      END IF;
      VALIDATE_OBJECT(V_HIE_OBJECT, FALSE, V_HIE_OWNER, V_HIE_NAME);
      CHECK_COLUMN(V_HIE_OWNER, V_HIE_NAME, 'ELEM', TRUE);
      CHECK_COLUMN(V_HIE_OWNER, V_HIE_NAME, 'HIE', TRUE);
      CHECK_COLUMN(V_HIE_OWNER, V_HIE_NAME, 'NODE', TRUE);
      V_SQL := V_SQL || 'S.' || V_COLUMN || ' IN (SELECT ELEM FROM '
            || V_HIE_OWNER || '.' || V_HIE_NAME
            || ' WHERE HIE = :B_H' || LPAD(P_GROUP_NO, 2, '0')
            || ' AND NODE = :B_N' || LPAD(P_GROUP_NO, 2, '0') || '))';
      ADD_BIND('B_H' || LPAD(P_GROUP_NO, 2, '0'), V_HIE);
      ADD_BIND('B_N' || LPAD(P_GROUP_NO, 2, '0'), V_NODE);
    ELSIF V_OPERATOR = 'IN' OR V_OPERATOR = 'NOT IN' THEN
      IF V_VALUE IS NULL OR REGEXP_LIKE(V_VALUE, '(^,)|(,$)|(,,)') THEN
        RAISE_APPLICATION_ERROR(-20016, '第' || P_GROUP_NO || '组' || V_OPERATOR || '规则含空值或连续逗号');
      END IF;
      V_SQL := V_SQL || CHR(10) || '       ';
      LOOP
        V_INDEX := V_INDEX + 1;
        V_TOKEN := TRIM(REGEXP_SUBSTR(V_VALUE, '[^,]+', 1, V_INDEX));
        EXIT WHEN V_TOKEN IS NULL;
        IF MOD(V_INDEX - 1, 1000) = 0 THEN
          IF V_INDEX > 1 THEN
            V_SQL := V_SQL || CASE WHEN V_OPERATOR = 'IN' THEN ' OR ' ELSE ' AND ' END;
          END IF;
          V_SQL := V_SQL || 'S.' || V_COLUMN || ' ' || V_OPERATOR || ' (';
          V_FIRST := TRUE;
        END IF;
        V_NAME := 'B_G' || LPAD(P_GROUP_NO, 2, '0') || '_I' || LPAD(V_INDEX, 4, '0');
        IF NOT V_FIRST THEN V_SQL := V_SQL || ', '; END IF;
        V_SQL := V_SQL || ':' || V_NAME;
        ADD_BIND(V_NAME, V_TOKEN);
        V_FIRST := FALSE;
        IF MOD(V_INDEX, 1000) = 0 OR REGEXP_SUBSTR(V_VALUE, '[^,]+', 1, V_INDEX + 1) IS NULL THEN
          V_SQL := V_SQL || ')';
          EXIT WHEN REGEXP_SUBSTR(V_VALUE, '[^,]+', 1, V_INDEX + 1) IS NULL;
        END IF;
      END LOOP;
      V_SQL := V_SQL || ')';
    ELSE
      RAISE_APPLICATION_ERROR(-20017, '第' || P_GROUP_NO || '组不支持筛选规则：' || V_OPERATOR);
    END IF;
  END;

  PROCEDURE WRITE_LOG(
      P_STEP IN VARCHAR2
