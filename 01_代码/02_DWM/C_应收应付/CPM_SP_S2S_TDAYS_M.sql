  FUNCTION NORMALIZE_LIST(P_VALUE VARCHAR2) RETURN VARCHAR2 IS
    V_RESULT VARCHAR2(4000) := NULL;
    V_TOKEN  VARCHAR2(4000);
    V_COUNT  PLS_INTEGER;
  BEGIN
    V_COUNT := REGEXP_COUNT(P_VALUE, ',') + 1;
    FOR I IN 1 .. V_COUNT LOOP
      V_TOKEN := TRIM(REGEXP_SUBSTR(P_VALUE, '[^,]+', 1, I));
      IF V_TOKEN IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, '参数列表存在空值项');
      END IF;
      IF V_RESULT IS NULL THEN
        V_RESULT := V_TOKEN;
      ELSE
        V_RESULT := V_RESULT || ',' || V_TOKEN;
      END IF;
    END LOOP;
    RETURN V_RESULT;
  END;

  PROCEDURE VALIDATE_TOKEN_LIST(
      P_VALUE     IN VARCHAR2
    , P_LABEL     IN VARCHAR2
    , P_ALLOW_ALL IN BOOLEAN
  ) IS
    V_VALUE VARCHAR2(4000) := TRIM(P_VALUE);
    V_TOKEN VARCHAR2(4000);
    V_COUNT PLS_INTEGER;
  BEGIN
    IF V_VALUE IS NULL THEN
      RAISE_APPLICATION_ERROR(-20002, P_LABEL || '不能为空');
    END IF;
    IF UPPER(V_VALUE) = 'ALL' THEN
      IF NOT P_ALLOW_ALL THEN
        RAISE_APPLICATION_ERROR(-20003, P_LABEL || '不允许使用ALL');
      END IF;
      RETURN;
    END IF;
    IF REGEXP_LIKE(V_VALUE, '(^|,)[[:space:]]*(,|$)') THEN
      RAISE_APPLICATION_ERROR(-20004, P_LABEL || '存在首尾、连续或空白token');
    END IF;
    V_COUNT := REGEXP_COUNT(V_VALUE, ',') + 1;
    FOR I IN 1 .. V_COUNT LOOP
      V_TOKEN := TRIM(REGEXP_SUBSTR(V_VALUE, '[^,]+', 1, I));
      IF V_TOKEN IS NULL OR UPPER(V_TOKEN) = 'ALL' THEN
        RAISE_APPLICATION_ERROR(-20005, P_LABEL || '存在非法token：' || P_VALUE);
      END IF;
      IF LENGTH(V_TOKEN) > 200 THEN
        RAISE_APPLICATION_ERROR(-20006, P_LABEL || 'token长度超过200');
      END IF;
      FOR J IN 1 .. I - 1 LOOP
        IF V_TOKEN = TRIM(REGEXP_SUBSTR(V_VALUE, '[^,]+', 1, J)) THEN
          RAISE_APPLICATION_ERROR(-20007, P_LABEL || '存在重复token：' || V_TOKEN);
        END IF;
      END LOOP;
    END LOOP;
  END;

  FUNCTION DIM_VALUE(P_VALUE VARCHAR2, P_LABEL VARCHAR2) RETURN VARCHAR2 IS
    V_VALUE VARCHAR2(4000) := TRIM_VALUE(P_VALUE);
  BEGIN
    -- 配置目标维度只允许空值表示不限制，ALL不静默扩大范围。
    IF UPPER(V_VALUE) = 'ALL' THEN
      RAISE_APPLICATION_ERROR(-20008, P_LABEL || '不允许配置值ALL，请使用空值表示不限制');
    END IF;
    RETURN NVL(V_VALUE, 'ZZZZ');
  END;

  FUNCTION VALIDATE_OBJECT(
      P_OBJECT_NAME IN VARCHAR2
    , P_TARGET      IN BOOLEAN
    , P_HIE         IN BOOLEAN
    , P_OWNER       OUT VARCHAR2
    , P_OBJECT      OUT VARCHAR2
  ) RETURN VARCHAR2 IS
    V_NAME        VARCHAR2(261) := UPPER(TRIM(P_OBJECT_NAME));
    V_DOT         PLS_INTEGER;
    V_OWNER       VARCHAR2(128);
    V_OBJECT      VARCHAR2(128);
    V_COUNT       NUMBER;
    V_OBJECT_TYPE VARCHAR2(19);
    V_GRANT_COUNT NUMBER;
  BEGIN
    -- 先做固定标识符校验，再做DBMS_ASSERT、白名单和字典校验。
    IF V_NAME IS NULL OR NOT REGEXP_LIKE(V_NAME, '^[A-Z][A-Z0-9_$#]*(\.[A-Z][A-Z0-9_$#]*)?$') THEN
      RAISE_APPLICATION_ERROR(-20009, '非法动态对象名：' || SUBSTR(P_OBJECT_NAME, 1, 200));
    END IF;
    V_DOT := INSTR(V_NAME, '.');
    IF V_DOT = 0 THEN
      V_OWNER := V_LOCAL_OWNER;
      V_OBJECT := V_NAME;
    ELSE
      V_OWNER := SUBSTR(V_NAME, 1, V_DOT - 1);
      V_OBJECT := SUBSTR(V_NAME, V_DOT + 1);
    END IF;
    V_NAME := DBMS_ASSERT.SQL_OBJECT_NAME(V_OWNER || '.' || V_OBJECT);
    V_OWNER := DBMS_ASSERT.SIMPLE_SQL_NAME(V_OWNER);
    V_OBJECT := DBMS_ASSERT.SIMPLE_SQL_NAME(V_OBJECT);

    -- 配置、来源和目标固定在过程OWNER；HIE固定在批准的TGK_FIMA_HISENSE。
    IF P_HIE THEN
      IF V_OWNER <> C_HIE_OWNER OR NOT REGEXP_LIKE(V_OBJECT, '^V_REF(_ED)?_[A-Z][A-Z0-9_$#]*$') THEN
        RAISE_APPLICATION_ERROR(-20010, 'HIE对象不在批准owner或名称白名单内：' || V_OWNER || '.' || V_OBJECT);
      END IF;
    ELSIF V_OWNER <> V_LOCAL_OWNER THEN
      RAISE_APPLICATION_ERROR(-20011, 'SOURCE/TARGET对象owner不在固定过程owner内：' || V_OWNER);
    END IF;

    SELECT COUNT(*), MAX(OBJECT_TYPE)
      INTO V_COUNT, V_OBJECT_TYPE
      FROM ALL_OBJECTS
     WHERE OWNER = V_OWNER
       AND OBJECT_NAME = V_OBJECT
       AND OBJECT_TYPE IN ('TABLE', 'VIEW', 'MATERIALIZED VIEW');
    IF V_COUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20012, '动态对象不存在或不可访问：' || V_OWNER || '.' || V_OBJECT);
    END IF;
    IF P_TARGET AND (V_OBJECT <> C_TARGET_TABLE OR V_OBJECT_TYPE <> 'TABLE') THEN
      RAISE_APPLICATION_ERROR(-20013, 'TARGET_TABLE不在固定白名单内：' || V_OWNER || '.' || V_OBJECT);
    END IF;
    IF P_HIE AND V_OBJECT_TYPE <> 'VIEW' THEN
      RAISE_APPLICATION_ERROR(-20014, 'HIE对象必须为VIEW：' || V_OWNER || '.' || V_OBJECT);
    END IF;

    -- 跨owner的HIE对象必须存在直接SELECT授权；不依赖角色授权。
    IF P_HIE AND V_OWNER <> SYS_CONTEXT('USERENV', 'CURRENT_USER') THEN
      SELECT COUNT(*)
        INTO V_GRANT_COUNT
        FROM ALL_TAB_PRIVS
       WHERE OWNER = V_OWNER
         AND TABLE_NAME = V_OBJECT
         AND GRANTEE = SYS_CONTEXT('USERENV', 'CURRENT_USER')
         AND PRIVILEGE = 'SELECT';
      IF V_GRANT_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20015, 'HIE对象缺少直接SELECT授权：' || V_OWNER || '.' || V_OBJECT);
      END IF;
    END IF;
    P_OWNER := V_OWNER;
    P_OBJECT := V_OBJECT;
    RETURN V_OWNER || '.' || V_OBJECT;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE BETWEEN -20999 AND -20000 THEN
        RAISE;
      END IF;
      RAISE_APPLICATION_ERROR(-20016, '动态对象校验失败：' || SUBSTR(SQLERRM, 1, 3500));
  END;

