    RAISE_APPLICATION_ERROR(-20020, 'P_SCENARIO不能为空、长度不能超过15且前四位必须为年份');
  END IF;
  IF TRIM(P_PERIODO) IS NULL OR NOT REGEXP_LIKE(TRIM(P_PERIODO), '^[0-9]{1,2}$') THEN
    RAISE_APPLICATION_ERROR(-20021, 'P_PERIODO必须为1至2位数字');
  END IF;
  V_PERIODO := LPAD(TRIM(P_PERIODO), 2, '0');
  IF V_PERIODO NOT BETWEEN '01' AND '12' THEN
    RAISE_APPLICATION_ERROR(-20022, 'P_PERIODO必须为01至12');
  END IF;
  IF TRIM(P_AZIENDA) IS NULL OR TRIM(P_BG) IS NULL OR TRIM(SESSION_USER) IS NULL THEN
    RAISE_APPLICATION_ERROR(-20023, 'P_AZIENDA、P_BG和SESSION_USER不能为空');
  END IF;
  IF LENGTH(P_AZIENDA) > 4000 OR LENGTH(P_BG) > 4000 THEN
    RAISE_APPLICATION_ERROR(-20024, 'P_AZIENDA或P_BG长度超过4000');
  END IF;
