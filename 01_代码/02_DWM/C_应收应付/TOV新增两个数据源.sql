-- 智动精工取数

SELECT COD_SCENARIO,COD_PERIODO,COD_AZIENDA,COD_VALUTA,SUM(IMPORTO_REV) AS IMPORTO_REV,SUM(IMPORTO) AS IMPORTO
  FROM
   (
      --收入数据
      SELECT A.COD_SCENARIO,'08' AS COD_PERIODO,A.COD_AZIENDA,A.COD_VALUTA,0-SUM(CASE WHEN COD_PERIODO = '08' THEN A.IMPORTO ELSE 0-A.IMPORTO END) AS IMPORTO_REV,0 AS IMPORTO
        FROM TGK_GB_HISENSE.DATI_SALDI_LORDI A
       WHERE A.COD_SCENARIO = '2026ACT'
         AND A.COD_PERIODO IN ('07','08')
         AND A.COD_AZIENDA IN (SELECT ELEM FROM TGK_GB_HISENSE.V_REF_AZIENDA WHERE HIE = '10' AND NODE IN ('150'))
         AND A.COD_CONTO IN ('S600100')
         AND A.COD_CATEGORIA IN ('ZAMOUNT','ZB00')
         AND A.COD_DEST1 = 'ZZCC'
         AND A.COD_DEST2 IN (SELECT ELEM FROM TGK_GB_HISENSE.V_REF_DEST2 WHERE HIE = '01' AND NODE IN ('15020')
                              UNION ALL
                             SELECT '4320.S0320' FROM DUAL)
         AND A.COD_DEST5 = 'ZZOT'
       GROUP BY A.COD_SCENARIO,A.COD_AZIENDA,A.COD_VALUTA

      UNION ALL

      --占用数据
      SELECT A.COD_SCENARIO,A.COD_PERIODO,A.COD_AZIENDA,A.COD_VALUTA,0 AS IMPORTO_REV,SUM(A.IMPORTO) AS IMPORTO
        FROM TGK_GB_HISENSE.DATI_SALDI_LORDI A
       WHERE A.COD_SCENARIO = '2026ACT'
         AND A.COD_PERIODO = '08'
         AND A.COD_AZIENDA IN (SELECT ELEM FROM TGK_GB_HISENSE.V_REF_AZIENDA WHERE HIE = '10' AND NODE IN ('150'))
         AND A.COD_CONTO IN ('SZK1011')
         AND A.COD_CATEGORIA IN ('ZAMOUNT','ZB00')
         AND A.COD_DEST1 = 'ZZCC'
         AND A.COD_DEST5 = 'ZZOT'
       GROUP BY A.COD_SCENARIO,A.COD_PERIODO,A.COD_AZIENDA,A.COD_VALUTA
   ) 
GROUP BY COD_SCENARIO,COD_PERIODO,COD_AZIENDA,COD_VALUTA



