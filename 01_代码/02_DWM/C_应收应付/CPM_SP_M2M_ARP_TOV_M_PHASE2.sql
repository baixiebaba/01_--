CREATE OR REPLACE PROCEDURE CPM_SP_M2M_ARP_TOV_M_PHASE2(
    P_SCENARIO   IN VARCHAR2
  , P_PERIODO    IN VARCHAR2
  , P_AZIENDA    IN VARCHAR2
  , P_BG         IN VARCHAR2
  , SESSION_USER IN VARCHAR2
) AS
  /**************************************************************************
  最后更新时间：20261020
  本次修改：增加AW_RUL_ARPTOV_000001特殊取数配置，支持BATCH_ID=1至4剔除和BATCH_ID=6按公司、二级性质取数。
            ARPM02按配置过滤后再生成ZAMOUNT、ZAMOUNT_L2。
  上次修改：ARPM02与IMOCC先汇总后按公司、客商、利润中心匹配收入；未匹配收入追加。
            D_BG统一后置映射，增加多事业部客户的负周转行剔除规则。
  名称：CPM_SP_M2M_ARP_TOV_M_PHASE2
  用途：装载应收周转计算汇总表
  源表：AW_MR9_ARPM02_000001、DWD_FI_MR_AR_IMOCC_MI、AW_MR9_REVM01_000001、AW_MR8_CPRS01_000001
  目标表：AW_MR9_ARPM03_000001
  版本信息：最新修改记录放最上面
  **************************************************************************/
  V_SCENARIO   VARCHAR2(30);
  V_PERIODO    VARCHAR2(30);
  V_YEARMONTH  VARCHAR2(10);
  V_AZIENDA    VARCHAR2(4000);
  V_SESSION_ID NUMBER;
  V_ERROR_COD  NUMBER;
  V_ERROR_MSG  VARCHAR2(4000);
BEGIN
  V_SESSION_ID := SYS_CONTEXT('USERENV', 'SESSIONID');

  DELETE FROM SESSION_AZIENDA_LIST
   WHERE SESSION_ID = V_SESSION_ID;
  DELETE FROM SESSION_V_REF_AZIENDA
   WHERE SESSION_ID = V_SESSION_ID;

  INSERT INTO SESSION_V_REF_AZIENDA(SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, HIE, NODE, ELEM
    FROM TGK_FIMA_HISENSE.V_REF_AZIENDA;

  V_SCENARIO := P_SCENARIO;
  V_PERIODO := LPAD(P_PERIODO, 2, '0');
  V_YEARMONTH := SUBSTR(V_SCENARIO, 1, 4) || V_PERIODO;

  -- 保持DWMCRS现状，仅以账套映射限制本次输入公司范围。
  INSERT INTO SESSION_AZIENDA_LIST(SESSION_ID, ELEM)
  SELECT DISTINCT V_SESSION_ID
       , ELEM
    FROM SESSION_V_REF_AZIENDA
   WHERE HIE = '10'
     AND (
           INSTR(',' || P_AZIENDA || ',', ',' || ELEM || ',') > 0
        OR INSTR(',' || P_AZIENDA || ',', ',' || NODE || ',') > 0
        OR P_AZIENDA = 'ALL'
     )
     AND ELEM IN (
           SELECT COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_ATSMAP_000001 A
            WHERE A.VALID_FR <= V_YEARMONTH
              AND NVL(A.VALID_TO, '999999') >= V_YEARMONTH
              AND (
                    P_BG = 'ALL'
                 OR INSTR(',' || P_BG || ',', ',' || A.COD_BG || ',') > 0
              )
              AND A.COD_BG NOT LIKE 'CXC%'
              AND A.COD_BG IN (
                    SELECT C.COD_BG
                      FROM TGK_FIMA_HISENSE.AW_RUL_COSMAP_000001 C
                     WHERE C.AR_TOV_FLAG = 'Y'
                       AND C.VALID_FR <= V_YEARMONTH
                       AND NVL(C.VALID_TO, '999999') >= V_YEARMONTH
              )
     )
     AND ELEM IN (
           SELECT COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001
            WHERE ARP_FLAG = 'Y'
              AND VALID_FR <= V_YEARMONTH
              AND NVL(VALID_TO, '999999') >= V_YEARMONTH
              AND COD_CONTO = 'ZAW_D2M_IN'
     )
     AND ELEM NOT IN (
           SELECT COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001
            WHERE ARP_FLAG = 'Y'
              AND COD_SCENARIO = V_SCENARIO
              AND COD_PERIODO = V_PERIODO
              AND COD_CONTO = 'ZAW_D2M_LOCK'
     );

  SELECT LISTAGG(ELEM, ',') WITHIN GROUP (ORDER BY ELEM)
    INTO V_AZIENDA
    FROM (
      SELECT DISTINCT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID
    );

  INSERT INTO ZTAB_CPM_LOG(
      CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA
  ) VALUES (
      'CPM_SP_M2M_ARP_TOV_M_PHASE2', 'BEGIN 开始执行', SYSDATE, SESSION_USER,
      V_SCENARIO, V_PERIODO, V_AZIENDA
  );
  COMMIT;

  -- 删除当前批次未锁定事业部的本过程数据，锁定事业部保留既有结果且不参与重算。
  DELETE FROM AW_MR9_ARPM03_000001 D
   WHERE COD_SCENARIO = V_SCENARIO
     AND COD_PERIODO = V_PERIODO
     AND COD_AZIENDA IN (
           SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID
     )
     AND PROVENIENZA = 'CPM_SP_M2M_ARP_TOV_M_PHASE2'
     AND NOT EXISTS (
           SELECT 1
             FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001 T
            WHERE T.ARP_FLAG = 'Y'
              AND T.COD_SCENARIO = V_SCENARIO
              AND T.COD_PERIODO = V_PERIODO
              AND T.COD_CONTO = 'ZAW_M2S_LOCK'
              AND T.D_BG = D.D_BG
     );

  INSERT INTO ZTAB_CPM_LOG(
      CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA
  ) VALUES (
      'CPM_SP_M2M_ARP_TOV_M_PHASE2', '当前批次删除完成', SYSDATE, SESSION_USER,
      V_SCENARIO, V_PERIODO, V_AZIENDA
  );

  -- ============================================================================
  -- 目标表装载：先汇总周转，再匹配收入；事业部映射及负周转剔除均在合并后执行。
  -- ============================================================================
  INSERT INTO AW_MR9_ARPM03_000001(
      OID
    , COD_SCENARIO
    , COD_PERIODO
    , D_BG
    , COD_AZIENDA
    , COD_CONTO
    , COD_CATEGORIA
    , GRP_SCOPE
    , CUST_CODE
    , CUST_NAME
    , CUST_HEAD_CODE
    , CUST_HEAD_NAME
    , CUST_BRANCH_CODE
    , CUST_BRANCH_NAME
    , COD_AZI_CTP
    , COUNTRY_NAME
    , NATURE_L2_NAME
    , D_CHANNEL
    , D_ONOFFLINE
    , COD_DEST2
    , COD_DEST3
    , D_SALE_DEPT
    , D_TOV_CHAN
    , D_CC_CUSTGRP
    , COD_VALUTA
    , AR_AMT
    , REV_AMT
    , F1_ODUE_AMT
    , F2_EPAY_AMT
    , F3_ECR_AMT
    , F4_UREB_AMT
    , F5_UFEE_AMT
    , F6_INVSM_AMT
    , F7_GSUB_AMT
    , F8_ADJ_AMT
    , PROVENIENZA
    , DATEUPD
    , USERUPD
  )
  WITH
  -- 利润中心标准化规则：仅按源利润中心及有效期统一转换，不按公司匹配。
  PROFIT_CENTER_RULE AS (
    SELECT LTRIM(TRIM(SRC_PROFITCENTER_CODE), '0') AS SRC_PROFITCENTER_CODE
         , MAX(PROFITCENTER_CODE) AS PROFITCENTER_CODE
      FROM DIM_RULE_FI_MR_AR_PROFIT_MAPPING
     WHERE BATCH_ID = 2
       AND VALID_FR <= V_YEARMONTH
       AND NVL(VALID_TO, '999999') >= V_YEARMONTH
     GROUP BY LTRIM(TRIM(SRC_PROFITCENTER_CODE), '0')
  ),
  -- 周转事业部范围：仅保留当前期间AR_TOV_FLAG为Y的有效事业部。
  TOV_BG_SCOPE AS (
    SELECT DISTINCT C.COD_BG
      FROM TGK_FIMA_HISENSE.AW_RUL_COSMAP_000001 C
     WHERE C.AR_TOV_FLAG = 'Y'
       AND C.VALID_FR <= V_YEARMONTH
       AND NVL(C.VALID_TO, '999999') >= V_YEARMONTH
  ),
  -- 账套事业部映射：公司事业部必须属于有效周转事业部范围。
  ATS_BG_MAP AS (
    SELECT A.COD_AZIENDA
         , A.COD_BG
      FROM TGK_FIMA_HISENSE.AW_RUL_ATSMAP_000001 A
     WHERE A.VALID_FR <= V_YEARMONTH
       AND NVL(A.VALID_TO, '999999') >= V_YEARMONTH
       AND A.COD_BG IN (
           SELECT COD_BG
             FROM TOV_BG_SCOPE
       )
       AND A.COD_BG NOT LIKE 'CXC%'
       AND (P_BG = 'ALL'
          OR INSTR(',' || P_BG || ',', ',' || A.COD_BG || ',') > 0)
  ),
  -- 利润中心所属事业部映射：保留利润中心在P_BG范围内匹配到的全部事业部，最终与公司事业部比较。
  PCR_BG_MAP AS (
    SELECT LTRIM(TRIM(P.COD_DEST2), '0') AS COD_DEST2
         , P.COD_BG
      FROM TGK_FIMA_HISENSE.AW_RUL_PCRMAP_000001 P
     WHERE P.VALID_FR <= V_YEARMONTH
       AND NVL(P.VALID_TO, '999999') >= V_YEARMONTH
       AND P.COD_BG IN (
           SELECT COD_BG
             FROM TOV_BG_SCOPE
       )
       AND P.COD_BG NOT LIKE 'CXC%'
       AND (
             P_BG = 'ALL'
          OR INSTR(',' || P_BG || ',', ',' || P.COD_BG || ',') > 0
       )
  ),
  -- 商冷客户群：无需有效期字段的维表按公司、客商归并。
  CUSTOMER_CC_MAP AS (
    SELECT LTRIM(TRIM(CUST_SAP_CODE), '0') AS CUST_SAP_CODE
         , LTRIM(TRIM(COMPANY_CODE_MDG), '0') AS COMPANY_CODE_MDG
         , MAX(CRG_CUST_GROUP_CODE) AS CRG_CUST_GROUP_CODE
      FROM DIM_CUSTOMER_COMPANY_INFO_DD
     WHERE CRG_CUST_GROUP_CODE IS NOT NULL
     GROUP BY LTRIM(TRIM(CUST_SAP_CODE), '0')
            , LTRIM(TRIM(COMPANY_CODE_MDG), '0')
  ),
  -- 周转渠道规则一：按公司、客商匹配。
  TOV_CHANNEL_RULE_1 AS (
    SELECT COMPANY_CODE
         , LTRIM(TRIM(CUST_CODE), '0') AS CUST_CODE
         , MAX(TOV_CHANNEL_CODE) AS TOV_CHANNEL_CODE
      FROM DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING
     WHERE BATCH_ID = 1
       AND VALID_FR <= V_YEARMONTH
       AND NVL(VALID_TO, '999999') >= V_YEARMONTH
     GROUP BY COMPANY_CODE
            , LTRIM(TRIM(CUST_CODE), '0')
  ),
  -- 周转渠道规则二：按公司、三级渠道匹配。
  TOV_CHANNEL_RULE_2 AS (
    SELECT COMPANY_CODE
         , CHANNEL_L3_CODE
         , MAX(TOV_CHANNEL_CODE) AS TOV_CHANNEL_CODE
      FROM DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING
     WHERE BATCH_ID = 2
       AND VALID_FR <= V_YEARMONTH
       AND NVL(VALID_TO, '999999') >= V_YEARMONTH
     GROUP BY COMPANY_CODE
            , CHANNEL_L3_CODE
  ),
  -- DEST3层级：仅收入未匹配时使用其自身国家名称维度。
  DEST3_COUNTRY_MAP AS (
    SELECT COD_DEST3
         , NVL(NVL(DESC_DEST3_ELEGER3, DESC_DEST3_ELEGER4), DESC_DEST3_ELEGER5) AS COUNTRY_NAME
      FROM TGK_FIMA_HISENSE.DEST3_GERARCHIA_FLAT
     WHERE COD_DEST3_GERARCHIA = '01'
  ),
  -- 当前场景期间的公司节点关系，保留收入集团归属范围计算口径。
  NODE_MAP AS (
    SELECT N.COD_SCENARIO
         , N.COD_PERIODO
         , N.ELEM
         , N.NODE
         , N.NODES
         , CASE WHEN H.ELEM IS NOT NULL THEN 1 ELSE 0 END AS IS_HITACHI
         , CASE WHEN H.ELEM IS NOT NULL THEN NVL(N.NODES, N.NODE) ELSE N.NODE END AS SELF_NODE
         , N.HQ
      FROM TGK_GB_HISENSE.V_APAR_ELEM_NODE_TAB N
      LEFT JOIN (
        SELECT DISTINCT ELEM
          FROM TGK_GB_HISENSE.V_REF_AZIENDA_TV
         WHERE COD_SCENARIO = V_SCENARIO
           AND COD_PERIODO = V_PERIODO
           AND HIE = '30'
           AND NODE = '1730'
      ) H
        ON H.ELEM = N.ELEM
     WHERE N.COD_SCENARIO = V_SCENARIO
       AND N.COD_PERIODO = V_PERIODO
  ),
  -- 应收周转特殊取数配置：仅读取当前期间有效的取数及剔除规则。
  ARPTOV_RULE AS (
    SELECT R.BATCH_ID
         , TRIM(R.COD_AZIENDA) AS COD_AZIENDA
         , TRIM(R.CUST_CODE) AS CUST_CODE
         , TRIM(R.NATURE_L2_NAME) AS NATURE_L2_NAME
         , TRIM(R.D_SALE_DEPT) AS D_SALE_DEPT
      FROM AW_RUL_ARPTOV_000001 R
     WHERE R.VALID_FR <= V_YEARMONTH
       AND NVL(R.VALID_TO, '999999') >= V_YEARMONTH
       AND R.BATCH_ID IN ('1', '2', '3', '4', '6')
  ),
  -- ARPM02来源：单次读取，根据ME_AGE_FLAG、MB_AGE_FLAG判断生成ZAMOUNT或ZAMOUNT_L2。
  ARPM02_SOURCE AS (
    SELECT A.COD_SCENARIO
         , A.COD_PERIODO
         , A.COD_AZIENDA
         , '1122000000' AS COD_CONTO
         , CASE
               WHEN A.ME_AGE_FLAG IN ('AR', 'CA', 'A10') THEN 'ZAMOUNT'
               WHEN A.MB_AGE_FLAG IN ('AR', 'CA', 'A10') THEN 'ZAMOUNT_L2'
           END AS COD_CATEGORIA
         , A.GRP_SCOPE
         , TRIM(A.CUST_CODE) AS CUST_CODE
         , A.CUST_NAME
         , A.CUST_HEAD_CODE
         , A.CUST_HEAD_NAME
         , A.CUST_BRANCH_CODE
         , A.CUST_BRANCH_NAME
         , A.COD_AZI_CTP
         , A.COUNTRY_NAME
         , A.NATURE_L2_NAME
         , A.D_CHANNEL
         , A.D_ONOFFLINE
         , A.COD_DEST2
         , A.COD_DEST3
         , A.D_SALE_DEPT
         , A.D_TOV_CHAN
         , A.D_CC_CUSTGRP
         , A.COD_VALUTA
         , NVL(A.BCY_ADJ_INCL_0_AMT, 0) AS AR_AMT
         , 0 AS REV_AMT
         , NVL(A.OVERDUE_0_AMT, 0) AS F1_ODUE_AMT
         , NVL(A.EPAY_AMT, 0) AS F2_EPAY_AMT
         , NVL(A.ECLS_AMT, 0) AS F3_ECR_AMT
         , NVL(A.UREB_AMT, 0) AS F4_UREB_AMT
         , NVL(A.UFEE_AMT, 0) AS F5_UFEE_AMT
         , NVL(A.INV_SAMPLE_AMT, 0) AS F6_INVSM_AMT
         , 0 AS F7_GSUB_AMT
         , 0 AS F8_ADJ_AMT
      FROM AW_MR9_ARPM02_000001 A
     WHERE A.COD_SCENARIO = V_SCENARIO
       AND A.COD_PERIODO = V_PERIODO
       AND A.COD_AZIENDA IN (
           SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID
       )
       AND A.COD_DEST2 IS NOT NULL
       AND A.COD_DEST2 <> 'ZZZZ'
       -- 至少有一类账龄标识满足周转取数范围。
       AND (
             A.ME_AGE_FLAG IN ('AR', 'CA', 'A10')
          OR A.MB_AGE_FLAG IN ('AR', 'CA', 'A10')
       )
       -- BATCH_ID=6：公司有维护时仅保留配置的二级性质，公司无维护时默认全部取数。
       AND (
             NOT EXISTS (
                 SELECT 1
                   FROM ARPTOV_RULE R6
                  WHERE R6.BATCH_ID = '6'
                    AND R6.COD_AZIENDA IS NOT NULL
                    AND R6.NATURE_L2_NAME IS NOT NULL
                    AND R6.COD_AZIENDA = TRIM(A.COD_AZIENDA)
             )
          OR EXISTS (
                 SELECT 1
                   FROM ARPTOV_RULE R6
                  WHERE R6.BATCH_ID = '6'
                    AND R6.COD_AZIENDA = TRIM(A.COD_AZIENDA)
                    AND R6.NATURE_L2_NAME = TRIM(A.NATURE_L2_NAME)
             )
       )
       -- BATCH_ID=1至4：在取数范围确定后，统一执行特殊剔除规则。
       AND NOT EXISTS (
           SELECT 1
             FROM ARPTOV_RULE R1
            WHERE R1.BATCH_ID = '1'
              AND R1.CUST_CODE IS NOT NULL
              AND TRIM(A.CUST_CODE) LIKE '%' || R1.CUST_CODE || '%'
       )
       AND NOT EXISTS (
           SELECT 1
             FROM ARPTOV_RULE R2
            WHERE R2.BATCH_ID = '2'
              AND R2.COD_AZIENDA = TRIM(A.COD_AZIENDA)
              AND R2.CUST_CODE IS NOT NULL
              AND R2.CUST_CODE = TRIM(A.CUST_CODE)
       )
       AND NOT EXISTS (
           SELECT 1
             FROM ARPTOV_RULE R3
            WHERE R3.BATCH_ID = '3'
              AND R3.NATURE_L2_NAME IS NOT NULL
              AND R3.NATURE_L2_NAME = TRIM(A.NATURE_L2_NAME)
       )
       AND NOT EXISTS (
           SELECT 1
             FROM ARPTOV_RULE R4
            WHERE R4.BATCH_ID = '4'
              AND R4.COD_AZIENDA = TRIM(A.COD_AZIENDA)
              AND R4.D_SALE_DEPT IS NOT NULL
              AND R4.D_SALE_DEPT = TRIM(A.D_SALE_DEPT)
       )
  ),
  -- IMOCC来源：不提前映射D_BG，科目固定1122000000，保留来源国家名称和利润中心口径。
  IMOCC_SOURCE AS (
    SELECT V_SCENARIO AS COD_SCENARIO
         , V_PERIODO AS COD_PERIODO
         , I.COMPANY_CODE AS COD_AZIENDA
         , '1122000000' AS COD_CONTO
         , 'ZAMOUNT' AS COD_CATEGORIA
         , 'GEX-集团外' AS GRP_SCOPE
         , TRIM(I.CUST_CODE) AS CUST_CODE
         , I.CUST_NAME
         , TRIM(I.CUST_CODE) AS CUST_HEAD_CODE
         , I.CUST_NAME AS CUST_HEAD_NAME
         , I.CUST_BRANCH_CODE
         , I.CUST_BRANCH_NAME
         , I.CP_COMPANY_CODE AS COD_AZI_CTP
         , I.COUNTRY_NAME
         , CAST(NULL AS VARCHAR2(200)) AS NATURE_L2_NAME
         , 'ZZZZ' AS D_CHANNEL
         , 'ZZZZ' AS D_ONOFFLINE
         , NVL(I.PROFITCENTER_CODE, 'ZZZZ') AS COD_DEST2
         , NVL(I.BUS_RANGE_CODE, 'ZZZZ') AS COD_DEST3
         , 'ZZZZ' AS D_SALE_DEPT
         , 'ZZZZ' AS D_TOV_CHAN
         , 'ZZZZ' AS D_CC_CUSTGRP
         , 'CNY' AS COD_VALUTA
         , NVL(I.IMOCC_CNY_AMT, 0) AS AR_AMT
         , 0 AS REV_AMT
         , 0 AS F1_ODUE_AMT
         , 0 AS F2_EPAY_AMT
         , 0 AS F3_ECR_AMT
         , 0 AS F4_UREB_AMT
         , 0 AS F5_UFEE_AMT
         , 0 AS F6_INVSM_AMT
         , 0 AS F7_GSUB_AMT
         , 0 AS F8_ADJ_AMT
      FROM DWD_FI_MR_AR_IMOCC_MI I
     WHERE I.DT_MONTH = V_YEARMONTH
       AND I.COMPANY_CODE IN ('1740', '2080')
       AND TRIM(I.CP_COMPANY_CODE) IS NULL
       AND I.PROFITCENTER_CODE IS NOT NULL
       AND I.PROFITCENTER_CODE <> 'ZZZZ'
       AND NVL(I.IMOCC_CNY_AMT, 0) <> 0
       AND I.COMPANY_CODE IN (
           SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID
       )
  ),
  -- TURNOVER：ARPM02和IMOCC先按匹配前的完整周转维度汇总。
  TURNOVER AS (
    SELECT COD_SCENARIO
         , COD_PERIODO
         , COD_AZIENDA
         , COD_CONTO
         , COD_CATEGORIA
         , GRP_SCOPE
         , CUST_CODE
         , CUST_NAME
         , CUST_HEAD_CODE
         , CUST_HEAD_NAME
         , CUST_BRANCH_CODE
         , CUST_BRANCH_NAME
         , COD_AZI_CTP
         , COUNTRY_NAME
         , NATURE_L2_NAME
         , D_CHANNEL
         , D_ONOFFLINE
         , COD_DEST2
         , COD_DEST3
         , D_SALE_DEPT
         , D_TOV_CHAN
         , D_CC_CUSTGRP
         , COD_VALUTA
         , SUM(AR_AMT) AS AR_AMT
         , SUM(REV_AMT) AS REV_AMT
         , SUM(F1_ODUE_AMT) AS F1_ODUE_AMT
         , SUM(F2_EPAY_AMT) AS F2_EPAY_AMT
         , SUM(F3_ECR_AMT) AS F3_ECR_AMT
         , SUM(F4_UREB_AMT) AS F4_UREB_AMT
         , SUM(F5_UFEE_AMT) AS F5_UFEE_AMT
         , SUM(F6_INVSM_AMT) AS F6_INVSM_AMT
         , SUM(F7_GSUB_AMT) AS F7_GSUB_AMT
         , SUM(F8_ADJ_AMT) AS F8_ADJ_AMT
      FROM (
        SELECT COD_SCENARIO, COD_PERIODO, COD_AZIENDA, COD_CONTO, COD_CATEGORIA
             , GRP_SCOPE, CUST_CODE, CUST_NAME, CUST_HEAD_CODE, CUST_HEAD_NAME
             , CUST_BRANCH_CODE, CUST_BRANCH_NAME, COD_AZI_CTP, COUNTRY_NAME, NATURE_L2_NAME
             , D_CHANNEL, D_ONOFFLINE, COD_DEST2, COD_DEST3, D_SALE_DEPT, D_TOV_CHAN
             , D_CC_CUSTGRP, COD_VALUTA, AR_AMT, REV_AMT, F1_ODUE_AMT, F2_EPAY_AMT
             , F3_ECR_AMT, F4_UREB_AMT, F5_UFEE_AMT, F6_INVSM_AMT, F7_GSUB_AMT, F8_ADJ_AMT
          FROM ARPM02_SOURCE
        UNION ALL
        SELECT COD_SCENARIO, COD_PERIODO, COD_AZIENDA, COD_CONTO, COD_CATEGORIA
             , GRP_SCOPE, CUST_CODE, CUST_NAME, CUST_HEAD_CODE, CUST_HEAD_NAME
             , CUST_BRANCH_CODE, CUST_BRANCH_NAME, COD_AZI_CTP, COUNTRY_NAME, NATURE_L2_NAME
