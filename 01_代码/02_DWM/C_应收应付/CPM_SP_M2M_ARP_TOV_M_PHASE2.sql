      LEFT JOIN TOV_CHANNEL_RULE_1 T1
        ON T1.COMPANY_CODE = R.COD_AZIENDA
       AND T1.CUST_CODE = LTRIM(TRIM(R.CUST_CODE), '0')
      LEFT JOIN TOV_CHANNEL_RULE_2 T2
        ON T2.COMPANY_CODE = R.COD_AZIENDA
       AND T2.CHANNEL_L3_CODE = R.D_CHANNEL
     WHERE CASE
             WHEN CUR_NODE.SELF_NODE = CASE WHEN CUR_NODE.IS_HITACHI = 1 THEN NVL(CTP_NODE.NODES, CTP_NODE.NODE) ELSE CTP_NODE.NODE END
              AND CUR_NODE.HQ = CTP_NODE.HQ THEN 'SUB-子公司'
             WHEN CUR_NODE.HQ = CTP_NODE.HQ THEN 'GIN-集团内'
