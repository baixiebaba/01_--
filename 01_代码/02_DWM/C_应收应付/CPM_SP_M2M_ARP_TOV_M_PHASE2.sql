         , 'ZZZZ' AS D_TOV_CHAN
         , 'ZZZZ' AS D_CC_CUSTGRP
         , 'CNY' AS COD_VALUTA
         , 0 AS AR_AMT
         , 0 AS REV_AMT
         , 0 AS F1_ODUE_AMT
         , 0 AS F2_EPAY_AMT
         , 0 AS F3_ECR_AMT
         , 0 AS F4_UREB_AMT
         , 0 AS F5_UFEE_AMT
