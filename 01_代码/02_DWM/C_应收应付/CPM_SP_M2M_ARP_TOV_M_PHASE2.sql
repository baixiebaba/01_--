   * 目标表    ：AW_MR9_ARPM03_000001
   *
 * 修改历史：
 *   ALTER BY 20261110 18:18 SHIQINGFENG.EX GB科目与组织节点成员初始化进会话表，特殊来源取数改读会话表
 *   ALTER BY 20261110 17:30 SHIQINGFENG.EX 账龄与收入来源利润中心改按AW_RUL_ARPPRC_000001映射
 *   ALTER BY 20261110 11:25 SHIQINGFENG.EX ARPM02的050节点判断由逐行EXISTS改为LEFT JOIN
   *   ALTER BY 20261110 11:22 SHIQINGFENG.EX 会话表HIE装载时拼FIMA_/GB_前缀区分两棵组织树，免加字段
   *   ALTER BY 20261110 11:14 SHIQINGFENG.EX 特殊来源改为公共底层CTE单次扫描GB余额表，降低大表重复扫描耗时
   *   ALTER BY 20261110 10:05 SHIQINGFENG.EX 新增数据分类字段SRC_DETAIL，标识周转各数据来源
   *   ALTER BY 20261109 18:22 SHIQINGFENG.EX 利润中心事业部映射去重，避免配置重复行导致金额翻倍
   *   ALTER BY 20261109 18:12 SHIQINGFENG.EX 修复周转行事业部二次映射，ARPM03周转金额不再按命中事业部数翻倍
   *   ALTER BY 20261109 17:00 SHIQINGFENG.EX 装载后清理金额全为0的记录
   *   ALTER BY 20261109 16:38 SHIQINGFENG.EX 去掉全部锁定判断，取数、删除、装载都按参数事业部全量执行
   *   ALTER BY 20261109 16:20 SHIQINGFENG.EX 入参取消公司参数，删除范围改为按事业部，取数仍按事业部推导的公司清单限制
   *   ALTER BY 20261109 11:10 SHIQINGFENG.EX ARPM02取数限制条件前置为AG过程维护的TOV_FLAG标识列
   *   ALTER BY 20261102 15:49 SHIQINGFENG.EX 移除D_TOV_CHAN维度
   *   ALTER BY 20261102 15:00 SHIQINGFENG.EX 新增渠道BU维度
   *   ALTER BY 20261029 18:20 SHIQINGFENG.EX 收入利润中心映射新增BATCH_ID=6，优先级BATCH_ID=2>6>收入原利润中心。
   *   ALTER BY 20261027 18:47 SHIQINGFENG.EX 还原ARPM02的AR_AMT在050节点和其他公司的计算公式。
   *   ALTER BY 20261027 18:33 SHIQINGFENG.EX ARPM02的AR_AMT按050节点和其他公司调整计算公式。
   *   ALTER BY 20261027 16:19 SHIQINGFENG.EX 特殊数据源保留原始组织范围，固定入表公司4330和1100并增加独立删除逻辑。
   *   ALTER BY 20261027 16:04 SHIQINGFENG.EX 增加两段目标表装载日志，区分主装载和特殊数据源装载。
   *   ALTER BY 20261027 15:51 SHIQINGFENG.EX 新增智动精工和模具周转取数，按场景、公司范围及P_BG事业部范围装载。
   *   20261020 新增最终颗粒度口径字段D_GRAN_CAL，固定写入ARTO_CUST。
   *   20261020 增加AW_RUL_ARPTOV_000001特殊取数配置，支持BATCH_ID=1至4剔除和BATCH_ID=6按公司、二级性质取数。
   *******************************************************************************/
  V_SCENARIO   VARCHAR2(30);
  V_PERIODO    VARCHAR2(30);
  V_YEARMONTH  VARCHAR2(10);
  V_AZIENDA    VARCHAR2(4000);
  V_SESSION_ID NUMBER;
  V_ERROR_COD  NUMBER;
  V_ERROR_MSG  VARCHAR2(4000);
BEGIN
  V_SESSION_ID := SYS_CONTEXT('USERENV', 'SESSIONID');

  DELETE FROM SESSION_AZIENDA_LIST
  WHERE SESSION_ID = V_SESSION_ID;
  DELETE FROM SESSION_V_REF_AZIENDA
  WHERE SESSION_ID = V_SESSION_ID;

  /* HIE拼前缀区分FIMA和GB两棵组织树：两树HIE/NODE键位大量重叠且成员不同，查询时写死FIMA_/GB_前缀。 */
  INSERT INTO SESSION_V_REF_AZIENDA(SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, 'FIMA_' || HIE, NODE, ELEM
    FROM TGK_FIMA_HISENSE.V_REF_AZIENDA;

  INSERT INTO SESSION_V_REF_AZIENDA(SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, 'GB_' || HIE, NODE, ELEM
    FROM TGK_GB_HISENSE.V_REF_AZIENDA;

  /* 特殊来源用到的GB科目和组织节点成员随会话初始化，取数时直接读会话表，避免递归视图每次实时展开。 */
  INSERT INTO SESSION_V_REF_AZIENDA(SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, 'GBCONTO_' || HIE, NODE, ELEM
    FROM TGK_GB_HISENSE.V_REF_CONTO
  WHERE HIE = '01'
    AND NODE = 'S6001A';

  INSERT INTO SESSION_V_REF_AZIENDA(SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, 'GBDEST1_' || HIE, NODE, ELEM
    FROM TGK_GB_HISENSE.V_REF_DEST1
  WHERE HIE = '01'
    AND NODE IN ('100', '1102', '110');

  INSERT INTO SESSION_V_REF_AZIENDA(SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, 'GBDEST2_' || HIE, NODE, ELEM
    FROM TGK_GB_HISENSE.V_REF_DEST2
  WHERE HIE = '01'
    AND NODE IN ('15020', '1102', '1103', '1104', '1105', '10090');

  V_SCENARIO := P_SCENARIO;
  V_PERIODO := LPAD(P_PERIODO, 2, '0');
  V_YEARMONTH := SUBSTR(V_SCENARIO, 1, 4) || V_PERIODO;

  /* 公司清单由事业部参数反推，只用于限制取数源数据量；删除与写入范围按事业部判断。 */
  INSERT INTO SESSION_AZIENDA_LIST(SESSION_ID, ELEM)
  SELECT DISTINCT V_SESSION_ID
      , ELEM
    FROM SESSION_V_REF_AZIENDA
  WHERE HIE = 'FIMA_10'
    AND ELEM IN (
          SELECT COD_AZIENDA
            FROM TGK_FIMA_HISENSE.AW_RUL_ATSMAP_000001 A
            WHERE A.VALID_FR <= V_YEARMONTH
              AND NVL(A.VALID_TO, '999999') >= V_YEARMONTH
              AND (
                    P_BG = 'ALL'
                OR INSTR(',' || P_BG || ',', ',' || A.COD_BG || ',') > 0
              )
              AND A.COD_BG NOT LIKE 'CXC%'
              AND A.COD_BG IN (
                    SELECT C.COD_BG
                      FROM TGK_FIMA_HISENSE.AW_RUL_COSMAP_000001 C
                    WHERE C.AR_TOV_FLAG = 'Y'
                      AND C.VALID_FR <= V_YEARMONTH
                      AND NVL(C.VALID_TO, '999999') >= V_YEARMONTH
              )
    )
    AND ELEM IN (
          SELECT COD_AZIENDA
            FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001
            WHERE ARP_FLAG = 'Y'
              AND VALID_FR <= V_YEARMONTH
              AND NVL(VALID_TO, '999999') >= V_YEARMONTH
              AND COD_CONTO = 'ZAW_D2M_IN'
    );

  SELECT LISTAGG(ELEM, ',') WITHIN GROUP (ORDER BY ELEM)
    INTO V_AZIENDA
    FROM (
      SELECT DISTINCT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID
    );

  INSERT INTO ZTAB_CPM_LOG (CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA)
  VALUES ('CPM_SP_M2M_ARP_TOV_M_PHASE2', 'BEGIN 开始执行', SYSDATE, SESSION_USER, V_SCENARIO, V_PERIODO, P_BG || '|' || V_AZIENDA);
  COMMIT;

  /* 按事业部删除当期本过程数据。 */
  DELETE FROM AW_MR9_ARPM03_000001 D
  WHERE D.COD_SCENARIO = V_SCENARIO
    AND D.COD_PERIODO = V_PERIODO
    AND D.PROVENIENZA = 'CPM_SP_M2M_ARP_TOV_M_PHASE2'
    AND (
          P_BG = 'ALL'
      OR INSTR(',' || P_BG || ',', ',' || D.D_BG || ',') > 0
    );

  INSERT INTO ZTAB_CPM_LOG (CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA)
  VALUES ('CPM_SP_M2M_ARP_TOV_M_PHASE2', '当前批次删除完成', SYSDATE, SESSION_USER, V_SCENARIO, V_PERIODO, P_BG || '|' || V_AZIENDA);

  /* 目标表装载：先汇总周转，再匹配收入；事业部映射及负周转剔除均在合并后执行。 */
  INSERT INTO AW_MR9_ARPM03_000001 (
      OID
    , COD_SCENARIO
    , COD_PERIODO
    , D_BG
    , COD_AZIENDA
    , COD_CONTO
    , COD_CATEGORIA
    , D_GRAN_CAL
    , GRP_SCOPE
    , CUST_CODE
    , CUST_NAME
    , CUST_HEAD_CODE
    , CUST_HEAD_NAME
    , CUST_BRANCH_CODE
    , CUST_BRANCH_NAME
    , COD_AZI_CTP
    , COUNTRY_NAME
    , NATURE_L2_NAME
    , D_CHANNEL
    , D_ONOFFLINE
    , COD_DEST2
    , COD_DEST3
    , D_SALE_DEPT
    , D_CHANNEL_BU
    , D_CC_CUSTGRP
    , COD_VALUTA
    , AR_AMT
    , REV_AMT
    , F1_ODUE_AMT
    , F2_EPAY_AMT
    , F3_ECR_AMT
    , F4_UREB_AMT
    , F5_UFEE_AMT
    , F6_INVSM_AMT
    , F7_GSUB_AMT
    , F8_ADJ_AMT
    , SRC_DETAIL
    , PROVENIENZA
    , DATEUPD
    , USERUPD
  )
  WITH
  /* 应收周转利润中心映射：batch1按公司+源利润中心（一公司一行），batch2仅按源利润中心，源利润中心去前导零匹配。
     ALTER BY 20261110 17:30 SHIQINGFENG.EX 利润中心映射改按AW_RUL_ARPPRC_000001，替换原DIM_RULE的BATCH_ID=2规则 */
  ARPPRC_RULE_1 AS (
    SELECT TRIM(COD_AZIENDA) AS COD_AZIENDA
        , NULLIF(LTRIM(TRIM(SRC_PROFITCENTER_CODE), '0'), '') AS SRC_PROFITCENTER_CODE
        , MAX(TRIM(COD_DEST2)) AS COD_DEST2
      FROM AW_RUL_ARPPRC_000001
    WHERE BATCH_ID = '1'
      AND VALID_FR <= V_YEARMONTH
      AND NVL(VALID_TO, '999999') >= V_YEARMONTH
    GROUP BY TRIM(COD_AZIENDA)
            , NULLIF(LTRIM(TRIM(SRC_PROFITCENTER_CODE), '0'), '')
  ),
  ARPPRC_RULE_2 AS (
    SELECT NULLIF(LTRIM(TRIM(SRC_PROFITCENTER_CODE), '0'), '') AS SRC_PROFITCENTER_CODE
        , MAX(TRIM(COD_DEST2)) AS COD_DEST2
      FROM AW_RUL_ARPPRC_000001
    WHERE BATCH_ID = '2'
      AND VALID_FR <= V_YEARMONTH
      AND NVL(VALID_TO, '999999') >= V_YEARMONTH
    GROUP BY NULLIF(LTRIM(TRIM(SRC_PROFITCENTER_CODE), '0'), '')
  ),
  /* ALTER BY 20261029 18:20 SHIQINGFENG.EX BATCH_ID=6规则先按公司主数据展开，事实侧等号关联且物料组为空不匹配。 */
  PROFIT_CENTER_RULE_6 AS (
    SELECT A.COD_AZIENDA AS COMPANY_CODE
        , TRIM(PM.MATERIAL_GROUP_CODE) AS MATERIAL_GROUP_CODE
        , MAX(PM.PROFITCENTER_CODE) AS PROFITCENTER_CODE
      FROM TGK_FIMA_HISENSE.DIM_RULE_FI_MR_AR_PROFIT_MAPPING PM
      JOIN (SELECT DISTINCT COD_AZIENDA
              FROM TGK_FIMA_HISENSE.AZIENDA) A
        ON A.COD_AZIENDA LIKE TRIM(PM.COMPANY_CODE)
    WHERE PM.BATCH_ID = 6
      AND NVL(TRIM(PM.MATERIAL_GROUP_CODE), 'ZZZZ') <> 'ZZZZ'
      AND PM.VALID_FR <= V_YEARMONTH
      AND NVL(PM.VALID_TO, '999999') >= V_YEARMONTH
    GROUP BY A.COD_AZIENDA
           , TRIM(PM.MATERIAL_GROUP_CODE)
  ),
  /* 周转事业部范围：仅保留当前期间AR_TOV_FLAG为Y的有效事业部。 */
  TOV_BG_SCOPE AS (
    SELECT DISTINCT C.COD_BG
      FROM TGK_FIMA_HISENSE.AW_RUL_COSMAP_000001 C
    WHERE C.AR_TOV_FLAG = 'Y'
      AND C.VALID_FR <= V_YEARMONTH
      AND NVL(C.VALID_TO, '999999') >= V_YEARMONTH
  ),
  /* 账套事业部映射：公司事业部必须属于有效周转事业部范围。 */
  ATS_BG_MAP AS (
    SELECT A.COD_AZIENDA
        , A.COD_BG
      FROM TGK_FIMA_HISENSE.AW_RUL_ATSMAP_000001 A
    WHERE A.VALID_FR <= V_YEARMONTH
      AND NVL(A.VALID_TO, '999999') >= V_YEARMONTH
      AND A.COD_BG IN (
          SELECT COD_BG
            FROM TOV_BG_SCOPE
      )
      AND A.COD_BG NOT LIKE 'CXC%'
      AND (P_BG = 'ALL'
          OR INSTR(',' || P_BG || ',', ',' || A.COD_BG || ',') > 0)
  ),
  /* 利润中心所属事业部映射：保留利润中心在P_BG范围内匹配到的全部事业部，最终与公司事业部比较。
     配置表存在同一利润中心+事业部重复维护行，去重防止映射阶段整行翻倍。
     ALTER BY 20261109 18:22 SHIQINGFENG.EX 利润中心事业部映射去重，避免配置重复行导致金额翻倍 */
  PCR_BG_MAP AS (
    SELECT DISTINCT LTRIM(TRIM(P.COD_DEST2), '0') AS COD_DEST2
        , P.COD_BG
      FROM TGK_FIMA_HISENSE.AW_RUL_PCRMAP_000001 P
    WHERE P.VALID_FR <= V_YEARMONTH
      AND NVL(P.VALID_TO, '999999') >= V_YEARMONTH
      AND P.COD_BG IN (
          SELECT COD_BG
            FROM TOV_BG_SCOPE
      )
      AND P.COD_BG NOT LIKE 'CXC%'
      AND (
            P_BG = 'ALL'
          OR INSTR(',' || P_BG || ',', ',' || P.COD_BG || ',') > 0
      )
  ),
  /* 商冷客户群：无需有效期字段的维表按公司、客商归并。 */
  CUSTOMER_CC_MAP AS (
    SELECT LTRIM(TRIM(CUST_SAP_CODE), '0') AS CUST_SAP_CODE
        , LTRIM(TRIM(COMPANY_CODE_MDG), '0') AS COMPANY_CODE_MDG
        , MAX(CRG_CUST_GROUP_CODE) AS CRG_CUST_GROUP_CODE
      FROM DIM_CUSTOMER_COMPANY_INFO_DD
    WHERE CRG_CUST_GROUP_CODE IS NOT NULL
    GROUP BY LTRIM(TRIM(CUST_SAP_CODE), '0')
            , LTRIM(TRIM(COMPANY_CODE_MDG), '0')
  ),
  /* 周转渠道规则一：按公司、客商匹配。 */
  TOV_CHANNEL_RULE_1 AS (
    SELECT COMPANY_CODE
        , LTRIM(TRIM(CUST_CODE), '0') AS CUST_CODE
        , MAX(TOV_CHANNEL_CODE) AS TOV_CHANNEL_CODE
      FROM DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING
    WHERE BATCH_ID = 1
      AND VALID_FR <= V_YEARMONTH
      AND NVL(VALID_TO, '999999') >= V_YEARMONTH
    GROUP BY COMPANY_CODE
            , LTRIM(TRIM(CUST_CODE), '0')
  ),
  /* 周转渠道规则二：按公司、三级渠道匹配。 */
  TOV_CHANNEL_RULE_2 AS (
    SELECT COMPANY_CODE
        , CHANNEL_L3_CODE
        , MAX(TOV_CHANNEL_CODE) AS TOV_CHANNEL_CODE
      FROM DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING
    WHERE BATCH_ID = 2
      AND VALID_FR <= V_YEARMONTH
      AND NVL(VALID_TO, '999999') >= V_YEARMONTH
    GROUP BY COMPANY_CODE
            , CHANNEL_L3_CODE
  ),
  /* ALTER BY 20261102 15:00 SHIQINGFENG.EX 1030新增渠道BU：按三级公司分类映射渠道BU（com_3rd_code = channel_l3_code）。 */
  CHANNEL_BU_RULE AS (
    SELECT COM_3RD_CODE AS CHANNEL_L3_CODE
         , MAX(CHANNEL_BU_CODE) AS CHANNEL_BU_CODE
      FROM DIM_RULE_MRS_MR3_CHANNEL_BU_RELATION
     GROUP BY COM_3RD_CODE
  ),
  /* DEST3层级：仅收入未匹配时使用其自身国家名称维度。 */
  DEST3_COUNTRY_MAP AS (
    SELECT COD_DEST3
        , NVL(NVL(DESC_DEST3_ELEGER3, DESC_DEST3_ELEGER4), DESC_DEST3_ELEGER5) AS COUNTRY_NAME
      FROM TGK_FIMA_HISENSE.DEST3_GERARCHIA_FLAT
    WHERE COD_DEST3_GERARCHIA = '01'
  ),
  /* 当前场景期间的公司节点关系，保留收入集团归属范围计算口径。 */
  NODE_MAP AS (
    SELECT N.COD_SCENARIO
        , N.COD_PERIODO
        , N.ELEM
        , N.NODE
        , N.NODES
        , CASE WHEN H.ELEM IS NOT NULL THEN 1 ELSE 0 END AS IS_HITACHI
        , CASE WHEN H.ELEM IS NOT NULL THEN NVL(N.NODES, N.NODE) ELSE N.NODE END AS SELF_NODE
        , N.HQ
      FROM TGK_GB_HISENSE.V_APAR_ELEM_NODE_TAB N
      LEFT JOIN (
        SELECT DISTINCT ELEM
          FROM TGK_GB_HISENSE.V_REF_AZIENDA_TV
        WHERE COD_SCENARIO = V_SCENARIO
          AND COD_PERIODO = V_PERIODO
          AND HIE = '30'
          AND NODE = '1730'
      ) H
        ON H.ELEM = N.ELEM
    WHERE N.COD_SCENARIO = V_SCENARIO
      AND N.COD_PERIODO = V_PERIODO
  ),
  /* ARPM01调整汇总：按场景、期间、公司、客商和利润中心聚合因素7、因素8，避免原表多行导致ARPM02重复。 */
  ARPM01_ADJ_SUM AS (
    SELECT A.COD_SCENARIO
        , A.COD_PERIODO
        , A.COD_AZIENDA
        , TRIM(A.CUST_CODE) AS CUST_CODE
        , TRIM(A.COD_DEST2) AS COD_DEST2
        , SUM(CASE WHEN A.D_ADJ_TYPE = 'ARP_03_001' THEN NVL(A.BCY_0_AMT, 0) ELSE 0 END) AS F7_GSUB_AMT
        , SUM(CASE WHEN A.D_ADJ_TYPE = 'ARP_03_002' THEN NVL(A.BCY_0_AMT, 0) ELSE 0 END) AS F8_ADJ_AMT
      FROM AW_MR9_ARPM01_000001 A
    WHERE A.COD_SCENARIO = V_SCENARIO
      AND A.COD_PERIODO = V_PERIODO
      AND A.COD_AZIENDA IN (
          SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID
      )
      /* 仅取ZFAMOUNT类别及周转因素7、因素8对应的调整类型。 */
      AND A.COD_CATEGORIA = 'ZFAMOUNT'
      AND A.D_ADJ_TYPE IN ('ARP_03_001', 'ARP_03_002')
    GROUP BY A.COD_SCENARIO
            , A.COD_PERIODO
            , A.COD_AZIENDA
            , TRIM(A.CUST_CODE)
            , TRIM(A.COD_DEST2)
  ),
  /* ARPM02来源：单次读取，根据ME_AGE_FLAG、MB_AGE_FLAG判断生成ZAMOUNT或ZAMOUNT_L2。 */
  ARPM02_SOURCE AS (
    SELECT A.COD_SCENARIO
        , A.COD_PERIODO
        , A.COD_AZIENDA
        , '1122000000' AS COD_CONTO
        , CASE
              WHEN A.ME_AGE_FLAG IN ('AR', 'CA', 'A10') THEN 'ZAMOUNT'
              WHEN A.MB_AGE_FLAG IN ('AR', 'CA', 'A10') THEN 'ZAMOUNT_L2'
          END AS COD_CATEGORIA
        , A.GRP_SCOPE
        , TRIM(A.CUST_CODE) AS CUST_CODE
        , A.CUST_NAME
        , A.CUST_HEAD_CODE
        , A.CUST_HEAD_NAME
        , A.CUST_BRANCH_CODE
        , A.CUST_BRANCH_NAME
        , A.COD_AZI_CTP
        , A.COUNTRY_NAME
        , A.NATURE_L2_NAME
        , A.D_CHANNEL
        , A.D_ONOFFLINE
        /* 账龄利润中心按ARPPRC映射：batch1公司+源利润中心 > batch2源利润中心 > 原值。
           ALTER BY 20261110 17:30 SHIQINGFENG.EX 新增ARPPRC利润中心映射 */
        , NVL(P1.COD_DEST2, NVL(P2.COD_DEST2, A.COD_DEST2)) AS COD_DEST2
        , A.COD_DEST3
        , A.D_SALE_DEPT
        , A.D_CHANNEL_BU
        , A.D_CC_CUSTGRP
        , A.COD_VALUTA
        /* ALTER BY 20261110 11:25 SHIQINGFENG.EX 050节点判断由逐行EXISTS改为LEFT JOIN会话表去重结果集。 */
