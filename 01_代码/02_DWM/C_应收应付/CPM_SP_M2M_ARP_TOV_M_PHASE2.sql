         , NVL(M.COUNTRY_NAME, 'ZZZZ') AS COUNTRY_NAME
         , M.NATURE_L2_NAME
         , NVL(M.D_CHANNEL, 'ZZZZ') AS D_CHANNEL
         , NVL(M.D_ONOFFLINE, 'ZZZZ') AS D_ONOFFLINE
         , NVL(M.COD_DEST2, 'ZZZZ') AS COD_DEST2
         , NVL(M.COD_DEST3, 'ZZZZ') AS COD_DEST3
         , NVL(M.D_SALE_DEPT, 'ZZZZ') AS D_SALE_DEPT
         , NVL(M.D_TOV_CHAN, 'ZZZZ') AS D_TOV_CHAN
         , NVL(M.D_CC_CUSTGRP, 'ZZZZ') AS D_CC_CUSTGRP
         , NVL(M.COD_VALUTA, 'CNY') AS COD_VALUTA
         , M.AR_AMT
         , M.REV_AMT
         , M.F1_ODUE_AMT
         , M.F2_EPAY_AMT
         , M.F3_ECR_AMT
         , M.F4_UREB_AMT
         , M.F5_UFEE_AMT
         , M.F6_INVSM_AMT
         , M.F7_GSUB_AMT
         , M.F8_ADJ_AMT
      FROM MERGED_FACT M
