 * 脚本名称  ：SESSION_AZIENDA_LIST_HIE字段变更.sql
 * 功能描述  ：为公司会话表增加组织层级、组织节点和锁定标识字段，重复执行时不重复加列。
 * 源表      ：ALL_TAB_COLUMNS
 * 目标表    ：SESSION_AZIENDA_LIST
 *
 * 修改历史：
 *   ALTER BY 20261123 11:35 SHIQINGFENG.EX 新增HIE、NODE和LOCK_FLAG字段。
 ******************************************************************************/
DECLARE
  V_HIE_COUNT       NUMBER;
  V_NODE_COUNT      NUMBER;
  V_LOCK_FLAG_COUNT NUMBER;
BEGIN
  SELECT COUNT(CASE WHEN COLUMN_NAME = 'HIE' THEN 1 END) AS HIE_COUNT
       , COUNT(CASE WHEN COLUMN_NAME = 'NODE' THEN 1 END) AS NODE_COUNT
       , COUNT(CASE WHEN COLUMN_NAME = 'LOCK_FLAG' THEN 1 END) AS LOCK_FLAG_COUNT
    INTO V_HIE_COUNT
       , V_NODE_COUNT
       , V_LOCK_FLAG_COUNT
    FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'TGK_FIMA_HISENSE'
     AND TABLE_NAME = 'SESSION_AZIENDA_LIST';

  /* 字段类型沿用SESSION_V_REF_AZIENDA，LOCK_FLAG默认Y以兼容其他过程。
     ALTER BY 20261123 11:35 SHIQINGFENG.EX 新增HIE、NODE和LOCK_FLAG字段 */
  IF V_HIE_COUNT = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE TGK_FIMA_HISENSE.SESSION_AZIENDA_LIST ADD HIE VARCHAR2(10)';
  ELSE
    EXECUTE IMMEDIATE 'ALTER TABLE TGK_FIMA_HISENSE.SESSION_AZIENDA_LIST MODIFY (HIE DEFAULT NULL)';
  END IF;

  IF V_NODE_COUNT = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE TGK_FIMA_HISENSE.SESSION_AZIENDA_LIST ADD NODE VARCHAR2(10)';
  END IF;

  IF V_LOCK_FLAG_COUNT = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE TGK_FIMA_HISENSE.SESSION_AZIENDA_LIST ADD LOCK_FLAG VARCHAR2(1) DEFAULT ''Y''';
  ELSE
    EXECUTE IMMEDIATE 'ALTER TABLE TGK_FIMA_HISENSE.SESSION_AZIENDA_LIST MODIFY (LOCK_FLAG DEFAULT ''Y'')';
  END IF;
END;
/

COMMENT ON COLUMN TGK_FIMA_HISENSE.SESSION_AZIENDA_LIST.HIE IS '公司组织层级';
COMMENT ON COLUMN TGK_FIMA_HISENSE.SESSION_AZIENDA_LIST.NODE IS '公司组织节点';
COMMENT ON COLUMN TGK_FIMA_HISENSE.SESSION_AZIENDA_LIST.LOCK_FLAG IS '锁定标识：Y-LOCK，N-UNLOCK';
