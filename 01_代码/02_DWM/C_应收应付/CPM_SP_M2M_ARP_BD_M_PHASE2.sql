                      , R.LOGIC_NAME, R.CUST_CODE, R.CUST_NAME, R.NATURE_L3_NAME
                      , R.BD_RATIO_1 DESC, R.BD_RATIO_2 DESC, R.BD_RATIO_3 DESC
                      , R.BD_RATIO_4 DESC, R.BD_RATIO_5 DESC, R.BD_RATIO_6 DESC
                      , R.BD_RATIO_7 DESC, R.BD_RATIO_8 DESC, R.BD_RATIO_9 DESC
                ) RATE_RN
            FROM RATE_COMPANY_SOURCE A
            JOIN RULE_SOURCE R
              ON R.COD_AZIENDA = A.RATE_COD_AZIENDA
             AND R.COD_CONTO = A.COD_CONTO
             AND SUBSTR(R.GRP_SCOPE, 1, 3) = SUBSTR(A.GRP_SCOPE, 1, 3)
             AND (
                  (R.BATCH_ID = 1
                   AND R.CUST_CODE IS NOT NULL
                   AND R.CUST_CODE = A.CUST_CODE)
               OR (R.BATCH_ID = 2
                   AND R.CUST_CODE IS NULL
                   AND R.NATURE_L3_NAME IS NOT NULL
                   AND R.NATURE_L3_NAME = A.NATURE_L3_NAME)
               OR (R.BATCH_ID = 3
                   AND R.CUST_CODE IS NULL
                   AND R.NATURE_L3_NAME IS NULL)
             )
        ) R
       WHERE R.RATE_RN = 1
    ),
    /* 按OID和科目关联唯一有效比例配置，避免配置重叠时放大目标行。 */
    FORM_RATE_SELECTED AS (
      SELECT OID, COD_AZIENDA, COD_CONTO
