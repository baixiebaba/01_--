          , NVL(INDIVIDUAL_DATA.SPID_3_AMT,0) INDIVIDUAL_3_AMT, NVL(INDIVIDUAL_DATA.SPID_4_AMT,0) INDIVIDUAL_4_AMT
          , NVL(INDIVIDUAL_DATA.SPID_5_AMT,0) INDIVIDUAL_5_AMT, NVL(INDIVIDUAL_DATA.SPID_6_AMT,0) INDIVIDUAL_6_AMT
          , NVL(INDIVIDUAL_DATA.SPID_7_AMT,0) INDIVIDUAL_7_AMT, NVL(INDIVIDUAL_DATA.SPID_8_AMT,0) INDIVIDUAL_8_AMT
          , NVL(INDIVIDUAL_DATA.SPID_9_AMT,0) INDIVIDUAL_9_AMT, NVL(INDIVIDUAL_DATA.SPID_10_AMT,0) INDIVIDUAL_10_AMT
          , NVL(INDIVIDUAL_DATA.SPID_11_AMT,0) INDIVIDUAL_11_AMT, NVL(INDIVIDUAL_DATA.SPID_12_AMT,0) INDIVIDUAL_12_AMT
          , NVL(INDIVIDUAL_DATA.SPID_13_AMT,0) INDIVIDUAL_13_AMT, NVL(INDIVIDUAL_DATA.SPID_14_AMT,0) INDIVIDUAL_14_AMT
          , NVL(INDIVIDUAL_DATA.SPID_15_AMT,0) INDIVIDUAL_15_AMT
          , NVL(FORM_RATE.BD_RATIO_1,0) BD_RATIO_1, NVL(FORM_RATE.BD_RATIO_2,0) BD_RATIO_2
          , NVL(FORM_RATE.BD_RATIO_3,0) BD_RATIO_3, NVL(FORM_RATE.BD_RATIO_4,0) BD_RATIO_4
          , NVL(FORM_RATE.BD_RATIO_5,0) BD_RATIO_5, NVL(FORM_RATE.BD_RATIO_6,0) BD_RATIO_6
          , NVL(FORM_RATE.BD_RATIO_7,0) BD_RATIO_7, NVL(FORM_RATE.BD_RATIO_8,0) BD_RATIO_8
          , NVL(FORM_RATE.BD_RATIO_9,0) BD_RATIO_9
        FROM CALCULATION_SOURCE A
        LEFT JOIN (
          SELECT COD_AZIENDA, COD_CONTO, CUST_CODE, COD_DEST2, NATURE_L3_NAME
              , COUNT(*) HAS_INDIVIDUAL
              , SUM(SPID_1_AMT) SPID_1_AMT, SUM(SPID_2_AMT) SPID_2_AMT, SUM(SPID_3_AMT) SPID_3_AMT
              , SUM(SPID_4_AMT) SPID_4_AMT, SUM(SPID_5_AMT) SPID_5_AMT, SUM(SPID_6_AMT) SPID_6_AMT
              , SUM(SPID_7_AMT) SPID_7_AMT, SUM(SPID_8_AMT) SPID_8_AMT, SUM(SPID_9_AMT) SPID_9_AMT
              , SUM(SPID_10_AMT) SPID_10_AMT, SUM(SPID_11_AMT) SPID_11_AMT, SUM(SPID_12_AMT) SPID_12_AMT
              , SUM(SPID_13_AMT) SPID_13_AMT, SUM(SPID_14_AMT) SPID_14_AMT, SUM(SPID_15_AMT) SPID_15_AMT
            FROM AW_MR9_ARPM02_000001
           WHERE COD_SCENARIO = V_SCENARIO
             AND COD_PERIODO = V_PERIODO
             AND COD_AZIENDA IN (
                   SELECT ELEM
                     FROM SESSION_AZIENDA_LIST
                    WHERE SESSION_ID = V_SESSION_ID
             )
             AND COD_CATEGORIA = 'ZFAMOUNT'
             AND D_ADJ_TYPE = 'ARP_02_002'
          GROUP BY COD_AZIENDA, COD_CONTO, CUST_CODE, COD_DEST2, NATURE_L3_NAME
        ) INDIVIDUAL_DATA ON INDIVIDUAL_DATA.COD_AZIENDA = A.COD_AZIENDA AND INDIVIDUAL_DATA.COD_CONTO = A.COD_CONTO AND INDIVIDUAL_DATA.CUST_CODE = A.CUST_CODE
          AND INDIVIDUAL_DATA.COD_DEST2 = A.COD_DEST2 AND INDIVIDUAL_DATA.NATURE_L3_NAME = A.NATURE_L3_NAME
        LEFT JOIN FORM_RATE_SELECTED FORM_RATE ON FORM_RATE.OID = A.OID
          AND FORM_RATE.COD_CONTO = A.COD_CONTO
    ),
    /* 根据个别认定金额、规则比例和投保未覆盖系数计算1至15账龄坏账。 */
    BAD_DEBT_CALCULATION AS (
      SELECT CALCULATION_BASE.*
          , CASE WHEN HAS_INDIVIDUAL = 1 THEN INDIVIDUAL_1_AMT ELSE BD_BASE_1_AMT * NVL(BD_RATIO_1,0) * CASE WHEN NVL(INS_COV_DAYS,0) <= 0 THEN 1 WHEN INS_COV_DAYS <= 30 THEN NVL(INS_UNCOV_RATE,1) ELSE 0 END END CALCULATED_1_AMT
