CREATE OR REPLACE PROCEDURE CPM_SP_M2M_ARP_BD_M_PHASE2(
    P_SCENARIO   IN VARCHAR2
  , P_PERIODO    IN VARCHAR2
  , P_AZIENDA    IN VARCHAR2
  , SESSION_USER IN VARCHAR2
) AS
  /*******************************************************************************
   *                              存储过程说明
   *-----------------------------------------------------------------------------
   * 最后更新时间：20261105 18:25
   * 本次修改：ALTER BY 20261105 18:25 SHIQINGFENG.EX STEP1负数改为行内优先冲减，行内冲不掉的再跨利润中心按账龄从远到近分配，冲不完落账龄1
   * 上次修改：ALTER BY 20261105 18:00 SHIQINGFENG.EX 修正STEP1冲不掉的负数回填符号，原写法把负数当正数加回计提基数
   *
   * 过程名称  ：CPM_SP_M2M_ARP_BD_M_PHASE2
   * 功能描述  ：按STEP1坏账计提基数、STEP2坏账计算、STEP3坏账分摊三步加工ARPM02坏账表
   * 源表      ：AW_MR9_ARPM01_000001、AW_MR9_ARPM02_000001、AW_MR6_ARPINS_000001、AW_RUL_ARPBDR_000001、DWD_FI_MR_ARAP_SUM_MI
   * 目标表    ：AW_MR9_ARPM02_000001
   *
   * 修改历史：
   *   ALTER BY 20261105 18:25 SHIQINGFENG.EX STEP1负数改为行内优先冲减，行内冲不掉的再跨利润中心按账龄从远到近分配，冲不完落账龄1
   *   ALTER BY 20261105 18:00 SHIQINGFENG.EX 修正STEP1冲不掉的负数回填符号，原写法把负数当正数加回计提基数
   *   ALTER BY 20261105 17:35 SHIQINGFENG.EX STEP1改为明细行内冲减，冲不掉的负数保留原账龄段
   *   ALTER BY 20261026 16:35 SHIQINGFENG.EX STEP2 坏账比例按组织架构优先映射维护公司
   *   20261018 STEP2 个别认定来源改用ARPM02的SPID字段并限定ZAMOUNT目标类别
   *   20261017 STEP2 个别认定前增加来源存在性判断，无来源时跳过聚合查询
   *   20261016 STEP2 规则有效期和批次过滤前置，STEP1减少重复扫描
   *   20261015 STEP2 个别认定聚合补充来源公司范围过滤
   *   20261014 STEP2 个别认定来源前置场景、期间、公司及业务类型过滤
   *   20261013 STEP2 坏账金额BD_1_AMT至BD_15_AMT统一保留两位小数
   *   20261012 STEP2 配置表按客商、科目匹配并去重，MERGE ON仅按OID
   *   20261011 STEP1至STEP3按公司、客商、科目粒度处理，MERGE ON统一按OID
   *   20261010 STEP1 按公司、客商、科目粒度执行FIFO并回写
   *   20261009 修复STEP1多明细行账龄累计重复导致FIFO扣减放大
   *   20261009 按真实配置表结构修正STEP2客户匹配、有效期及1-9比例
   *   20261009 修复公司范围空值判断及STEP2账龄基数字段覆盖
   *   20261009 按三个坏账设计页修复规则表、返利扣减、1-15账龄、个别认定状态、重跑清零及异常边界
   *   20261008 STEP3 账龄分摊合计改为汇总各账龄分摊金额，并在S查询中统一计算回写
   *   20261008 日志按STEP1、STEP2、STEP3分段记录，成功路径统一提交
   *   20261008 按最新设计文档合并坏账STEP1、STEP2、STEP3
   *   20261008 新增ARPM02坏账计算表STEP2坏账计算过程
   *******************************************************************************/
  V_SCENARIO       VARCHAR2(30);
  V_PERIODO        VARCHAR2(30);
  V_YEARMONTH      VARCHAR2(10);
  V_PREV_YEARMONTH VARCHAR2(10);
  V_LM_SCENARIO    VARCHAR2(30);
  V_LM_PERIODO     VARCHAR2(2);
  V_AZIENDA        VARCHAR2(4000);
  V_SESSION_ID     NUMBER;
  V_HAS_INDIVIDUAL NUMBER;
  V_ERROR_COD      NUMBER;
  V_ERROR_MSG      VARCHAR2(4000);
BEGIN
  V_SESSION_ID := SYS_CONTEXT('USERENV', 'SESSIONID');
  V_SCENARIO := P_SCENARIO;
  V_PERIODO := LPAD(P_PERIODO, 2, '0');
  V_YEARMONTH := SUBSTR(V_SCENARIO, 1, 4) || V_PERIODO;
  V_PREV_YEARMONTH := TO_CHAR(ADD_MONTHS(TO_DATE(V_YEARMONTH || '01', 'YYYYMMDD'), -1), 'YYYYMM');
  V_LM_SCENARIO := SUBSTR(V_PREV_YEARMONTH, 1, 4) || SUBSTR(V_SCENARIO, 5);
  V_LM_PERIODO := SUBSTR(V_PREV_YEARMONTH, 5, 2);

  /* 清理本会话遗留数据，不影响其他会话。 */
  DELETE FROM SESSION_AZIENDA_LIST
   WHERE SESSION_ID = V_SESSION_ID;

  DELETE FROM SESSION_V_REF_AZIENDA
   WHERE SESSION_ID = V_SESSION_ID;

  INSERT INTO SESSION_V_REF_AZIENDA (SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, HIE, NODE, ELEM
    FROM TGK_FIMA_HISENSE.V_REF_AZIENDA;

  /* 按公司参数收集本级组织节点，仅保留本期D2M已锁定的公司。 */
  INSERT INTO SESSION_AZIENDA_LIST (SESSION_ID, ELEM)
  SELECT DISTINCT V_SESSION_ID, ELEM
    FROM SESSION_V_REF_AZIENDA
   WHERE HIE = '10'
     AND (INSTR(',' || P_AZIENDA || ',', ',' || ELEM || ',') > 0
       OR INSTR(',' || P_AZIENDA || ',', ',' || NODE || ',') > 0
       OR P_AZIENDA = 'ALL')
     AND ELEM IN (
           SELECT COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001
            WHERE ARP_FLAG = 'Y'
              AND VALID_FR <= V_YEARMONTH
              AND NVL(VALID_TO, '999999') >= V_YEARMONTH
              AND COD_CONTO = 'ZAW_D2M_IN'
     );

  /* 汇总本会话公司清单，供日志记录。 */
  SELECT LISTAGG(ELEM, ',') WITHIN GROUP (ORDER BY ELEM)
    INTO V_AZIENDA
    FROM (
      SELECT DISTINCT ELEM
        FROM SESSION_AZIENDA_LIST
       WHERE SESSION_ID = V_SESSION_ID
    );

  INSERT INTO ZTAB_CPM_LOG (CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA)
  VALUES ('CPM_SP_M2M_ARP_BD_M_PHASE2', 'BEGIN 开始执行', SYSDATE, SESSION_USER, V_SCENARIO, V_PERIODO, V_AZIENDA);
  COMMIT;

  /* STEP1：坏账计提基数——以BCY_ADJ_INCL_1~15为账龄基础，垫资从长账龄开始冲减；
     负数先在本行内从远账龄到近账龄冲正数，本行冲不掉的剩余再跨利润中心按同样顺序分配，仍冲不完的落账龄1。
     ALTER BY 20261105 18:25 SHIQINGFENG.EX STEP1负数改为行内优先冲减，行内冲不掉的再跨利润中心分配 */
  MERGE INTO AW_MR9_ARPM02_000001 T
  USING (
    WITH
    /* 当前期间目标表行及垫资、投保信息。 */
    BASE_DATA AS (
      SELECT A.OID, A.COD_AZIENDA, A.CUST_CODE, A.COD_CONTO, A.COD_DEST2
          , A.CUST_HEAD_KEY
          , A.COD_CATEGORIA
          , A.BCY_ADJ_INCL_1_AMT, A.BCY_ADJ_INCL_2_AMT, A.BCY_ADJ_INCL_3_AMT
          , A.BCY_ADJ_INCL_4_AMT, A.BCY_ADJ_INCL_5_AMT, A.BCY_ADJ_INCL_6_AMT
          , A.BCY_ADJ_INCL_7_AMT, A.BCY_ADJ_INCL_8_AMT, A.BCY_ADJ_INCL_9_AMT
          , A.BCY_ADJ_INCL_10_AMT, A.BCY_ADJ_INCL_11_AMT, A.BCY_ADJ_INCL_12_AMT
          , A.BCY_ADJ_INCL_13_AMT, A.BCY_ADJ_INCL_14_AMT, A.BCY_ADJ_INCL_15_AMT
          , NVL(DR.SPC_DSV_DED_AMT, 0) AS SPC_DSV_DED_AMT
          , NVL(DR.SPC_REB_DED_AMT, 0) AS SPC_REB_DED_AMT
          , I.INS_COV_DAYS, I.INS_UNCOV_RATIO
        FROM (
          SELECT OID, COD_AZIENDA, CUST_CODE, COD_CONTO, COD_DEST2
              , COD_CATEGORIA, BCY_ADJ_INCL_1_AMT, BCY_ADJ_INCL_2_AMT, BCY_ADJ_INCL_3_AMT
              , BCY_ADJ_INCL_4_AMT, BCY_ADJ_INCL_5_AMT, BCY_ADJ_INCL_6_AMT, BCY_ADJ_INCL_7_AMT
              , BCY_ADJ_INCL_8_AMT, BCY_ADJ_INCL_9_AMT, BCY_ADJ_INCL_10_AMT, BCY_ADJ_INCL_11_AMT
              , BCY_ADJ_INCL_12_AMT, BCY_ADJ_INCL_13_AMT, BCY_ADJ_INCL_14_AMT, BCY_ADJ_INCL_15_AMT
              , NVL(NULLIF(TRIM(CUST_HEAD_CODE), ''), CUST_CODE) CUST_HEAD_KEY
            FROM AW_MR9_ARPM02_000001
           WHERE COD_SCENARIO = V_SCENARIO
             AND COD_PERIODO = V_PERIODO
             AND COD_AZIENDA IN (SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID)
        ) A
        LEFT JOIN (
          SELECT COD_AZIENDA, COD_CONTO, CUST_CODE, COD_DEST2
              , SUM(CASE WHEN D_ADJ_TYPE = 'ARP_02_001' THEN BCY_0_AMT ELSE 0 END) SPC_DSV_DED_AMT
              , SUM(CASE WHEN D_ADJ_TYPE = 'ARP_02_003' THEN BCY_0_AMT ELSE 0 END) SPC_REB_DED_AMT
            FROM AW_MR9_ARPM01_000001
           WHERE COD_SCENARIO = V_SCENARIO
             AND COD_PERIODO = V_PERIODO
             AND COD_AZIENDA IN (SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID)
             AND COD_CATEGORIA = 'ZFAMOUNT'
             AND D_ADJ_TYPE IN ('ARP_02_001', 'ARP_02_003')
           GROUP BY COD_AZIENDA, COD_CONTO, CUST_CODE, COD_DEST2
        ) DR ON DR.COD_AZIENDA = A.COD_AZIENDA
           AND DR.COD_CONTO = A.COD_CONTO
           AND DR.CUST_CODE = A.CUST_CODE
           AND DR.COD_DEST2 = A.COD_DEST2
        LEFT JOIN (
          SELECT COD_AZIENDA, COD_CONTO, CUST_CODE, MAX(INS_COV_DAYS) INS_COV_DAYS
              , MAX(INS_UNCOV_RATIO) INS_UNCOV_RATIO
            FROM AW_MR6_ARPINS_000001
          WHERE COD_SCENARIO = V_SCENARIO AND COD_PERIODO = V_PERIODO
            AND COD_AZIENDA IN (SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID)
          GROUP BY COD_AZIENDA, COD_CONTO, CUST_CODE
        ) I ON I.COD_AZIENDA = A.COD_AZIENDA AND I.COD_CONTO = A.COD_CONTO AND I.CUST_CODE = A.CUST_CODE
    ),
    /* 将各账龄列转为账龄编号和金额，便于统一执行长账龄优先规则。 */
    AGE_UNPIVOT AS (
      SELECT *
        FROM BASE_DATA
        UNPIVOT (RAW_AMT FOR AGE_NO IN (
          BCY_ADJ_INCL_1_AMT AS 1, BCY_ADJ_INCL_2_AMT AS 2, BCY_ADJ_INCL_3_AMT AS 3
        , BCY_ADJ_INCL_4_AMT AS 4, BCY_ADJ_INCL_5_AMT AS 5, BCY_ADJ_INCL_6_AMT AS 6
        , BCY_ADJ_INCL_7_AMT AS 7, BCY_ADJ_INCL_8_AMT AS 8, BCY_ADJ_INCL_9_AMT AS 9
        , BCY_ADJ_INCL_10_AMT AS 10, BCY_ADJ_INCL_11_AMT AS 11, BCY_ADJ_INCL_12_AMT AS 12
        , BCY_ADJ_INCL_13_AMT AS 13, BCY_ADJ_INCL_14_AMT AS 14, BCY_ADJ_INCL_15_AMT AS 15)) UNPIVOT_ROWS
    ),
    /* 按账龄倒序计算每行之前已占用的正数金额。 */
    AGE_PROGRESS AS (
      SELECT AGE_UNPIVOT.*, GREATEST(NVL(RAW_AMT, 0), 0) POS_AMT
          , SUM(GREATEST(NVL(RAW_AMT, 0), 0)) OVER
              (PARTITION BY OID, COD_CONTO ORDER BY AGE_NO DESC ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) PRIOR_POS
        FROM AGE_UNPIVOT
    ),
    /* 根据垫资金额计算各账龄段实际可扣减金额。 */
    DEDUCTED_AGE AS (
      SELECT AGE_PROGRESS.*, GREATEST(NVL(SPC_DSV_DED_AMT, 0) + NVL(SPC_REB_DED_AMT, 0) - NVL(PRIOR_POS, 0), 0) DED_LEFT
          , GREATEST(NVL(RAW_AMT, 0), 0)
            - LEAST(GREATEST(NVL(RAW_AMT, 0), 0), GREATEST(NVL(SPC_DSV_DED_AMT, 0) + NVL(SPC_REB_DED_AMT, 0) - NVL(PRIOR_POS, 0), 0)) ADJ_POS
        FROM AGE_PROGRESS
    ),
    /* 行内各账龄段正数，并带出本行的垫资与投保字段供回写。 */
    ROW_POS AS (
      SELECT COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO, OID, AGE_NO
          , SUM(ADJ_POS) ROW_AGE_POS
          , MAX(SPC_DSV_DED_AMT) SPC_DSV_DED_AMT
          , MAX(SPC_REB_DED_AMT) SPC_REB_DED_AMT
          , MAX(INS_COV_DAYS) INS_COV_DAYS
          , MAX(INS_UNCOV_RATIO) INS_UNCOV_RATIO
        FROM DEDUCTED_AGE
       GROUP BY COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO, OID, AGE_NO
    ),
    /* 行负数合计与本行可冲正数合计。 */
    ROW_NEG AS (
      SELECT COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO, OID
          , SUM(-LEAST(NVL(RAW_AMT, 0), 0)) ROW_NEG_AMT
          , SUM(ADJ_POS) ROW_POS_AMT
        FROM DEDUCTED_AGE
       GROUP BY COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO, OID
    ),
    /* 行内负数从远账龄到近账龄冲本行正数，记录累计可冲量与冲不掉的剩余。 */
    ROW_FILL AS (
      SELECT P.COD_AZIENDA, P.CUST_HEAD_KEY, P.COD_CONTO, P.OID, P.AGE_NO, P.ROW_AGE_POS
          , P.SPC_DSV_DED_AMT, P.SPC_REB_DED_AMT, P.INS_COV_DAYS, P.INS_UNCOV_RATIO
          , LEAST(N.ROW_NEG_AMT, N.ROW_POS_AMT) NEG_FILL
          , N.ROW_NEG_AMT - LEAST(N.ROW_NEG_AMT, N.ROW_POS_AMT) RESID_NEG
          , SUM(P.ROW_AGE_POS) OVER
              (PARTITION BY P.COD_AZIENDA, P.COD_CONTO, P.OID
                ORDER BY P.AGE_NO DESC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) POS_FAR
          , NVL(SUM(P.ROW_AGE_POS) OVER
              (PARTITION BY P.COD_AZIENDA, P.COD_CONTO, P.OID
                ORDER BY P.AGE_NO DESC ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0) POS_BEFORE
        FROM ROW_POS P
        JOIN ROW_NEG N
          ON N.COD_AZIENDA = P.COD_AZIENDA
         AND N.CUST_HEAD_KEY = P.CUST_HEAD_KEY
         AND N.COD_CONTO = P.COD_CONTO
         AND N.OID = P.OID
    ),
    /* 行内每段冲掉的负数，以及冲完后剩余的正数。 */
    ROW_ALLOC AS (
      SELECT F.COD_AZIENDA, F.CUST_HEAD_KEY, F.COD_CONTO, F.OID, F.AGE_NO, F.RESID_NEG
          , F.SPC_DSV_DED_AMT, F.SPC_REB_DED_AMT, F.INS_COV_DAYS, F.INS_UNCOV_RATIO
          , LEAST(F.NEG_FILL, F.POS_FAR) - LEAST(F.NEG_FILL, F.POS_BEFORE) ROW_ALLOC
          , F.ROW_AGE_POS - (LEAST(F.NEG_FILL, F.POS_FAR) - LEAST(F.NEG_FILL, F.POS_BEFORE)) POS_LEFT
        FROM ROW_FILL F
    ),
    /* 主户组内行内冲完后各账龄段剩余正数合计。 */
    GROUP_POS_LEFT AS (
      SELECT COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO, AGE_NO, SUM(POS_LEFT) GRP_POS_LEFT
        FROM ROW_ALLOC
       GROUP BY COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO, AGE_NO
    ),
    /* 主户组行内冲不掉的负数合计。 */
    GROUP_RESID AS (
      SELECT COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO, SUM(RESID_NEG) GRP_RESID
        FROM (SELECT DISTINCT COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO, OID, RESID_NEG FROM ROW_ALLOC)
       GROUP BY COD_AZIENDA, CUST_HEAD_KEY, COD_CONTO
    ),
    /* 剩余负数从远账龄到近账龄冲组内剩余正数，记录累计可冲量。 */
    GROUP_FILL_BASE AS (
      SELECT P.COD_AZIENDA, P.CUST_HEAD_KEY, P.COD_CONTO, P.AGE_NO, P.GRP_POS_LEFT, N.GRP_RESID
          , SUM(P.GRP_POS_LEFT) OVER
              (PARTITION BY P.COD_AZIENDA, P.CUST_HEAD_KEY, P.COD_CONTO
                ORDER BY P.AGE_NO DESC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) POS_FAR
          , NVL(SUM(P.GRP_POS_LEFT) OVER
              (PARTITION BY P.COD_AZIENDA, P.CUST_HEAD_KEY, P.COD_CONTO
                ORDER BY P.AGE_NO DESC ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0) POS_BEFORE
        FROM GROUP_POS_LEFT P
        JOIN GROUP_RESID N
          ON N.COD_AZIENDA = P.COD_AZIENDA
         AND N.CUST_HEAD_KEY = P.CUST_HEAD_KEY
         AND N.COD_CONTO = P.COD_CONTO
    ),
    /* 每段分到的剩余负数取累计增量，冲不完的落账龄1。
       ALTER BY 20261105 18:25 SHIQINGFENG.EX STEP1改为行内优先冲减，行内冲不掉的负数再跨利润中心按账龄从远到近分配 */
    GROUP_FILL AS (
      SELECT A.COD_AZIENDA, A.CUST_HEAD_KEY, A.COD_CONTO, A.AGE_NO, A.GRP_RESID
          , LEAST(A.GRP_RESID, A.POS_FAR) - LEAST(A.GRP_RESID, A.POS_BEFORE)
            + CASE WHEN A.AGE_NO = 1
                   THEN GREATEST(A.GRP_RESID - LEAST(A.GRP_RESID, A.POS_FAR), 0)
                   ELSE 0 END GRP_ALLOC
        FROM GROUP_FILL_BASE A
    ),
    /* 行内剩余正数再扣减跨行分到的负数，负数按各行剩余负数占比分摊。 */
    AGE_ALLOCATED AS (
      SELECT R.*
          , R.POS_LEFT - NVL(F.GRP_ALLOC * R.RESID_NEG / NULLIF(F.GRP_RESID, 0), 0) FINAL_AGE_POS
        FROM ROW_ALLOC R
        JOIN GROUP_FILL F
          ON F.COD_AZIENDA = R.COD_AZIENDA
         AND F.CUST_HEAD_KEY = R.CUST_HEAD_KEY
         AND F.COD_CONTO = R.COD_CONTO
         AND F.AGE_NO = R.AGE_NO
    ),
    /* 将账龄明细重新汇总为目标表的一行及各计提基数。 */
    BASE_RESULT AS (
      SELECT OID, COD_CONTO, MAX(SPC_DSV_DED_AMT) SPC_DSV_DED_AMT, MAX(SPC_REB_DED_AMT) SPC_REB_DED_AMT
          , MAX(INS_COV_DAYS) INS_COV_DAYS, MAX(INS_UNCOV_RATIO) INS_UNCOV_RATIO
          , SUM(CASE WHEN AGE_NO = 1 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_1_AMT
          , SUM(CASE WHEN AGE_NO = 2 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_2_AMT
          , SUM(CASE WHEN AGE_NO = 3 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_3_AMT
          , SUM(CASE WHEN AGE_NO = 4 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_4_AMT
          , SUM(CASE WHEN AGE_NO = 5 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_5_AMT
          , SUM(CASE WHEN AGE_NO = 6 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_6_AMT
          , SUM(CASE WHEN AGE_NO = 7 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_7_AMT
          , SUM(CASE WHEN AGE_NO = 8 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_8_AMT
          , SUM(CASE WHEN AGE_NO = 9 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_9_AMT
          , SUM(CASE WHEN AGE_NO = 10 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_10_AMT
          , SUM(CASE WHEN AGE_NO = 11 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_11_AMT
          , SUM(CASE WHEN AGE_NO = 12 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_12_AMT
          , SUM(CASE WHEN AGE_NO = 13 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_13_AMT
          , SUM(CASE WHEN AGE_NO = 14 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_14_AMT
          , SUM(CASE WHEN AGE_NO = 15 THEN FINAL_AGE_POS ELSE 0 END) BD_BASE_15_AMT
        FROM AGE_ALLOCATED GROUP BY OID, COD_CONTO
    ) SELECT BASE_RESULT.*, BD_BASE_1_AMT + BD_BASE_2_AMT + BD_BASE_3_AMT + BD_BASE_4_AMT
              + BD_BASE_5_AMT + BD_BASE_6_AMT + BD_BASE_7_AMT + BD_BASE_8_AMT
              + BD_BASE_9_AMT + BD_BASE_10_AMT + BD_BASE_11_AMT + BD_BASE_12_AMT
              + BD_BASE_13_AMT + BD_BASE_14_AMT + BD_BASE_15_AMT BD_BASE_0_AMT
