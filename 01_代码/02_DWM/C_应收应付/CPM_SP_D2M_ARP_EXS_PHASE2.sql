CREATE OR REPLACE PROCEDURE CPM_SP_D2M_ARP_EXS_PHASE2(
    P_SCENARIO   IN VARCHAR2
  , P_PERIODO    IN VARCHAR2
  , P_AZIENDA    IN VARCHAR2
  , SESSION_USER IN VARCHAR2
) AS
  /*******************************************************************************
   *                              存储过程说明
   *-----------------------------------------------------------------------------
   * 最后更新时间：20261105 16:33
   * 本次修改：ALTER BY 20261105 16:33 SHIQINGFENG.EX 新增公司抽取范围和锁定限制。
   * 上次修改：ALTER BY 20261105 15:59 SHIQINGFENG.EX 新增M01调整数据更新M02是否存续字段过程。
   *
   * 过程名称  ：CPM_SP_D2M_ARP_EXS_PHASE2
   * 功能描述  ：按公司和客商名称，将M01调整数据的IS_EXS更新至M02往来账龄结果表。
   * 源表      ：TGK_FIMA_HISENSE.V_REF_AZIENDA、TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001、TGK_FIMA_HISENSE.AW_MR9_ARPM01_000001
   * 目标表    ：TGK_FIMA_HISENSE.AW_MR9_ARPM02_000001
   *
   * 修改历史：
   *   ALTER BY 20261105 16:33 SHIQINGFENG.EX 新增公司抽取范围和锁定限制。
   *   ALTER BY 20261105 15:59 SHIQINGFENG.EX 新增M01调整数据更新M02是否存续字段过程。
   *******************************************************************************/
  V_SCENARIO   VARCHAR2(30);
  V_PERIODO    VARCHAR2(2);
  V_YEARMONTH  VARCHAR2(10);
  V_AZIENDA    VARCHAR2(4000);
  V_SESSION_ID NUMBER;

BEGIN
  V_SESSION_ID := SYS_CONTEXT('USERENV', 'SESSIONID');
  V_SCENARIO := P_SCENARIO;
  V_PERIODO := LPAD(P_PERIODO, 2, '0');
  V_YEARMONTH := SUBSTR(V_SCENARIO, 1, 4) || V_PERIODO;

  DELETE FROM SESSION_AZIENDA_LIST
   WHERE SESSION_ID = V_SESSION_ID;

  DELETE FROM SESSION_V_REF_AZIENDA
   WHERE SESSION_ID = V_SESSION_ID;

  INSERT INTO SESSION_V_REF_AZIENDA(SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, HIE, NODE, ELEM
    FROM TGK_FIMA_HISENSE.V_REF_AZIENDA;

  INSERT INTO SESSION_AZIENDA_LIST(SESSION_ID, ELEM)
  SELECT DISTINCT V_SESSION_ID
       , ELEM
    FROM SESSION_V_REF_AZIENDA
   WHERE SESSION_ID = V_SESSION_ID
     AND HIE = '10'
     AND (
           INSTR(',' || P_AZIENDA || ',', ',' || ELEM || ',') > 0
        OR INSTR(',' || P_AZIENDA || ',', ',' || NODE || ',') > 0
        OR P_AZIENDA = 'ALL'
     )
     /* 仅保留当前期间允许抽取且尚未锁定的公司。 */
     /* ALTER BY 20261105 16:33 SHIQINGFENG.EX 新增公司抽取范围和锁定限制。 */
     AND ELEM IN (
           SELECT COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001
            WHERE ARP_FLAG = 'Y'
              AND VALID_FR <= V_YEARMONTH
              AND NVL(VALID_TO, '999999') >= V_YEARMONTH
              AND COD_CONTO = 'ZAW_D2M_IN'
     )
     AND ELEM NOT IN (
           SELECT T.COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001 T
            WHERE T.ARP_FLAG = 'Y'
              AND T.COD_SCENARIO = V_SCENARIO
              AND T.COD_PERIODO = V_PERIODO
              AND T.COD_CONTO = 'ZAW_D2M_LOCK'
     );

  SELECT LISTAGG(ELEM, ',') WITHIN GROUP (ORDER BY ELEM)
    INTO V_AZIENDA
    FROM (
      SELECT DISTINCT ELEM
        FROM SESSION_AZIENDA_LIST
       WHERE SESSION_ID = V_SESSION_ID
    );

  INSERT INTO ZTAB_CPM_LOG(CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA)
  VALUES ('CPM_SP_D2M_ARP_EXS_PHASE2', '开始运行', SYSDATE, SESSION_USER, V_SCENARIO, V_PERIODO, V_AZIENDA);
  COMMIT;

  /* 按公司和客商名称更新M02存续标识。 */
  /* ALTER BY 20261105 15:59 SHIQINGFENG.EX 新增M01调整数据更新M02是否存续字段过程。 */
  BEGIN
    MERGE INTO TGK_FIMA_HISENSE.AW_MR9_ARPM02_000001 T
    USING (
      SELECT DISTINCT A.COD_AZIENDA
           , A.CUST_NAME
           , A.IS_EXS
        FROM TGK_FIMA_HISENSE.AW_MR9_ARPM02_000001 A
       WHERE A.COD_SCENARIO = V_SCENARIO
         AND A.COD_PERIODO = V_PERIODO
         AND A.COD_AZIENDA IN (
               SELECT ELEM
                 FROM SESSION_AZIENDA_LIST
                WHERE SESSION_ID = V_SESSION_ID
         )
         AND A.CUST_NAME IS NOT NULL
         AND A.IS_EXS IS NOT NULL
    ) S
       ON (
              T.COD_SCENARIO = V_SCENARIO
          AND T.COD_PERIODO = V_PERIODO
          AND T.COD_AZIENDA = S.COD_AZIENDA
          AND T.CUST_NAME = S.CUST_NAME
       )
     WHEN MATCHED THEN
          UPDATE
             SET T.IS_EXS = S.IS_EXS
               , T.USERUPD = SESSION_USER
               , T.DATEUPD = SYSDATE
          ;
  END;

  DELETE FROM SESSION_AZIENDA_LIST
   WHERE SESSION_ID = V_SESSION_ID;

  DELETE FROM SESSION_V_REF_AZIENDA
   WHERE SESSION_ID = V_SESSION_ID;

  INSERT INTO ZTAB_CPM_LOG(CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA)
  VALUES ('CPM_SP_D2M_ARP_EXS_PHASE2', '运行成功', SYSDATE, SESSION_USER, V_SCENARIO, V_PERIODO, V_AZIENDA);
  COMMIT;

END CPM_SP_D2M_ARP_EXS_PHASE2;
