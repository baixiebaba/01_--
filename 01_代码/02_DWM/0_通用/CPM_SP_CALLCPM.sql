CREATE OR REPLACE PROCEDURE CPM_SP_CALLCPM
(
    P_SP_NAME           IN VARCHAR2,    -- 要调用的存储过程名
    P_SCENARIO          IN VARCHAR2,    -- 年份
    P_PERIODO           IN VARCHAR2,    -- 月份
    P_AZIENDA           IN VARCHAR2,    -- 公司
    SESSION_USER        IN VARCHAR2,    -- 执行用户
    P_ACCOUNT_GROUP     IN VARCHAR2,    -- 科目组
    P_ACC_TYPE          IN VARCHAR2,    -- 科目分类
    P_DATA_GOAL         IN VARCHAR2,    -- 数据目标表名
    P_BG                IN VARCHAR2,    -- 事业部
    P_CATE              IN VARCHAR2     -- 数据类别
) AS
/*******************************************************************************
 * 最后更新时间：20261103 11:08  XIESHUJUAN.EX  上一版本信息：20260930 14:44  XIAOYACHAO.EX
 * 存储过程名称：CPM_SP_CALLCPM
 * 功能描述：动态调用存储过程
 * 创建日期：2026-01-28
 * 修改历史：
 *   版本  日期         修改人    修改说明
 *   V1.0  2026-01-28  [LC]      初始版本
 *   V2.0  2026-06-12  [WANGZIHAO1.EX]      增加中国区不含自营程序调度
 *   V3.0  2026-07-14  [SHIQINGFENG.EX] 修改调用程序为动态sql
 *   V4.0  2026-07-28  [XIESHUJUAN.EX]  增加销售费用电冰空营销中心数据分摊下发 + [XIAOYACHAO.EX]空调CBG收入成本分区域
 *   V5.0  2026-08-07  [FENGJIANFENG.EX] 增加无公司参数的存储过程锁定 + 增加前台表手动更新冲突锁定表的存储过程
 *   V6.0  2026-08-25  [HUOXINGZHAO.EX] CPM_SP_MAGVAR 自动管法差新增参数 指定值为1 ，1 ：执行管法差原逻辑
 *   V7.0  2026-08-25  [WANGZIHAO1.EX] 修改研发费用调用程序,增加品线分摊调用
 *   V8.0  2026-09-03  [XIAOYACHAO.EX] 增加三因素分析调用
 *   V9.0  2026-09-03  [XIAOYACHAO.EX] 三因素分析累计调用增加对比方式参数
 *   V10.0  2026-09-03  [HUOXINGZHAO.EX] 中国区线下费用表-收入取数,按钮使用
 *   V11.0  2026-09-28  [XIAOYACHAO.EX] 空调0401自动管法差
 *   V12.0  2026-09-30  [WANGHAODE.EX] 其他损益中国区下发产品公司
 *   V13.0 2026-11-03   [XIESHUJUAN.EX] 新增分摊校验程序



 *******************************************************************************/

    -- ==================== 变量声明 ====================
V_SCENARIO       VARCHAR2(15);
V_PERIODO        VARCHAR2(15);
V_ERROR_COD      NUMBER;
V_ERROR_MSG      VARCHAR2(4000);--错误信息
V_AZIENDA        VARCHAR2(4000);--当前组织（剔除正在执行的公司范围）
V_START_TIME     TIMESTAMP;      -- 开始时间
V_END_TIME       TIMESTAMP;      -- 结束时间
V_D2M_LOCK       CLOB;
V_M2S_LOCK       CLOB;
V_S2S_LOCK       CLOB;

V_RUN_COUNT NUMBER;
V_RUN_USER VARCHAR2(100);
V_RUN_ROWID VARCHAR2(36);
V_ENTITY VARCHAR2(4000);--参数传入组织范围
V_PAPAM_TIME DATE;--获取冲突锁定表时间

    V_SESSION_ID  NUMBER;
BEGIN
-- 获取当前 Session ID
    V_SESSION_ID := SYS_CONTEXT('USERENV', 'SESSIONID');

V_RUN_ROWID := NEWID();

    -- 1. 参数校验：核心参数不能为空
    IF P_SP_NAME IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, '错误：要调用的存储过程名不能为空！');
    END IF;

    /* 获取调度需要的场景、期间*/
    IF P_SCENARIO = '9999ACT' THEN
      V_SCENARIO := TO_CHAR(SYSDATE - 13, 'YYYY') || 'ACT';
      V_PERIODO  := TO_CHAR(SYSDATE - 13, 'MM');
    ELSIF P_SCENARIO = '9999BGT' THEN
      V_SCENARIO := TO_CHAR(SYSDATE - 13, 'YYYY') || 'BGT';
      V_PERIODO  := TO_CHAR(SYSDATE - 13, 'MM');
    ELSE
      V_SCENARIO := P_SCENARIO;
      V_PERIODO := P_PERIODO;
    END IF;


INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA)
VALUES (V_SESSION_ID,'CPM_SP_CALLCPM_LOCK','P-运行开始-'||P_SP_NAME,SYSDATE,SESSION_USER,V_SCENARIO,V_PERIODO,P_AZIENDA);
COMMIT;


 /*P：组织参数初始化*/
SELECT LISTAGG(ELEM,',') INTO V_ENTITY
FROM(
    SELECT DISTINCT ELEM
    FROM TGK_FIMA_HISENSE.V_REF_AZIENDA
    WHERE HIE = '10'
    AND ( INSTR(','||P_AZIENDA||',',','||ELEM||',') > 0
           OR INSTR(','||P_AZIENDA||',',','||NODE||',') > 0
           OR UPPER(P_AZIENDA) = 'ALL')
    /*20260127 新增抽取一期公司范围*/
    AND ELEM IN (SELECT COD_AZIENDA FROM AW_RUL_DWMCRS_000001 WHERE COD_CONTO = 'ZAW_D2M_IN')

    UNION ALL
    SELECT DISTINCT COD_AZIENDA AS ELEM
        FROM TGK_FIMA_HISENSE.AZIENDA
        WHERE P_AZIENDA = 'KT'
        AND (COD_AZIENDA LIKE '62%' OR COD_AZIENDA LIKE '68%')

    UNION ALL
    SELECT DISTINCT COD_AZIENDA AS ELEM
        FROM TGK_FIMA_HISENSE.AZIENDA
        WHERE P_AZIENDA = 'SX'
        AND (COD_AZIENDA LIKE '2%' OR COD_AZIENDA LIKE '163%')

    UNION ALL
    SELECT DISTINCT COD_AZIENDA AS ELEM
        FROM TGK_FIMA_HISENSE.AZIENDA
        WHERE P_AZIENDA = 'BX'
        AND (COD_AZIENDA LIKE '63%' OR COD_AZIENDA LIKE '67%' OR COD_AZIENDA LIKE '6000%')
  );


/* 20260807_ADD：锁定逻辑整体调整，改动范围包括超时锁处理及 P0-P5 */
--获取正在执行程序的执行开始时间。
--P0 公司参数为空或为文本 NULL 时忽略公司条件，仅按其他参数匹配；公司有值时匹配重叠公司或空公司全局锁。
SELECT MIN(T.DATEUPD) INTO V_PAPAM_TIME
FROM ZTAB_CPM_PARAM T
WHERE T.CPM = P_SP_NAME
AND T.COD_SCENARIO = V_SCENARIO
AND T.COD_PERIODO = V_PERIODO
AND T.ACCOUNT_GROUP = DECODE(P_ACCOUNT_GROUP,'','|','NULL','|',P_ACCOUNT_GROUP)
AND T.ACC_TYPE = DECODE(P_ACC_TYPE,'','|','NULL','|',P_ACC_TYPE)
AND T.CATE = DECODE(P_CATE,'','|','NULL','|',P_CATE)
AND (T.BG = DECODE(P_BG,'','|','NULL','|',P_BG) OR T.BG = 'ALL')
AND T.FLAG = 'RUNNING'
AND T.COD_AZIENDA = DECODE(P_AZIENDA,'','|','NULL','|',V_ENTITY)
;

--P0 如果正在执行的程序超过1.5小时，则默认该程序异常报错，并将冲突状态表FLAG字段更新为ERROR
IF SYSDATE - V_PAPAM_TIME > 1.5 / 24 THEN
  UPDATE ZTAB_CPM_PARAM T
  SET FLAG = 'ERROR'
  WHERE T.CPM = P_SP_NAME
  AND T.COD_SCENARIO = V_SCENARIO
  AND T.COD_PERIODO = V_PERIODO
  AND T.ACCOUNT_GROUP = DECODE(P_ACCOUNT_GROUP,'','|','NULL','|',P_ACCOUNT_GROUP)
  AND T.ACC_TYPE = DECODE(P_ACC_TYPE,'','|','NULL','|',P_ACC_TYPE)
  AND T.CATE = DECODE(P_CATE,'','|','NULL','|',P_CATE)
  AND (T.BG = DECODE(P_BG,'','|','NULL','|',P_BG) OR T.BG = 'ALL')
  AND T.FLAG = 'RUNNING'
  AND T.COD_AZIENDA = DECODE(P_AZIENDA,'','|','NULL','|',V_ENTITY)
  ;
END IF;

/* P1-P2：公司为空时按剩余参数锁定；公司有值时按公司重叠范围锁定并剔除冲突公司 */
IF P_AZIENDA IS NULL OR P_AZIENDA = 'NULL' THEN
  SELECT COUNT(*), MAX(T.USERUPD)
  INTO V_RUN_COUNT, V_RUN_USER
  FROM ZTAB_CPM_PARAM T
  WHERE T.CPM = P_SP_NAME
  AND T.COD_SCENARIO = V_SCENARIO
  AND T.COD_PERIODO = V_PERIODO
  AND T.ACCOUNT_GROUP = DECODE(P_ACCOUNT_GROUP,'','|','NULL','|',P_ACCOUNT_GROUP)
  AND T.ACC_TYPE = DECODE(P_ACC_TYPE,'','|','NULL','|',P_ACC_TYPE)
  AND T.CATE = DECODE(P_CATE,'','|','NULL','|',P_CATE)
  AND (T.BG = DECODE(P_BG,'','|','NULL','|',P_BG) OR T.BG = 'ALL')
  AND T.FLAG = 'RUNNING';

  V_AZIENDA := NULL;
ELSE
  /* P1：获取正在执行的公司数 & 执行用户 */
  WITH SRC AS
  (
    SELECT TRIM(REGEXP_SUBSTR(V_ENTITY, '[^,]+', 1, LEVEL)) AS ENTITY
    FROM DUAL
    CONNECT BY LEVEL <= REGEXP_COUNT(V_ENTITY, '[^,]+')
  ),
  RUNNING AS
  (
    SELECT DISTINCT N.ENTITY, T.USERUPD
    FROM SRC N
    JOIN(
          SELECT COD_AZIENDA,USERUPD
          FROM ZTAB_CPM_PARAM T
          WHERE T.CPM = P_SP_NAME
          AND T.COD_SCENARIO = V_SCENARIO
          AND T.COD_PERIODO = V_PERIODO
      AND T.ACCOUNT_GROUP = DECODE(P_ACCOUNT_GROUP,'','|','NULL','|',P_ACCOUNT_GROUP)
      AND T.ACC_TYPE = DECODE(P_ACC_TYPE,'','|','NULL','|',P_ACC_TYPE)
      AND T.CATE = DECODE(P_CATE,'','|','NULL','|',P_CATE)
      AND (T.BG = DECODE(P_BG,'','|','NULL','|',P_BG) OR T.BG = 'ALL')
      AND T.FLAG = 'RUNNING'
         ) T
      ON  (  NVL(T.COD_AZIENDA,'|') = '|'
         OR T.COD_AZIENDA = N.ENTITY
         OR ',' || T.COD_AZIENDA || ',' LIKE '%,' || N.ENTITY || ',%'
         OR T.COD_AZIENDA LIKE N.ENTITY || ',%'
         OR T.COD_AZIENDA LIKE '%,' || N.ENTITY
         )
  )
  SELECT COUNT(DISTINCT ENTITY), MAX(USERUPD) INTO V_RUN_COUNT, V_RUN_USER
  FROM RUNNING;

  /* P2:获取排除正在执行公司后的可执行公司列表 */
  SELECT LISTAGG(ENTITY,',') INTO V_AZIENDA
  FROM(
      SELECT TRIM(REGEXP_SUBSTR(V_ENTITY, '[^,]+', 1, LEVEL)) AS ENTITY
      FROM DUAL
      CONNECT BY LEVEL <= REGEXP_COUNT(V_ENTITY, '[^,]+')

      MINUS
      SELECT DISTINCT N.ENTITY
      FROM(
        SELECT TRIM(REGEXP_SUBSTR(V_ENTITY, '[^,]+', 1, LEVEL)) AS ENTITY
        FROM DUAL
        CONNECT BY LEVEL <= REGEXP_COUNT(V_ENTITY, '[^,]+')
        ) N
      JOIN(
          SELECT *
          FROM ZTAB_CPM_PARAM T
          WHERE T.CPM = P_SP_NAME
          AND T.COD_SCENARIO = V_SCENARIO
          AND T.COD_PERIODO = V_PERIODO
          AND T.ACCOUNT_GROUP = DECODE(P_ACCOUNT_GROUP,'','|','NULL','|',P_ACCOUNT_GROUP)
          AND T.ACC_TYPE = DECODE(P_ACC_TYPE,'','|','NULL','|',P_ACC_TYPE)
          AND T.CATE = DECODE(P_CATE,'','|','NULL','|',P_CATE)
          AND (T.BG = DECODE(P_BG,'','|','NULL','|',P_BG) OR T.BG = 'ALL')
          AND T.FLAG = 'RUNNING'
        ) T
      ON (  NVL(T.COD_AZIENDA,'|') = '|'
        OR T.COD_AZIENDA = N.ENTITY
        OR ',' || T.COD_AZIENDA || ',' LIKE '%,' || N.ENTITY || ',%'
        OR T.COD_AZIENDA LIKE N.ENTITY || ',%'
        OR T.COD_AZIENDA LIKE '%,' || N.ENTITY
      )
      );
END IF;


/* P3 若 V_AZIENDA 为空（所有公司或剩余参数均在执行中），记录日志并中断 */
IF V_RUN_COUNT > 0 AND V_AZIENDA IS NULL THEN
  INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA,Remark)
  VALUES (V_SESSION_ID,'CPM_SP_CALLCPM'
         ,'【'||P_SP_NAME||' 禁止重复提交】,【当前用户:'||V_RUN_USER||'】 正在执行中，请等待完成后再试！'
         ,SYSDATE, SESSION_USER, V_SCENARIO, V_PERIODO, DECODE(P_AZIENDA,'','|','NULL','|',V_ENTITY)
         ,'【'||P_SP_NAME||' 禁止重复提交】');
  COMMIT;

  RAISE_APPLICATION_ERROR( -20001,'【'||P_SP_NAME||' 禁止重复提交】,【当前用户:'||V_RUN_USER||'】 正在执行中，请等待完成后再试！');
END IF;

/* P4：检查程序执行依赖顺序表（公司为空时忽略公司条件） */
FOR REC IN
(
  WITH SRC AS
  (
    SELECT TRIM(REGEXP_SUBSTR(DECODE(P_AZIENDA,'','|','NULL','|',V_ENTITY), '[^,]+', 1, LEVEL)) AS ENTITY
    FROM DUAL
    CONNECT BY LEVEL <= REGEXP_COUNT(DECODE(P_AZIENDA,'','|','NULL','|',V_ENTITY), '[^,]+')
  )

  SELECT T.CPM AS RUN_SP,T.COD_AZIENDA AS RUN_AZIENDA,T.USERUPD AS RUN_USER
  FROM ZTAB_CPM_PARAM T
  JOIN SRC N
  ON (   P_AZIENDA IS NULL
      OR P_AZIENDA = 'NULL'
      OR NVL(T.COD_AZIENDA,'|') = '|'
      OR T.COD_AZIENDA = N.ENTITY
      OR ',' || T.COD_AZIENDA || ',' LIKE '%,' || N.ENTITY || ',%'
      OR T.COD_AZIENDA LIKE N.ENTITY || ',%'
      OR T.COD_AZIENDA LIKE '%,' || N.ENTITY
     )
  WHERE T.CPM IN (SELECT F.CPM_FIRST FROM ZTAB_CPM_RUNNING_ORDER F WHERE F.CPM_LAST = P_SP_NAME)
  AND T.COD_SCENARIO = V_SCENARIO
  AND T.COD_PERIODO = V_PERIODO
  AND T.FLAG = 'RUNNING'
) LOOP

  INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA,REMARK)
  VALUES (V_SESSION_ID,'CPM_SP_CALLCPM'
      ,'【'||P_SP_NAME||' 依赖顺序禁止】前序程序【'||REC.RUN_SP||'】正在执行公司【'||REC.RUN_AZIENDA||'】，存在参数冲突，请等待完成后再试！'
      ,SYSDATE, SESSION_USER, V_SCENARIO, V_PERIODO, DECODE(P_AZIENDA,'','|','NULL','|',V_ENTITY)
      ,'【'||P_SP_NAME||' 依赖顺序禁止】'
      );
  COMMIT;

  RAISE_APPLICATION_ERROR(-20002,'【'||P_SP_NAME||' 依赖顺序禁止】前序程序正在执行中，请等待完成后再试！');
END LOOP;

/* P5 插入 RUNNING 记录；公司为空或为文本 NULL 时以 | 保存 */
INSERT INTO ZTAB_CPM_PARAM(CPM,COD_SCENARIO,COD_PERIODO,COD_AZIENDA,FLAG,USERUPD,DATEUPD,SOID,ACCOUNT_GROUP,ACC_TYPE,CATE,BG)
VALUES(P_SP_NAME, V_SCENARIO, V_PERIODO
    , DECODE(P_AZIENDA,'','|','NULL','|',V_AZIENDA)
    , 'RUNNING', SESSION_USER, SYSDATE, V_RUN_ROWID
    , DECODE(P_ACCOUNT_GROUP,'','|','NULL','|',P_ACCOUNT_GROUP)
    , DECODE(P_ACC_TYPE,'','|','NULL','|',P_ACC_TYPE)
    , DECODE(P_CATE,'','|','NULL','|',P_CATE)
    , DECODE(P_BG,'','|','NULL','|',P_BG)
  );
COMMIT;

INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA)
VALUES (V_SESSION_ID,'CPM_SP_CALLCPM_LOCK','P-运行结束-'||P_SP_NAME,SYSDATE,SESSION_USER,V_SCENARIO,V_PERIODO,V_AZIENDA);
COMMIT;



    /*获取锁定公司或事业部*/
    SELECT FN_GET_LOCK_AZIENDA(P_AZIENDA,P_BG,V_SCENARIO,V_PERIODO,'M') INTO  V_D2M_LOCK
    FROM DUAL;
    SELECT FN_GET_LOCK_AZIENDA(P_AZIENDA,P_BG,V_SCENARIO,V_PERIODO,'S') INTO  V_M2S_LOCK
    FROM DUAL;
    SELECT FN_GET_LOCK_AZIENDA(P_AZIENDA,P_BG,V_SCENARIO,V_PERIODO,'Z') INTO  V_S2S_LOCK
    FROM DUAL;


    --收入成本,产量和库存在REV程序已调用,1-正常数据抽取，2-调整数据抽取
    IF UPPER(P_SP_NAME) = 'CPM_SP_D2M_REV_M' THEN
     --记录开始时间
     V_START_TIME := SYSDATE;

     INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA
     ,D2M_LOCK,M2S_LOCK,S2S_LOCK,Remark
     )
     VALUES (V_SESSION_ID,'CPM_SP_CALLCPM','收入成本单体数据更新'||'-'||P_SP_NAME||'-'||P_DATA_GOAL||'-运行开始',V_START_TIME,SESSION_USER,V_SCENARIO,V_PERIODO,V_AZIENDA,V_D2M_LOCK,V_M2S_LOCK,V_S2S_LOCK,P_DATA_GOAL||'---说明：'||'1-正常数据抽取，2-调整数据抽取'
     );
     COMMIT;


    EXECUTE IMMEDIATE 'BEGIN CPM_SP_D2M_REV_M(:1, :2, :3, :4, :5); END;'
    USING V_SCENARIO, V_PERIODO, V_AZIENDA, P_DATA_GOAL, SESSION_USER;

    -- 记录结束时间
    V_END_TIME := SYSDATE;

    INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA,REMARK
                             ,D2M_LOCK,M2S_LOCK,S2S_LOCK)
    VALUES (V_SESSION_ID,'CPM_SP_CALLCPM','收入成本单体数据更新'||'-'||P_SP_NAME||'-'||P_DATA_GOAL||'-运行结束！',V_END_TIME,SESSION_USER,V_SCENARIO,V_PERIODO,V_AZIENDA,'耗时：'||EXTRACT(HOUR FROM (V_END_TIME-V_START_TIME)) ||'小时'||EXTRACT(MINUTE FROM (V_END_TIME-V_START_TIME))||'分钟'||EXTRACT(SECOND FROM (V_END_TIME-V_START_TIME))||'秒'
                             ,V_D2M_LOCK,V_M2S_LOCK,V_S2S_LOCK);
    COMMIT;


    END IF;

    --存货未实现
    IF UPPER(P_SP_NAME) = 'CPM_SP_M2M_UP_M' THEN
     --记录开始时间
     V_START_TIME := SYSDATE;

     INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA
     ,D2M_LOCK,M2S_LOCK,S2S_LOCK
     )
     VALUES (V_SESSION_ID,'CPM_SP_CALLCPM','外销未实现数据更新'||'-'||P_SP_NAME||'-运行开始',V_START_TIME,SESSION_USER,V_SCENARIO,V_PERIODO,V_AZIENDA,V_D2M_LOCK,V_M2S_LOCK,V_S2S_LOCK
     );
     COMMIT;

       EXECUTE IMMEDIATE 'BEGIN CPM_SP_M2M_UP_M(:1, :2, :3); END;'
       USING V_SCENARIO, V_PERIODO, SESSION_USER;

    -- 记录结束时间
    V_END_TIME := SYSDATE;

    INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA,REMARK
                             ,D2M_LOCK,M2S_LOCK,S2S_LOCK
                             )
    VALUES (V_SESSION_ID,'CPM_SP_CALLCPM','外销未实现数据更新'||'-'||P_SP_NAME||'-运行结束！',V_END_TIME,SESSION_USER,V_SCENARIO,V_PERIODO,V_AZIENDA,'耗时：'||EXTRACT(HOUR FROM (V_END_TIME-V_START_TIME)) ||'小时'||EXTRACT(MINUTE FROM (V_END_TIME-V_START_TIME))||'分钟'||EXTRACT(SECOND FROM (V_END_TIME-V_START_TIME))||'秒'
                             ,V_D2M_LOCK,V_M2S_LOCK,V_S2S_LOCK
                             );
    COMMIT;

    END IF;

    --库存更新
    IF UPPER(P_SP_NAME) = 'CPM_SP_D2M_INV_M' THEN
     --记录开始时间
     V_START_TIME := SYSDATE;

     INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA
     ,D2M_LOCK,M2S_LOCK,S2S_LOCK
     )
     VALUES (V_SESSION_ID,'CPM_SP_CALLCPM','库存数据更新'||'-'||P_SP_NAME||'-运行开始',V_START_TIME,SESSION_USER,V_SCENARIO,V_PERIODO,V_AZIENDA,V_D2M_LOCK,V_M2S_LOCK,V_S2S_LOCK
     );
     COMMIT;

       EXECUTE IMMEDIATE 'BEGIN CPM_SP_D2M_INV_M(:1, :2, :3, :4); END;'
       USING V_SCENARIO, V_PERIODO, V_AZIENDA, SESSION_USER;

    -- 记录结束时间
    V_END_TIME := SYSDATE;

    INSERT INTO ZTAB_CPM_LOG(SESSION_ID,CPM,STEP,EXECTIME,CREATEBY,COD_SCENARIO,COD_PERIODO,COD_AZIENDA,REMARK
