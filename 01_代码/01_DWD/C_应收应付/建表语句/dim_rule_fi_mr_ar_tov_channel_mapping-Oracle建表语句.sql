/* 应收周转分析渠道映射规则表（Oracle 建表语句）
 * 源表: dim.dim_rule_fi_mr_ar_tov_channel_mapping (Doris)
 * 目标表: DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING
 * 说明:
 *   1. bigint → NUMBER(19); int → NUMBER(10); varchar(n) → VARCHAR2(n); datetime → DATE
 *   2. Doris UNIQUE KEY(ruleInnerId) 具备唯一约束语义, 映射为 Oracle 主键 PK_DIM_RULE_AR_TOV_CHAN_MAP
 *   3. 原 Doris 的 DEFAULT CURRENT_TIMESTAMP 在 Oracle 中对 DATE 列需改为 DEFAULT SYSDATE
 *      (CURRENT_TIMESTAMP 返回 TIMESTAMP WITH TIME ZONE, 赋给 DATE 列会隐式转换异常)
 *   4. 列名沿用源表写法, 仅统一为大写(RULEINNERID), 不改名, 避免影响既有 ETL 映射;
 *      若希望规范化为 RULE_INNER_ID, 需同步修改装载脚本
 *   5. 分桶/副本/存储等 Doris 属性在 Oracle 无对应, 已移除
 *   6. Oracle 不支持 CREATE TABLE 内联 COMMENT, 注释统一用 COMMENT ON COLUMN 单独下发
 *   7. 源表 TOV_CHANNEL_NAME 的注释为 "周转分析周转分析渠道名称渠道名称"(原文重复),
 *      此处按 "周转分析渠道名称" 落库, 如需与源表逐字一致请改回
 *   7. 约束名/索引名控制在 30 字节以内, 兼容 Oracle 12.1 及以下版本的标识符长度限制
 */

CREATE TABLE DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING (
      RULEINNERID           NUMBER(19)      NOT NULL
    , ID                    NUMBER(10)      NOT NULL
    , VALID_FR              VARCHAR2(255)
    , VALID_TO              VARCHAR2(255)
    , LOAD_DT               DATE            DEFAULT SYSDATE
    , BATCH_ID              VARCHAR2(255)
    , LOGIC_NAME            VARCHAR2(255)
    , COMPANY_CODE          VARCHAR2(255)
    , CUST_CODE             VARCHAR2(255)
    , CUST_NAME             VARCHAR2(255)
    , CHANNEL_L3_CODE       VARCHAR2(255)
    , CHANNEL_L3_NAME       VARCHAR2(255)
    , TOV_CHANNEL_CODE      VARCHAR2(255)
    , TOV_CHANNEL_NAME      VARCHAR2(255)
    , UNIQUE_KEY            VARCHAR2(1024)  NOT NULL
    , CONSTRAINT PK_DIM_RULE_AR_TOV_CHAN_MAP PRIMARY KEY (RULEINNERID)
);

COMMENT ON TABLE DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING IS '应收周转分析渠道映射规则表';

COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.RULEINNERID      IS '规则内部主键';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.ID               IS '主键';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.VALID_FR         IS '有效期起';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.VALID_TO         IS '有效期止';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.LOAD_DT          IS '加载时间';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.BATCH_ID         IS '匹配顺序';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.LOGIC_NAME       IS '逻辑处理';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.COMPANY_CODE     IS '公司编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.CUST_CODE        IS '客商编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.CUST_NAME        IS '客商名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.CHANNEL_L3_CODE  IS '三级公司分类编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.CHANNEL_L3_NAME  IS '三级公司分类名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.TOV_CHANNEL_CODE IS '周转分析渠道编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.TOV_CHANNEL_NAME IS '周转分析渠道名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING.UNIQUE_KEY       IS '唯一键(用于匹配去重)';

/* 原 Doris 分桶键为 ruleInnerId, 主键已覆盖; 以下索引为按业务匹配路径补充, 不需要可删除 */
CREATE INDEX IDX_DIM_RULE_AR_TOVCHAN_1 ON DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING (COMPANY_CODE, CUST_CODE);
CREATE INDEX IDX_DIM_RULE_AR_TOVCHAN_2 ON DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING (CHANNEL_L3_CODE);
CREATE INDEX IDX_DIM_RULE_AR_TOVCHAN_3 ON DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING (UNIQUE_KEY);

GRANT ALL ON DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING TO app_read;
