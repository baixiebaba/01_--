/* 应收业务管理单元映射规则表（Oracle 建表语句）
 * 源表: dim.dim_rule_fi_mr_ar_busdept_mapping (Doris)
 * 目标表: DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING
 * 说明:
 *   1. bigint → NUMBER(19); int → NUMBER(10); varchar(n) → VARCHAR2(n); datetime → DATE
 *   2. Doris UNIQUE KEY(ruleInnerId) 具备唯一约束语义, 映射为 Oracle 主键 PK_DIM_RULE_AR_BUSDEPT_MAP
 *   3. 原 Doris 的 DEFAULT CURRENT_TIMESTAMP 在 Oracle 中对 DATE 列需改为 DEFAULT SYSDATE
 *      (CURRENT_TIMESTAMP 返回 TIMESTAMP WITH TIME ZONE, 赋给 DATE 列会隐式转换异常)
 *   4. 列名沿用源表写法, 仅统一为大写(RULEINNERID), 不改名, 避免影响既有 ETL 映射;
 *      若希望规范化为 RULE_INNER_ID, 需同步修改装载脚本
 *   5. 分桶/副本/存储等 Doris 属性在 Oracle 无对应, 已移除
 *   6. Oracle 不支持 CREATE TABLE 内联 COMMENT, 注释统一用 COMMENT ON COLUMN 单独下发
 *   7. 约束名/索引名控制在 30 字节以内, 兼容 Oracle 12.1 及以下版本的标识符长度限制
 */


CREATE TABLE DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING (
      RULEINNERID          NUMBER(19)      NOT NULL
    , ID                   NUMBER(10)      NOT NULL
    , VALID_FR             VARCHAR2(255)
    , VALID_TO             VARCHAR2(255)
    , LOAD_DT              DATE            DEFAULT SYSDATE
    , BATCH_ID             VARCHAR2(255)
    , LOGIC_NAME           VARCHAR2(255)
    , SYSTEM_SRC           VARCHAR2(255)
    , NATURE_L3_NAME       VARCHAR2(255)
    , PROFITCENTER_CODE    VARCHAR2(255)
    , PROFITCENTER_NAME    VARCHAR2(255)
    , MARKETING_DEPT_CODE  VARCHAR2(255)
    , MARKETING_DEPT_NAME  VARCHAR2(255)
    , UNIQUE_KEY           VARCHAR2(1024)  NOT NULL
    , COMPANY_CODE         VARCHAR2(255)
    , CONSTRAINT PK_DIM_RULE_AR_BUSDEPT_MAP PRIMARY KEY (RULEINNERID)
);

COMMENT ON TABLE DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING IS '应收业务管理单元映射规则表';

COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.RULEINNERID         IS '规则内部主键';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.ID                  IS '主键';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.VALID_FR            IS '有效期起';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.VALID_TO            IS '有效期止';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.LOAD_DT             IS '加载时间';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.BATCH_ID            IS '匹配顺序';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.LOGIC_NAME          IS '逻辑处理';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.SYSTEM_SRC          IS '系统号';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.NATURE_L3_NAME      IS '三级性质';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.PROFITCENTER_CODE   IS '映射后利润中心编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.PROFITCENTER_NAME   IS '映射后利润中心名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.MARKETING_DEPT_CODE IS '业务管理单元编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.MARKETING_DEPT_NAME IS '业务管理单元名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.UNIQUE_KEY          IS '唯一键(用于匹配去重)';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING.COMPANY_CODE        IS '公司编码';

GRANT ALL ON DIM_RULE_FI_MR_AR_BUSDEPT_MAPPING TO app_read;
