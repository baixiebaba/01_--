/* 客户公司视图信息（Oracle 建表语句）
 * 源表: dw.dim_customer_company_info_dd (Doris)
 * 目标表: DIM_CUSTOMER_COMPANY_INFO_DD
 * 说明:
 *   1) Doris 的 DUPLICATE KEY(cust_code) 并非唯一键, 语义上对应 Oracle 的堆表, 不建主键
 *   2) 分桶/副本/存储等 Doris 属性在 Oracle 无对应, 已移除
 *   3) varchar(n) → VARCHAR2(n); datetime → DATE
 *   4) Oracle 不支持 CREATE TABLE 内联 COMMENT, 注释统一用 COMMENT ON COLUMN 单独下发
 */

CREATE TABLE DIM_CUSTOMER_COMPANY_INFO_DD (
      CUST_CODE             VARCHAR2(30)
    , CUST_SAP_CODE         VARCHAR2(30)
    , CUST_SAP_CLIENT       VARCHAR2(30)
    , COMPANY_CODE_MDG      VARCHAR2(12)
    , COMPANY_CODE          VARCHAR2(12)
    , PAY_COND_CODE         VARCHAR2(30)
    , PAY_COND_NAME         VARCHAR2(450)
    , RECO_ACCT_CODE        VARCHAR2(30)
    , RECO_ACCT_NAME        VARCHAR2(300)
    , SELECTION_CODE        VARCHAR2(9)
    , SELECTION_NAME        VARCHAR2(300)
    , ACCT_REMARK           VARCHAR2(90)
    , FREEZE_FLAG           VARCHAR2(3)
    , PAY_WAY_CODE          VARCHAR2(12)
    , PAY_WAY_NAME          VARCHAR2(300)
    , ONLINE_CODE           VARCHAR2(6)
    , ONLINE_NAME           VARCHAR2(150)
    , COM_DELETE_FLAG       VARCHAR2(3)
    , EDI_DEFAULT_SP        VARCHAR2(300)
    , EDI_ID                VARCHAR2(300)
    , EDI_ID2               VARCHAR2(300)
    , EDI_TYPE              VARCHAR2(300)
    , TV_LISENSE            VARCHAR2(300)
    , VALID_TO_DATE         VARCHAR2(300)
    , PACK_TYPE             VARCHAR2(300)
    , VAT_NO                VARCHAR2(300)
    , VAT_TYPE              VARCHAR2(300)
    , HEADQUARTERS          VARCHAR2(60)
    , PAY_FREEZE            VARCHAR2(30)
    , CRG_CUST_GROUP_CODE   VARCHAR2(100)
    , CRG_CUST_GROUP_NAME   VARCHAR2(255)
    , LOAD_DT               DATE
);

COMMENT ON TABLE DIM_CUSTOMER_COMPANY_INFO_DD IS '客户公司视图信息';

COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.CUST_CODE           IS '客户编码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.CUST_SAP_CODE       IS '客户SAP编码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.CUST_SAP_CLIENT     IS '客户SAPCLIENT';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.COMPANY_CODE_MDG    IS 'MDG公司代码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.COMPANY_CODE        IS '公司代码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.PAY_COND_CODE       IS '付款条件编码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.PAY_COND_NAME       IS '付款条件名称';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.RECO_ACCT_CODE      IS '统驭科目编码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.RECO_ACCT_NAME      IS '统驭科目名称';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.SELECTION_CODE      IS '选择规则编码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.SELECTION_NAME      IS '选择规则名称';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.ACCT_REMARK         IS '账户备注';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.FREEZE_FLAG         IS '冻结标记';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.PAY_WAY_CODE        IS '支付方式编码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.PAY_WAY_NAME        IS '支付方式名称';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.ONLINE_CODE         IS '线上/线下编码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.ONLINE_NAME         IS '线上/线下名称';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.COM_DELETE_FLAG     IS '公司区域删除标识';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.EDI_DEFAULT_SP      IS '客户EDI 默认库位';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.EDI_ID              IS '客户EDI ID';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.EDI_ID2             IS '客户EDI ID2';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.EDI_TYPE            IS '客户EDI 类型';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.TV_LISENSE          IS 'TV lisense';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.VALID_TO_DATE       IS 'Valid to';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.PACK_TYPE           IS '包装类型';
