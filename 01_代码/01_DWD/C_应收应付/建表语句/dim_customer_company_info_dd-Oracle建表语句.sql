COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.HEADQUARTERS        IS '总部';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.PAY_FREEZE          IS '付款冻结';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.CRG_CUST_GROUP_CODE IS '商冷客户群编码';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.CRG_CUST_GROUP_NAME IS '商冷客户群名称';
COMMENT ON COLUMN DIM_CUSTOMER_COMPANY_INFO_DD.LOAD_DT             IS '数据加载时间';

/* 原 Doris 分桶键为 (cust_code, cust_sap_client), 若有按客户/公司查询场景可建索引 */
CREATE INDEX IDX_DIM_CUST_COMP_INFO_1 ON DIM_CUSTOMER_COMPANY_INFO_DD (CUST_CODE, CUST_SAP_CLIENT);
CREATE INDEX IDX_DIM_CUST_COMP_INFO_2 ON DIM_CUSTOMER_COMPANY_INFO_DD (COMPANY_CODE);

GRANT ALL ON DIM_CUSTOMER_COMPANY_INFO_DD TO app_read;
