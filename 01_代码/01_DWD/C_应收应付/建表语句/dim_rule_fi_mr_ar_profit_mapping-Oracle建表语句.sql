/* 应收利润中心映射规则表（Oracle 建表语句）
 * 源表: dim.dim_rule_fi_mr_ar_profit_mapping (Doris)
 * 目标表: DIM_RULE_FI_MR_AR_PROFIT_MAPPING
 * 说明:
 *   1) bigint → NUMBER(19); int → NUMBER(10); varchar(n) → VARCHAR2(n); datetime → DATE
 *   2) Doris UNIQUE KEY(ruleInnerId) 具备唯一约束语义, 映射为 Oracle 主键 PK_DIM_RULE_AR_PROFIT_MAP
 *   3) 原 Doris 的 DEFAULT CURRENT_TIMESTAMP 在 Oracle 中对 DATE 列需改为 DEFAULT SYSDATE
 *      (CURRENT_TIMESTAMP 返回 TIMESTAMP WITH TIME ZONE, 赋给 DATE 列会隐式转换异常)
 *   4) 列名沿用源表写法, 仅统一为大写(RULEINNERID), 不改名, 避免影响既有 ETL 映射;
 *      若希望规范化为 RULE_INNER_ID, 需同步修改装载脚本
 *   5) 分桶/副本/存储等 Doris 属性在 Oracle 无对应, 已移除
 *   6) Oracle 不支持 CREATE TABLE 内联 COMMENT, 注释统一用 COMMENT ON COLUMN 单独下发
 *   7. 约束名/索引名控制在 30 字节以内, 兼容 Oracle 12.1 及以下版本的标识符长度限制
 *   8. ALTER BY 20261029 18:10 SHIQINGFENG.EX 补 material_group_code / material_group_name 两列
 *      (Doris 侧已是 18 列, 原 Oracle 镜像漏建这两列, 导致 batch_id=6 按物料组映射时报 ORA-00904)
 */

CREATE TABLE DIM_RULE_FI_MR_AR_PROFIT_MAPPING (
      RULEINNERID               NUMBER(19)      NOT NULL
    , ID                        NUMBER(10)      NOT NULL
    , VALID_FR                  VARCHAR2(255)
    , VALID_TO                  VARCHAR2(255)
    , LOAD_DT                   DATE            DEFAULT SYSDATE
    , BATCH_ID                  VARCHAR2(255)
    , LOGIC_NAME                VARCHAR2(255)
    , COMPANY_CODE              VARCHAR2(255)
    , ONOFFLINE_CODE            VARCHAR2(255)
    , ONOFFLINE_NAME            VARCHAR2(255)
    , ACCT_SRC_CODE             VARCHAR2(255)
    , SRC_PROFITCENTER_CODE     VARCHAR2(255)
    , SRC_PROFITCENTER_NAME     VARCHAR2(255)
    , PROFITCENTER_CODE         VARCHAR2(255)
    , PROFITCENTER_NAME         VARCHAR2(255)
    , MATERIAL_GROUP_CODE       VARCHAR2(255)
    , MATERIAL_GROUP_NAME       VARCHAR2(255)
    , UNIQUE_KEY                VARCHAR2(1024)  NOT NULL
    , CONSTRAINT PK_DIM_RULE_AR_PROFIT_MAP PRIMARY KEY (RULEINNERID)
);

COMMENT ON TABLE DIM_RULE_FI_MR_AR_PROFIT_MAPPING IS '应收利润中心映射规则表';

COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.RULEINNERID           IS '规则内部主键';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.ID                    IS '主键';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.VALID_FR              IS '有效期起';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.VALID_TO              IS '有效期止';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.LOAD_DT               IS '加载时间';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.BATCH_ID              IS '匹配顺序';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.LOGIC_NAME            IS '逻辑处理';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.COMPANY_CODE          IS '公司编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.ONOFFLINE_CODE        IS '渠道分组编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.ONOFFLINE_NAME        IS '渠道分组名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.ACCT_SRC_CODE         IS '科目编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.SRC_PROFITCENTER_CODE IS '映射前利润中心编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.SRC_PROFITCENTER_NAME IS '映射前利润中心名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.PROFITCENTER_CODE     IS '映射后利润中心编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.PROFITCENTER_NAME     IS '映射后利润中心名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.MATERIAL_GROUP_CODE   IS '物料组编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.MATERIAL_GROUP_NAME   IS '物料组名称';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_PROFIT_MAPPING.UNIQUE_KEY            IS '唯一键(用于匹配去重)';

/* 原 Doris 分桶键为 ruleInnerId, 主键已覆盖; 以下索引为按业务匹配路径补充, 不需要可删除 */
CREATE INDEX IDX_DIM_RULE_AR_PROFIT_1 ON DIM_RULE_FI_MR_AR_PROFIT_MAPPING (COMPANY_CODE, ACCT_SRC_CODE, SRC_PROFITCENTER_CODE);
CREATE INDEX IDX_DIM_RULE_AR_PROFIT_2 ON DIM_RULE_FI_MR_AR_PROFIT_MAPPING (UNIQUE_KEY);

GRANT ALL ON DIM_RULE_FI_MR_AR_PROFIT_MAPPING TO app_read;
