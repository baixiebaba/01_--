/* 应收国家业务范围映射规则表（Oracle 建表语句）
 * 源表: dim.dim_rule_fi_mr_ar_country_busrange_mapping (Doris)
 * 目标表: DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING
 *
 * 修订记录 2026-10-15: 此前为压缩标识符长度, 误将 COUNTRY 缩写为 CTRY,
 *   生成了 DIM_RULE_FI_MR_AR_CTRY_BUSRANGE_MAPPING, 与源表名不一致。本版本已恢复为与源表一一对应的完整名称。
 *
 * 说明:
 *   1. bigint → NUMBER(19); int → NUMBER(10); varchar(n) → VARCHAR2(n); datetime → DATE
 *   2. Doris UNIQUE KEY(ruleInnerId) 具备唯一约束语义, 映射为 Oracle 主键 PK_DIM_RULE_AR_CNTRY_BUSR_MAP
 *   3. 原 Doris 的 DEFAULT CURRENT_TIMESTAMP 在 Oracle 中对 DATE 列需改为 DEFAULT SYSDATE
 *      (CURRENT_TIMESTAMP 返回 TIMESTAMP WITH TIME ZONE, 赋给 DATE 列会隐式转换异常)
 *   4. 列名沿用源表写法, 仅统一为大写(RULEINNERID), 不改名, 避免影响既有 ETL 映射
 *   5. 分桶/副本/存储等 Doris 属性在 Oracle 无对应, 已移除
 *   6. Oracle 不支持 CREATE TABLE 内联 COMMENT, 注释统一用 COMMENT ON COLUMN 单独下发
 *   7. 表名 42 个字符, 超过 30 字节, 仅适用于 Oracle 12.2+ (标识符上限 128);
 *      若目标库为 12.1 及以下, 需另行缩短表名并同步修改装载脚本
 */


/* ========== 步骤 0: 删除此前误建的缩写名表 (确认无误后再执行) ==========
 * 未加 PURGE, 删除后进入回收站, 可回滚:
 *   FLASHBACK TABLE DIM_RULE_FI_MR_AR_CTRY_BUSRANGE_MAPPING TO BEFORE DROP;
 * 若你实际建的是完整名, 则改执行:
 *   DROP TABLE DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING;
 */
DROP TABLE DIM_RULE_FI_MR_AR_CTRY_BUSRANGE_MAPPING;


/* ========== 步骤 1: 建表 ========== */
CREATE TABLE DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING (
      RULEINNERID     NUMBER(19)      NOT NULL
    , ID              NUMBER(10)      NOT NULL
    , VALID_FR        VARCHAR2(255)
    , VALID_TO        VARCHAR2(255)
    , LOAD_DT         DATE            DEFAULT SYSDATE
    , BATCH_ID        VARCHAR2(255)
    , LOGIC_NAME      VARCHAR2(255)
    , COUNTRY_CODE    VARCHAR2(255)
    , COUNTRY_NAME    VARCHAR2(255)
    , BUS_RANGE_CODE  VARCHAR2(255)
    , BUS_RANGE_NAME  VARCHAR2(255)
    , UNIQUE_KEY      VARCHAR2(1024)  NOT NULL
    , CONSTRAINT PK_DIM_RULE_AR_CNTRY_BUSR_MAP PRIMARY KEY (RULEINNERID)
);


/* ========== 步骤 2: 表注释与列注释 ========== */
COMMENT ON TABLE DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING IS '应收国家业务范围映射规则表';

COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.RULEINNERID    IS '规则内部主键';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.ID             IS '主键';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.VALID_FR       IS '有效期起';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.VALID_TO       IS '有效期止';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.LOAD_DT        IS '加载时间';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.BATCH_ID       IS '匹配顺序';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.LOGIC_NAME     IS '逻辑处理';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.COUNTRY_CODE   IS '国家编码';
COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.COUNTRY_NAME   IS '国家名称';
