COMMENT ON COLUMN DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING.UNIQUE_KEY     IS '唯一键(用于匹配去重)';


/* ========== 步骤 3: 索引 (按业务匹配路径补充, 不需要可删除) ========== */
CREATE INDEX IDX_AR_CNTRY_BUSRNG_1 ON DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING (COUNTRY_CODE);
CREATE INDEX IDX_AR_CNTRY_BUSRNG_2 ON DIM_RULE_FI_MR_AR_COUNTRY_BUSRANGE_MAPPING (BUS_RANGE_CODE);
