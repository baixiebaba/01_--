CREATE OR REPLACE PROCEDURE CPM_SP_M2S_ARP_TOV_M_PHASE2(
    P_SCENARIO  IN VARCHAR2
  , P_PERIODO   IN VARCHAR2
  , P_AZIENDA   IN VARCHAR2
  , P_BG        IN VARCHAR2
  , SESSION_USER IN VARCHAR2
) AS
  /**************************************************************************
  最后更新时间：20261014
  名称：CPM_SP_M2S_ARP_TOV_M_PHASE2
  用途：装载应收周转计算汇总表
  源表：AW_MR9_ARPM02_000001、DWD_FI_MR_AR_IMOCC_MI、AW_MR9_REVM01_000001、AW_MR8_CPRS01_000001
  目标表：AW_MR8_ARPS01_000001
  逻辑文档：经分二期-应收-数据模型详细设计文档.xlsx
  目标Sheet：DWS-ARPS01-周转计算汇总表
  特殊逻辑：四个来源统一为目标字段后按目标粒度汇总；收入和调整来源分别拆分为
            ZAMOUNT、ZAMOUNT_L2；收入来源按节点规则计算集团归属范围。
            ARPM02事业部优先按Doris利润中心映射表BATCH_ID=2命中，使用过程输入事业部P_BG；未命中时按账套事业部映射表取COD_BG。

  手工执行：CALL CPM_SP_M2S_ARP_TOV_M_PHASE2('2025ACT','06','6700','BG001','USER');
  **************************************************************************/
  V_SCENARIO      VARCHAR2(30);
  V_PERIODO      VARCHAR2(30);
  V_YEARMONTH     VARCHAR2(10);
  V_LAST_DAY      DATE;
  V_AZIENDA       VARCHAR2(4000);
  V_SESSION_ID    NUMBER;
  V_ERROR_COD     NUMBER;
  V_ERROR_MSG     VARCHAR2(4000);
BEGIN

  V_SESSION_ID := SYS_CONTEXT('USERENV', 'SESSIONID');

  /* 删除本session的参数公司，防止同一个窗口跑中止后接着跑时公司范围扩大 */
  DELETE FROM SESSION_AZIENDA_LIST
   WHERE SESSION_ID = V_SESSION_ID;
  DELETE FROM SESSION_V_REF_AZIENDA
   WHERE SESSION_ID = V_SESSION_ID;

  INSERT INTO SESSION_V_REF_AZIENDA(SESSION_ID, HIE, NODE, ELEM)
  SELECT V_SESSION_ID, HIE, NODE, ELEM
    FROM TGK_FIMA_HISENSE.V_REF_AZIENDA;

  /* 时间参数初始化 */
  V_SCENARIO := P_SCENARIO;
  V_PERIODO := LPAD(P_PERIODO, 2, '0');
  V_YEARMONTH := SUBSTR(V_SCENARIO, 1, 4) || V_PERIODO;
  V_LAST_DAY := LAST_DAY(TO_DATE(V_YEARMONTH || '01', 'YYYYMMDD'));

  /* 组织参数初始化：只抽取有效且未锁定的应收公司 */
  INSERT INTO SESSION_AZIENDA_LIST(SESSION_ID, ELEM)
  SELECT DISTINCT V_SESSION_ID
       , ELEM
    FROM SESSION_V_REF_AZIENDA
   WHERE HIE = '10'
     AND (
           INSTR(',' || P_AZIENDA || ',', ',' || ELEM || ',') > 0
        OR INSTR(',' || P_AZIENDA || ',', ',' || NODE || ',') > 0
        OR P_AZIENDA = 'ALL'
     )
     /* 仅抽取输入事业部对应的公司范围 */
     AND ELEM IN (
           SELECT COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_ATSMAP_000001
            WHERE COD_BG = P_BG
     )
     AND ELEM IN (
           SELECT COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001
            WHERE ARP_FLAG = 'Y'
              AND VALID_FR <= V_YEARMONTH
              AND NVL(VALID_TO, '999999') >= V_YEARMONTH
              AND COD_CONTO = 'ZAW_D2M_IN'
     )
     AND ELEM NOT IN (
           SELECT COD_AZIENDA
             FROM TGK_FIMA_HISENSE.AW_RUL_DWMCRS_000001 T
            WHERE T.ARP_FLAG = 'Y'
              AND T.COD_SCENARIO = V_SCENARIO
              AND T.COD_PERIODO = V_PERIODO
              AND T.COD_CONTO = 'ZAW_D2M_LOCK'
     );

  /* 获取所有跑的公司列表，供日志插入使用 */
  SELECT LISTAGG(ELEM, ',') WITHIN GROUP (ORDER BY ELEM)
    INTO V_AZIENDA
    FROM (
      SELECT DISTINCT ELEM
        FROM SESSION_AZIENDA_LIST
       WHERE SESSION_ID = V_SESSION_ID
    );

  INSERT INTO ZTAB_CPM_LOG(
      CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA
  ) VALUES (
      'CPM_SP_M2S_ARP_TOV_M_PHASE2', 'BEGIN 开始执行', SYSDATE, SESSION_USER,
      V_SCENARIO, V_PERIODO, V_AZIENDA
  );
  COMMIT;

  /* 删除当前批次本过程生成的数据，保证增量重跑不产生重复数据 */
  DELETE FROM AW_MR8_ARPS01_000001
   WHERE COD_SCENARIO = V_SCENARIO
     AND COD_PERIODO = V_PERIODO
     AND COD_AZIENDA IN (
           SELECT ELEM
             FROM SESSION_AZIENDA_LIST
            WHERE SESSION_ID = V_SESSION_ID
     )
     AND PROVENIENZA = 'CPM_SP_M2S_ARP_TOV_M_PHASE2';

  INSERT INTO ZTAB_CPM_LOG(
      CPM, STEP, EXECTIME, CREATEBY, COD_SCENARIO, COD_PERIODO, COD_AZIENDA
  ) VALUES (
      'CPM_SP_M2S_ARP_TOV_M_PHASE2', '当前批次删除完成', SYSDATE, SESSION_USER,
      V_SCENARIO, V_PERIODO, V_AZIENDA
  );

  /* ============================================================================
     目标表装载：四个来源先按统一字段接口UNION ALL，再按目标粒度SUM。
     ARPM02按ME/MB账龄标识分别形成ZAMOUNT/ZAMOUNT_L2；收入和调整各复制两类。
     ============================================================================ */
  INSERT INTO AW_MR8_ARPS01_000001(
      COD_SCENARIO
    , COD_PERIODO
    , D_BG
    , COD_AZIENDA
    , COD_CONTO
    , COD_CATEGORIA
    , GRP_SCOPE
    , CUST_CODE
    , CUST_NAME
    , CUST_HEAD_CODE
    , CUST_HEAD_NAME
    , CUST_BRANCH_CODE
    , CUST_BRANCH_NAME
    , COD_AZI_CTP
    , COUNTRY_CODE
    , COUNTRY_NAME
    , NATURE_L2_NAME
    , D_ADJ_TYPE
    , D_CHANNEL
    , D_TOV_CHAN
    , D_CC_CUSTGRP
    , D_ONOFFLINE
    , COD_DEST2
    , COD_DEST3
    , D_SALE_DEPT
    , COD_VALUTA
    , AR_AMT
    , REV_AMT
    , F1_ODUE_AMT
    , F2_EPAY_AMT
    , F3_ECR_AMT
    , F4_UREB_AMT
    , F5_UFEE_AMT
    , F6_INVSM_AMT
    , F7_GSUB_AMT
    , F8_ADJ_AMT
    , PROVENIENZA
  )
  WITH
  /* 利润中心映射：仓库实际规则表为Doris对象，BATCH_ID=2按公司+原利润中心匹配。 */
  PROFIT_CENTER_RULE AS (
    SELECT COMPANY_CODE
         , NULLIF(LTRIM(TRIM(SRC_PROFITCENTER_CODE), '0'), '') AS SRC_PROFITCENTER_CODE
         , MAX(PROFITCENTER_CODE) AS PROFITCENTER_CODE
      FROM DIM.DIM_RULE_FI_MR_AR_PROFIT_MAPPING
     WHERE BATCH_ID = 2
     GROUP BY COMPANY_CODE
            , NULLIF(LTRIM(TRIM(SRC_PROFITCENTER_CODE), '0'), '')
  ),
  /* 账套事业部映射：利润中心未命中时按公司取COD_BG。 */
  ATS_BG_MAP AS (
    SELECT COD_AZIENDA
         , MAX(COD_BG) AS COD_BG
      FROM TGK_FIMA_HISENSE.AW_RUL_ATSMAP_000001
     GROUP BY COD_AZIENDA
  ),
  /* 商冷客户群：按公司+客商匹配实际维表，未匹配统一为ZZZZ。 */
  CUSTOMER_CC_MAP AS (
    SELECT NULLIF(LTRIM(TRIM(D.CUST_SAP_CODE), '0'), '') AS CUST_SAP_CODE
         , NULLIF(LTRIM(TRIM(D.COMPANY_CODE_MDG), '0'), '') AS COMPANY_CODE_MDG
         , MAX(D.CRG_CUST_GROUP_CODE) AS CRG_CUST_GROUP_CODE
      FROM DW.DIM_CUSTOMER_COMPANY_INFO_DD D
     WHERE D.CRG_CUST_GROUP_CODE IS NOT NULL
     GROUP BY NULLIF(LTRIM(TRIM(D.CUST_SAP_CODE), '0'), '')
            , NULLIF(LTRIM(TRIM(D.COMPANY_CODE_MDG), '0'), '')
  ),
  /* 周转分析渠道：BATCH_ID=1按公司+客商，BATCH_ID=2按公司+三级分类。 */
  TOV_CHANNEL_RULE_1 AS (
    SELECT COMPANY_CODE
         , NULLIF(LTRIM(TRIM(CUST_CODE), '0'), '') AS CUST_CODE
         , MAX(TOV_CHANNEL_CODE) AS TOV_CHANNEL_CODE
      FROM DIM.DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING
     WHERE BATCH_ID = 1
     GROUP BY COMPANY_CODE, NULLIF(LTRIM(TRIM(CUST_CODE), '0'), '')
  ),
  TOV_CHANNEL_RULE_2 AS (
    SELECT COMPANY_CODE
         , CHANNEL_L3_CODE
         , MAX(TOV_CHANNEL_CODE) AS TOV_CHANNEL_CODE
      FROM DIM.DIM_RULE_FI_MR_AR_TOV_CHANNEL_MAPPING
     WHERE BATCH_ID = 2
     GROUP BY COMPANY_CODE, CHANNEL_L3_CODE
  ),
  /* ARPM02：按ME账龄标识生成ZAMOUNT，按MB账龄标识生成ZAMOUNT_L2。 */
  ARPM02_FACT AS (
    SELECT A.COD_SCENARIO
         , A.COD_PERIODO
         , CASE WHEN PM.SRC_PROFITCENTER_CODE IS NOT NULL THEN P_BG
                ELSE NVL(AB.COD_BG, 'ZZZZ')
           END AS D_BG
         , A.COD_AZIENDA
         , A.COD_CONTO
         , 'ZAMOUNT' AS COD_CATEGORIA
         , A.GRP_SCOPE
         , A.CUST_CODE
         , A.CUST_NAME
         , A.CUST_HEAD_CODE
         , A.CUST_HEAD_NAME
         , A.CUST_BRANCH_CODE
         , A.CUST_BRANCH_NAME
         , A.COD_AZI_CTP
         , A.COUNTRY_CODE
         , A.COUNTRY_NAME
         , A.NATURE_L2_NAME
         , A.D_ADJ_TYPE
         , A.D_CHANNEL
         , NVL(A.D_TOV_CHAN, NVL(T1.TOV_CHANNEL_CODE, NVL(T2.TOV_CHANNEL_CODE, 'ZZZZ'))) AS D_TOV_CHAN
         , NVL(CC.CRG_CUST_GROUP_CODE, 'ZZZZ') AS D_CC_CUSTGRP
         , A.D_ONOFFLINE
         , NVL(PM.PROFITCENTER_CODE, A.COD_DEST2) AS COD_DEST2
         , A.COD_DEST3
         , A.D_SALE_DEPT
         , NVL(A.COD_VALUTA, 'CNY') AS COD_VALUTA
         , NVL(A.BCY_ADJ_INCL_0_AMT, 0) AS AR_AMT
         , 0 AS REV_AMT
         , NVL(A.F1_ODUE_AMT, 0) AS F1_ODUE_AMT
         , NVL(A.F2_EPAY_AMT, 0) AS F2_EPAY_AMT
         , NVL(A.F3_ECR_AMT, 0) AS F3_ECR_AMT
         , NVL(A.F4_UREB_AMT, 0) AS F4_UREB_AMT
         , NVL(A.F5_UFEE_AMT, 0) AS F5_UFEE_AMT
         , NVL(A.F6_INVSM_AMT, 0) AS F6_INVSM_AMT
         , 0 AS F7_GSUB_AMT
         , 0 AS F8_ADJ_AMT
      FROM (
        SELECT *
          FROM AW_MR9_ARPM02_000001
         WHERE COD_SCENARIO = V_SCENARIO
           AND COD_PERIODO = V_PERIODO
           AND COD_AZIENDA IN (SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID)
           AND ME_AGE_FLAG IN ('AR', 'CA', 'A10')
      ) A
      LEFT JOIN PROFIT_CENTER_RULE PM
        ON PM.COMPANY_CODE = A.COD_AZIENDA
       AND PM.SRC_PROFITCENTER_CODE = NULLIF(LTRIM(TRIM(A.COD_DEST2), '0'), '')
      LEFT JOIN ATS_BG_MAP AB
        ON AB.COD_AZIENDA = A.COD_AZIENDA
      LEFT JOIN CUSTOMER_CC_MAP CC
        ON CC.COMPANY_CODE_MDG = NULLIF(LTRIM(TRIM(A.COD_AZIENDA), '0'), '')
       AND CC.CUST_SAP_CODE = NULLIF(LTRIM(TRIM(A.CUST_CODE), '0'), '')
      LEFT JOIN TOV_CHANNEL_RULE_1 T1
        ON T1.COMPANY_CODE = A.COD_AZIENDA
       AND T1.CUST_CODE = NULLIF(LTRIM(TRIM(A.CUST_CODE), '0'), '')
      LEFT JOIN TOV_CHANNEL_RULE_2 T2
        ON T2.COMPANY_CODE = A.COD_AZIENDA
       AND T2.CHANNEL_L3_CODE = A.D_CHANNEL

    UNION ALL

    SELECT A.COD_SCENARIO
         , A.COD_PERIODO
         , CASE WHEN PM.SRC_PROFITCENTER_CODE IS NOT NULL THEN P_BG
                ELSE NVL(AB.COD_BG, 'ZZZZ')
           END AS D_BG
         , A.COD_AZIENDA
         , A.COD_CONTO
         , 'ZAMOUNT_L2' AS COD_CATEGORIA
         , A.GRP_SCOPE AS GRP_SCOPE
         , A.CUST_CODE AS CUST_CODE
         , A.CUST_NAME AS CUST_NAME
         , A.CUST_HEAD_CODE AS CUST_HEAD_CODE
         , A.CUST_HEAD_NAME AS CUST_HEAD_NAME
         , A.CUST_BRANCH_CODE AS CUST_BRANCH_CODE
         , A.CUST_BRANCH_NAME AS CUST_BRANCH_NAME
         , A.COD_AZI_CTP AS COD_AZI_CTP
         , A.COUNTRY_CODE AS COUNTRY_CODE
         , A.COUNTRY_NAME AS COUNTRY_NAME
         , A.NATURE_L2_NAME AS NATURE_L2_NAME
         , A.D_ADJ_TYPE AS D_ADJ_TYPE
         , A.D_CHANNEL AS D_CHANNEL
         , NVL(A.D_TOV_CHAN, NVL(T1.TOV_CHANNEL_CODE, NVL(T2.TOV_CHANNEL_CODE, 'ZZZZ'))) AS D_TOV_CHAN
         , NVL(CC.CRG_CUST_GROUP_CODE, 'ZZZZ') AS D_CC_CUSTGRP
         , A.D_ONOFFLINE AS D_ONOFFLINE
         , NVL(PM.PROFITCENTER_CODE, A.COD_DEST2) AS COD_DEST2
         , A.COD_DEST3 AS COD_DEST3
         , A.D_SALE_DEPT AS D_SALE_DEPT
         , NVL(A.COD_VALUTA, 'CNY') AS COD_VALUTA
         , NVL(A.BCY_ADJ_INCL_0_AMT, 0) AS AR_AMT
         , 0 AS REV_AMT
         , NVL(A.F1_ODUE_AMT, 0) AS F1_ODUE_AMT
         , NVL(A.F2_EPAY_AMT, 0) AS F2_EPAY_AMT
         , NVL(A.F3_ECR_AMT, 0) AS F3_ECR_AMT
         , NVL(A.F4_UREB_AMT, 0) AS F4_UREB_AMT
         , NVL(A.F5_UFEE_AMT, 0) AS F5_UFEE_AMT
         , NVL(A.F6_INVSM_AMT, 0) AS F6_INVSM_AMT
         , 0 AS F7_GSUB_AMT
         , 0 AS F8_ADJ_AMT
      FROM (
        SELECT *
          FROM AW_MR9_ARPM02_000001
         WHERE COD_SCENARIO = V_SCENARIO
           AND COD_PERIODO = V_PERIODO
           AND COD_AZIENDA IN (SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID)
           AND MB_AGE_FLAG IN ('AR', 'CA', 'A10')
      ) A
      LEFT JOIN PROFIT_CENTER_RULE PM
        ON PM.COMPANY_CODE = A.COD_AZIENDA
       AND PM.SRC_PROFITCENTER_CODE = NULLIF(LTRIM(TRIM(A.COD_DEST2), '0'), '')
      LEFT JOIN ATS_BG_MAP AB
        ON AB.COD_AZIENDA = A.COD_AZIENDA
      LEFT JOIN CUSTOMER_CC_MAP CC
        ON CC.COMPANY_CODE_MDG = NULLIF(LTRIM(TRIM(A.COD_AZIENDA), '0'), '')
       AND CC.CUST_SAP_CODE = NULLIF(LTRIM(TRIM(A.CUST_CODE), '0'), '')
      LEFT JOIN TOV_CHANNEL_RULE_1 T1
        ON T1.COMPANY_CODE = A.COD_AZIENDA
       AND T1.CUST_CODE = NULLIF(LTRIM(TRIM(A.CUST_CODE), '0'), '')
      LEFT JOIN TOV_CHANNEL_RULE_2 T2
        ON T2.COMPANY_CODE = A.COD_AZIENDA
       AND T2.CHANNEL_L3_CODE = A.D_CHANNEL
  ),
  /* 国际营销占用：文档仅明确来源表和IMOCC_CNY_AMT；其余字段沿用同名字段 */
  IMOCC_FACT AS (
    SELECT I.COD_SCENARIO
         , V_PERIODO AS COD_PERIODO
         , NULL AS D_BG
         , I.COMPANY_CODE AS COD_AZIENDA
         , I.ACCT_CODE AS COD_CONTO
         , C.COD_CATEGORIA
         , I.GRP_SCOPE
         , I.CUST_CODE
         , I.CUST_NAME
         , I.CUST_HEAD_CODE
         , I.CUST_HEAD_NAME
         , I.CUST_BRANCH_CODE
         , I.CUST_BRANCH_NAME
         , I.CP_COMPANY_CODE AS COD_AZI_CTP
         , I.COUNTRY_CODE
         , I.COUNTRY_NAME
         , I.NATURE_L2_NAME
         , NULL AS D_ADJ_TYPE
         , 'ZZZZ' AS D_CHANNEL
         , 'ZZZZ' AS D_TOV_CHAN
         , 'ZZZZ' AS D_CC_CUSTGRP
         , 'ZZZZ' AS D_ONOFFLINE
         , I.PROFITCENTER_CODE AS COD_DEST2
         , I.BUS_RANGE_CODE AS COD_DEST3
         , I.MARKETING_DEPT_CODE AS D_SALE_DEPT
         , 'CNY' AS COD_VALUTA
         , NVL(I.IMOCC_CNY_AMT, 0) AS AR_AMT
         , 0 AS REV_AMT
         , 0 AS F1_ODUE_AMT
         , 0 AS F2_EPAY_AMT
         , 0 AS F3_ECR_AMT
         , 0 AS F4_UREB_AMT
         , 0 AS F5_UFEE_AMT
         , 0 AS F6_INVSM_AMT
         , 0 AS F7_GSUB_AMT
         , 0 AS F8_ADJ_AMT
      FROM (
        SELECT *
          FROM DWD_FI_MR_AR_IMOCC_MI
         WHERE DT_MONTH = V_YEARMONTH
           AND COMPANY_CODE IN (SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID)
      ) I
      CROSS JOIN (
        SELECT 'ZAMOUNT' AS COD_CATEGORIA FROM DUAL
        UNION ALL
        SELECT 'ZAMOUNT_L2' AS COD_CATEGORIA FROM DUAL
      ) C
  ),
  /* 收入来源维度：沿用D2M的场景期间节点匹配及日立公司判断。 */
  NODE_MAP AS (
    SELECT N.COD_SCENARIO
         , N.COD_PERIODO
         , N.ELEM
         , N.NODE
         , N.NODES
         , CASE WHEN H.ELEM IS NOT NULL THEN 1 ELSE 0 END AS IS_HITACHI
         , CASE WHEN H.ELEM IS NOT NULL THEN NVL(N.NODES, N.NODE)
                ELSE N.NODE
           END AS SELF_NODE
         , N.HQ
      FROM TGK_GB_HISENSE.V_APAR_ELEM_NODE_TAB N
      LEFT JOIN (
        SELECT DISTINCT R.ELEM
          FROM TGK_GB_HISENSE.V_REF_AZIENDA_TV R
         WHERE R.COD_SCENARIO = V_SCENARIO
           AND R.COD_PERIODO = V_PERIODO
           AND R.HIE = '30'
           AND R.NODE = '1730'
      ) H ON H.ELEM = N.ELEM
     WHERE N.COD_SCENARIO = V_SCENARIO
       AND N.COD_PERIODO = V_PERIODO
  ),
  /* 单体销售明细：收入金额按设计口径装载，并拆两类。 */
  REV_FACT AS (
    SELECT R.COD_SCENARIO
         , R.COD_PERIODO
         , CASE WHEN PM_REV.SRC_PROFITCENTER_CODE IS NOT NULL THEN P_BG
                ELSE NVL(AB_REV.COD_BG, 'ZZZZ')
           END AS D_BG
         , R.COD_AZIENDA
         , R.COD_CONTO
         , C.COD_CATEGORIA
         , CASE
               WHEN CUR_NODE.SELF_NODE = CASE WHEN CUR_NODE.IS_HITACHI = 1 THEN NVL(CTP_NODE.NODES, CTP_NODE.NODE)
                                                ELSE CTP_NODE.NODE
                                           END
                AND CUR_NODE.HQ = CTP_NODE.HQ THEN 'SUB-子公司'
               WHEN CUR_NODE.HQ = CTP_NODE.HQ THEN 'GIN-集团内'
               ELSE 'GEX-集团外'
           END AS GRP_SCOPE
         , R.CUST_CODE
         , R.CUST_NAME
         , R.CUST_HEAD_CODE
         , R.CUST_HEAD_NAME
         , R.CUST_BRANCH_CODE
         , R.CUST_BRANCH_NAME
         , R.COD_AZI_CTP
         /* TODO: 仓库未找到DEST3_GERARCHIA_FLAT定义及其业务范围关联字段；
            保留收入表已落地国家字段，待对象定义补齐后套用Excel的NVL层级回退。 */
         , R.COUNTRY_CODE
         , R.COUNTRY_NAME
         , R.NATURE_L2_NAME
         , R.D_ADJ_TYPE
         , R.D_CHANNEL
         , NVL(R.D_TOV_CHAN, NVL(TOV1_REV.TOV_CHANNEL_CODE, NVL(TOV2_REV.TOV_CHANNEL_CODE, 'ZZZZ'))) AS D_TOV_CHAN
         , NVL(CC_REV.CRG_CUST_GROUP_CODE, 'ZZZZ') AS D_CC_CUSTGRP
         , R.D_ONOFFLINE
         , NVL(PM_REV.PROFITCENTER_CODE, R.COD_DEST2) AS COD_DEST2
         , R.COD_DEST3
         , R.D_SALE_DEPT
         , 'CNY' AS COD_VALUTA
         , 0 AS AR_AMT
         , NVL(R.ORG_REV, 0) - NVL(R.POLICY_AMT, 0) - NVL(R.MAP_DIS1, 0)
             - NVL(R.MAP_DIS3, 0) - NVL(R.MAP_DIS4, 0) - NVL(R.MAP_DIS30, 0)
             - NVL(R.MAP_DIS34, 0) AS REV_AMT
         , 0 AS F1_ODUE_AMT
         , 0 AS F2_EPAY_AMT
         , 0 AS F3_ECR_AMT
         , 0 AS F4_UREB_AMT
         , 0 AS F5_UFEE_AMT
         , 0 AS F6_INVSM_AMT
         , 0 AS F7_GSUB_AMT
         , 0 AS F8_ADJ_AMT
      FROM (
        SELECT *
          FROM AW_MR9_REVM01_000001
         WHERE COD_SCENARIO = V_SCENARIO
           AND COD_PERIODO = V_PERIODO
           AND COD_AZIENDA IN (SELECT ELEM FROM SESSION_AZIENDA_LIST WHERE SESSION_ID = V_SESSION_ID)
           AND SRC_DETAIL <> 'BSEG_FLJC'
           AND COD_CATEGORIA NOT IN ('GA00_PA_IN', 'GA00_PA_OUT')
           AND D_ADJ_TYPE NOT IN ('REV_01_210', 'REV_01_212')
      ) R
      LEFT JOIN NODE_MAP CUR_NODE
        ON CUR_NODE.COD_SCENARIO = R.COD_SCENARIO
       AND CUR_NODE.COD_PERIODO = R.COD_PERIODO
       AND CUR_NODE.ELEM = R.COD_AZIENDA
      LEFT JOIN NODE_MAP CTP_NODE
        ON CTP_NODE.COD_SCENARIO = R.COD_SCENARIO
       AND CTP_NODE.COD_PERIODO = R.COD_PERIODO
       AND CTP_NODE.ELEM = R.COD_AZI_CTP
      LEFT JOIN PROFIT_CENTER_RULE PM_REV
        ON PM_REV.COMPANY_CODE = R.COD_AZIENDA
       AND PM_REV.SRC_PROFITCENTER_CODE = NULLIF(LTRIM(TRIM(R.COD_DEST2), '0'), '')
      LEFT JOIN ATS_BG_MAP AB_REV
        ON AB_REV.COD_AZIENDA = R.COD_AZIENDA
      LEFT JOIN CUSTOMER_CC_MAP CC_REV
        ON CC_REV.COMPANY_CODE_MDG = NULLIF(LTRIM(TRIM(R.COD_AZIENDA), '0'), '')
       AND CC_REV.CUST_SAP_CODE = NULLIF(LTRIM(TRIM(R.CUST_CODE), '0'), '')
      LEFT JOIN TOV_CHANNEL_RULE_1 TOV1_REV
        ON TOV1_REV.COMPANY_CODE = R.COD_AZIENDA
       AND TOV1_REV.CUST_CODE = NULLIF(LTRIM(TRIM(R.CUST_CODE), '0'), '')
      LEFT JOIN TOV_CHANNEL_RULE_2 TOV2_REV
        ON TOV2_REV.COMPANY_CODE = R.COD_AZIENDA
       AND TOV2_REV.CHANNEL_L3_CODE = R.D_CHANNEL
      CROSS JOIN (
        SELECT 'ZAMOUNT' AS COD_CATEGORIA FROM DUAL
        UNION ALL
        SELECT 'ZAMOUNT_L2' AS COD_CATEGORIA FROM DUAL
      ) C
     WHERE CASE
             WHEN CUR_NODE.SELF_NODE = CASE WHEN CUR_NODE.IS_HITACHI = 1 THEN NVL(CTP_NODE.NODES, CTP_NODE.NODE)
                                            ELSE CTP_NODE.NODE
                                       END
              AND CUR_NODE.HQ = CTP_NODE.HQ THEN 'SUB-子公司'
             WHEN CUR_NODE.HQ = CTP_NODE.HQ THEN 'GIN-集团内'
             ELSE 'GEX-集团外'
           END = 'GEX'
  ),
  /* 商显收入调整：仅取ZBIDADJ、科目S600100、公司2080和输入事业部，拆两类 */
  CPRS_FACT AS (
    SELECT P.COD_SCENARIO
         , V_PERIODO AS COD_PERIODO
         , P.D_BG
         , P.COD_AZIENDA
         , P.COD_CONTO
         , C.COD_CATEGORIA
         , NULL AS GRP_SCOPE
         , NULL AS CUST_CODE
         , NULL AS CUST_NAME
         , NULL AS CUST_HEAD_CODE
         , NULL AS CUST_HEAD_NAME
         , NULL AS CUST_BRANCH_CODE
         , NULL AS CUST_BRANCH_NAME
         , NULL AS COD_AZI_CTP
         , NULL AS COUNTRY_CODE
         , NULL AS COUNTRY_NAME
         , NULL AS NATURE_L2_NAME
         , NULL AS D_ADJ_TYPE
         , NULL AS D_CHANNEL
         , 'ZZZZ' AS D_TOV_CHAN
         , 'ZZZZ' AS D_CC_CUSTGRP
         , NULL AS D_ONOFFLINE
         , NULL AS COD_DEST2
         , NULL AS COD_DEST3
         , NULL AS D_SALE_DEPT
         , 'CNY' AS COD_VALUTA
         , 0 AS AR_AMT
         , 0 AS REV_AMT
         , 0 AS F1_ODUE_AMT
         , 0 AS F2_EPAY_AMT
         , 0 AS F3_ECR_AMT
         , 0 AS F4_UREB_AMT
         , 0 AS F5_UFEE_AMT
         , 0 AS F6_INVSM_AMT
         , 0 AS F7_GSUB_AMT
         , NVL(P.BCY_AMT, 0) AS F8_ADJ_AMT
      FROM (
        SELECT *
          FROM AW_MR8_CPRS01_000001
         WHERE COD_SCENARIO = V_SCENARIO
           AND D_BG = P_BG
           AND COD_AZIENDA = '2080'
           AND COD_CONTO = 'S600100'
           AND COD_CATEGORIA = 'ZBIDADJ'
      ) P
      CROSS JOIN (
        SELECT 'ZAMOUNT' AS COD_CATEGORIA FROM DUAL
        UNION ALL
        SELECT 'ZAMOUNT_L2' AS COD_CATEGORIA FROM DUAL
      ) C
  ),
  /* 四个来源的统一窄事实接口 */
  SOURCE_FACT AS (
    SELECT * FROM ARPM02_FACT
    UNION ALL
    SELECT * FROM IMOCC_FACT
    UNION ALL
    SELECT * FROM REV_FACT
    UNION ALL
    SELECT * FROM CPRS_FACT
  ),
  /* 四个来源统一默认值已在来源层处理，最终层仅兜底处理空值。 */
  NORMALIZED_FACT AS (
    SELECT S.COD_SCENARIO
         , S.COD_PERIODO
         , NVL(S.D_BG, 'ZZZZ') AS D_BG
         , S.COD_AZIENDA
         , S.COD_CONTO
         , S.COD_CATEGORIA
         , S.GRP_SCOPE
         , S.CUST_CODE
         , S.CUST_NAME
         , S.CUST_HEAD_CODE
         , S.CUST_HEAD_NAME
         , S.CUST_BRANCH_CODE
         , S.CUST_BRANCH_NAME
         , S.COD_AZI_CTP
         , S.COUNTRY_CODE
         , S.COUNTRY_NAME
         , S.NATURE_L2_NAME
         , S.D_ADJ_TYPE
         , S.D_CHANNEL
         , NVL(S.D_TOV_CHAN, 'ZZZZ') AS D_TOV_CHAN
         , NVL(S.D_CC_CUSTGRP, 'ZZZZ') AS D_CC_CUSTGRP
         , S.D_ONOFFLINE
         , S.COD_DEST2
         , S.COD_DEST3
         , S.D_SALE_DEPT
         , S.COD_VALUTA
         , S.AR_AMT
         , S.REV_AMT
         , S.F1_ODUE_AMT
         , S.F2_EPAY_AMT
         , S.F3_ECR_AMT
         , S.F4_UREB_AMT
         , S.F5_UFEE_AMT
         , S.F6_INVSM_AMT
         , S.F7_GSUB_AMT
         , S.F8_ADJ_AMT
      FROM SOURCE_FACT S
  )
  SELECT COD_SCENARIO
       , COD_PERIODO
       , D_BG
       , COD_AZIENDA
       , COD_CONTO
       , COD_CATEGORIA
       , GRP_SCOPE
       , CUST_CODE
       , CUST_NAME
       , CUST_HEAD_CODE
       , CUST_HEAD_NAME
       , CUST_BRANCH_CODE
       , CUST_BRANCH_NAME
       , COD_AZI_CTP
       , COUNTRY_CODE
       , COUNTRY_NAME
       , NATURE_L2_NAME
       , D_ADJ_TYPE
       , D_CHANNEL
       , D_TOV_CHAN
       , D_CC_CUSTGRP
       , D_ONOFFLINE
       , COD_DEST2
       , COD_DEST3
       , D_SALE_DEPT
       , COD_VALUTA
       , SUM(AR_AMT)
       , SUM(REV_AMT)
       , SUM(F1_ODUE_AMT)
       , SUM(F2_EPAY_AMT)
       , SUM(F3_ECR_AMT)
       , SUM(F4_UREB_AMT)
       , SUM(F5_UFEE_AMT)
       , SUM(F6_INVSM_AMT)
       , SUM(F7_GSUB_AMT)
       , SUM(F8_ADJ_AMT)
       , 'CPM_SP_M2S_ARP_TOV_M_PHASE2'
    FROM NORMALIZED_FACT
   GROUP BY COD_SCENARIO, COD_PERIODO, D_BG, COD_AZIENDA, COD_CONTO, COD_CATEGORIA
          , GRP_SCOPE, CUST_CODE, CUST_NAME, CUST_HEAD_CODE, CUST_HEAD_NAME
          , CUST_BRANCH_CODE, CUST_BRANCH_NAME, COD_AZI_CTP, COUNTRY_CODE, COUNTRY_NAME
          , NATURE_L2_NAME, D_ADJ_TYPE, D_CHANNEL, D_TOV_CHAN, D_CC_CUSTGRP, D_ONOFFLINE, COD_DEST2, COD_DEST3
          , D_SALE_DEPT, COD_VALUTA;

